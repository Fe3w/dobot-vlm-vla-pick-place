#!/usr/bin/env python3
"""Summary of Dobot pick-and-place runs (reads runs.jsonl; plain Python, run it in a terminal).

    python3 src/dobot_run_report.py              # the latest test list (or all runs if none)
    python3 src/dobot_run_report.py --all        # every run recorded
    python3 src/dobot_run_report.py --last 10    # the last 10 runs
    python3 src/dobot_run_report.py --md out.md  # also write the report as Markdown

Outcome per run:
    passed        placed, and the result check agrees with the task
    check failed  placed, but somewhere the task did not ask for (or something else was moved)
    failed        stopped before placing (stage + reason)
    stopped       Stop pressed
"""
import argparse
import collections
import json
import os
import sys

HOME = os.path.expanduser("~")
# >>> dobot-settings (generated by tools/patch_paths.py; same block in every script)
def _dobot_settings():
    """Folders and settings: environment variables, else the repo's .env, else ~/.config/dobot-pnp/.env."""
    import os
    f = globals().get("__file__")
    src = os.path.dirname(os.path.abspath(f)) if f else ""
    vals = {}
    for c in (os.environ.get("DOBOT_ENV_FILE"), src and os.path.join(src, "..", ".env"),
              os.path.expanduser("~/.config/dobot-pnp/.env")):
        if not c or not os.path.isfile(c):
            continue
        with open(c) as fh:
            for line in fh:
                line = line.strip()
                if line.startswith("export "):
                    line = line[7:].strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                v = v.strip()
                if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
                    v = v[1:-1]
                else:
                    v = v.split(" #")[0].strip()
                vals[k.strip()] = v
        vals.setdefault("DOBOT_HOME", os.path.dirname(os.path.abspath(c)))
        break
    vals.update({k: v for k, v in os.environ.items() if k.startswith(("DOBOT_", "VLM_"))})
    home = os.path.expanduser(vals.get("DOBOT_HOME") or (os.path.dirname(src) if src else "~/dobot-vlm-pick-place"))

    def path(key, default):
        p = os.path.expanduser(vals.get(key) or default)
        return os.path.normpath(p if os.path.isabs(p) else os.path.join(home, p))
    vals["DOBOT_HOME"] = home
    vals["DOBOT_SRC"] = path("DOBOT_SRC", src or "src")
    vals["DOBOT_ASSETS"] = path("DOBOT_ASSETS", "assets")
    vals["DOBOT_DATA"] = path("DOBOT_DATA", ".")
    return vals


_DOBOT_ENV = _dobot_settings()
_DOBOT_SRC, _DOBOT_ASSETS, _DOBOT_DATA = _DOBOT_ENV["DOBOT_SRC"], _DOBOT_ENV["DOBOT_ASSETS"], _DOBOT_ENV["DOBOT_DATA"]
# <<< dobot-settings

CAPTURE_ROOT = os.path.join(_DOBOT_DATA, "output", "isaac_capture")


def load(path):
    runs = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                try:
                    runs.append(json.loads(line))
                except ValueError:
                    pass
    return runs


def outcome(r):
    st = r.get("status")
    if st == "success":
        return "passed"
    if st == "check_failed":
        return "check failed"
    if st == "stopped":
        return "stopped"
    return "failed"


def select(runs, args):
    if args.all:
        return runs, "all runs"
    if args.last:
        return runs[-args.last:], f"last {args.last} runs"
    batches = [r.get("batch") for r in runs if r.get("batch")]
    if batches:
        b = batches[-1]
        return [r for r in runs if r.get("batch") == b], f"test list {b}"
    return runs, "all runs (no test list recorded yet)"


def report(runs, title):
    out = []
    n = len(runs)
    out.append(f"# Dobot run report: {title}")
    if not n:
        out.append("No runs.")
        return "\n".join(out)
    counts = collections.Counter(outcome(r) for r in runs)
    placed = counts["passed"] + counts["check failed"]
    secs = [r.get("seconds") for r in runs if isinstance(r.get("seconds"), (int, float))]
    out.append("")
    out.append(f"Runs: {n}  |  passed: {counts['passed']} ({100 * counts['passed'] / n:.0f}%)  |  placed: {placed}  |  "
               f"check failed: {counts['check failed']}  |  failed before placing: {counts['failed']}  |  "
               f"stopped: {counts['stopped']}")
    if secs:
        out.append(f"Time per run: median {sorted(secs)[len(secs) // 2]:.0f} s, max {max(secs):.0f} s")

    stages = collections.Counter(r.get("failed_stage") for r in runs if outcome(r) == "failed")
    if stages:
        out.append("")
        out.append("## Where runs stopped")
        for stage, k in stages.most_common():
            out.append(f"- {stage}: {k}")
            reasons = collections.Counter((r.get("reason") or "")[:140] for r in runs if r.get("failed_stage") == stage)
            for why, m in reasons.most_common(3):
                out.append(f"    {m}x  {why}")

    checks = collections.Counter()
    for r in runs:
        for c in (r.get("check") or {}).get("checks", []):
            if not c.get("ok"):
                checks[c.get("name")] += 1
    if checks:
        out.append("")
        out.append("## Failed result checks")
        for name, k in checks.most_common():
            out.append(f"- {name}: {k}")

    track = []
    for r in runs:
        w = r.get("tracking_worst_mm") or {}
        if w:
            move, mm = max(w.items(), key=lambda kv: kv[1])
            track.append((mm, move, r))
    if track:
        out.append("")
        out.append("## Worst arm tracking (measured vs commanded tip)")
        for mm, move, r in sorted(track, key=lambda x: -x[0])[:5]:
            out.append(f"- {mm:.0f} mm in '{move}' ({r.get('time')}, capture {r.get('capture_id')})")

    mem = [(r.get("memory_after") or {}) for r in runs]
    if any(m.get("rss_mb") or m.get("gpu_used_mb") for m in mem):
        out.append("")
        out.append("## Memory after each run (Isaac Sim process / GPU)")
        out.append("  " + "  ".join(f"#{i}: {m.get('rss_mb') or '?'} MB / {m.get('gpu_used_mb') or '?'} MB"
                                    for i, m in enumerate(mem, 1)))
        rs = [m["rss_mb"] for m in mem if m.get("rss_mb")]
        gs = [m["gpu_used_mb"] for m in mem if m.get("gpu_used_mb")]
        if len(rs) >= 2:
            out.append(f"  system memory change per run: {(rs[-1] - rs[0]) / (len(rs) - 1):+.0f} MB")
        if len(gs) >= 2:
            out.append(f"  GPU memory change per run: {(gs[-1] - gs[0]) / (len(gs) - 1):+.0f} MB")

    out.append("")
    out.append("## Runs")
    for i, r in enumerate(runs, 1):
        o = outcome(r)
        detail = (r.get("check") or {}).get("summary") if o in ("passed", "check failed") else \
            f"{r.get('failed_stage') or ''}: {r.get('reason') or ''}".strip(": ")
        g = r.get("grounding") or {}
        read = ""
        if g.get("target_prim"):
            read = f" [read as: {g['target_prim'].rsplit('/', 1)[-1]} {g.get('relation')} " \
                   f"{(g.get('reference_prim') or '').rsplit('/', 1)[-1]}]"
        out.append(f"{i:2d}. {o.upper():13s} {r.get('seconds', '?')} s  \"{r.get('task')}\"{read}")
        if detail:
            out.append(f"      {detail[:200]}")
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--file", default=os.path.join(CAPTURE_ROOT, "runs.jsonl"))
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--last", type=int, default=0)
    ap.add_argument("--md", default=None, help="also write the report to this Markdown file")
    args = ap.parse_args(argv)
    if not os.path.isfile(args.file):
        print(f"no runs recorded yet: {args.file}")
        return 1
    runs, title = select(load(args.file), args)
    text = report(runs, title)
    print(text)
    if args.md:
        with open(args.md, "w") as f:
            f.write(text + "\n")
        print(f"\nwritten to {args.md}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

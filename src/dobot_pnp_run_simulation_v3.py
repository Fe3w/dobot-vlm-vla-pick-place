# Result check (pure; unit-testable)
# =============================================================================
def _rigid(T):
    T = np.array(T, dtype=float)
    U, _, Vt = np.linalg.svd(T[:3, :3])
    R = U @ Vt
    if np.linalg.det(R) < 0:
        U[:, -1] *= -1
        R = U @ Vt
    T[:3, :3] = R
    return T


def _cap_pixel(cap, p):
    T, K = np.asarray(cap["camera_to_world"], float), cap["intrinsics"]
    pc = T[:3, :3].T @ (np.asarray(p, float) - T[:3, 3])
    if -pc[2] <= 1e-6:
        return None
    off = float(K.get("pixel_center_offset", 0.5))
    return (K["fx"] * pc[0] / -pc[2] + K["cx"] - off, K["cy"] - K["fy"] * pc[1] / -pc[2] - off)


def evaluate_result(cap, task, final, cfg=V3):
    """Did the run do what the task asked? final: {prim path: 4x4 world pose (metres)} just before stop.

    Returns {"passed": bool, "checks": [{"name", "ok", "detail"}], "summary": str}."""
    checks = []

    def add(name, ok, detail):
        checks.append({"name": name, "ok": bool(ok), "detail": detail})
    tgt, ref, rel = task["target_prim"], task["reference_prim"], task.get("relation", "beside")
    objs = cap["objects"]
    if tgt not in objs or not final or tgt not in final:
        add("object found", False, "no final pose recorded for the picked object")
        return {"passed": False, "checks": checks, "summary": "no final pose recorded"}

    def r_of(o):
        return 0.5 * min(o["max"][0] - o["min"][0], o["max"][1] - o["min"][1])

    def moved_center(path):
        o = objs[path]
        T0, T1 = _rigid(o["world_matrix"]), _rigid(final.get(path, o["world_matrix"]))
        local = T0[:3, :3].T @ (np.asarray(o["center"], float) - T0[:3, 3])
        return T1[:3, :3] @ local + T1[:3, 3], T0, T1

    c1, T0, T1 = moved_center(tgt)
    c0 = np.asarray(objs[tgt]["center"], float)
    robot = cap.get("robot") or {}
    if ref == robot.get("prim"):
        cr, rr = np.asarray(robot["center"], float), r_of(robot)
    else:
        cr, rr = moved_center(ref)[0], r_of(objs[ref])
    rt = r_of(objs[tgt])

    # 1. next to the reference, not on it and not far away
    gap = float(np.hypot(*(c1[:2] - cr[:2]))) - rt - rr
    add("next to the reference", cfg["CHECK_MIN_GAP_M"] <= gap <= cfg["CHECK_MAX_GAP_M"],
        f"gap {gap * 1e3:.0f} mm (allowed {cfg['CHECK_MIN_GAP_M'] * 1e3:.0f} to {cfg['CHECK_MAX_GAP_M'] * 1e3:.0f})")

    # 2. on the asked side (image directions, as the task was read from the camera image)
    want_img = {"left_of": 180.0, "right_of": 0.0, "behind": 90.0, "in_front_of": -90.0}.get(rel)
    if want_img is not None:
        u1, ur = _cap_pixel(cap, c1), _cap_pixel(cap, cr)
        if u1 is None or ur is None:
            add("on the asked side", False, "cannot project the result into the camera image")
        else:
            ang = math.degrees(math.atan2(-(u1[1] - ur[1]), u1[0] - ur[0]))
            dev = abs((ang - want_img + 180.0) % 360.0 - 180.0)
            add("on the asked side", dev <= cfg["CHECK_MAX_DIR_DEG"], f"{dev:.0f} deg off '{rel.replace('_', ' ')}'")
    elif rel == "opposite_side":
        want = math.atan2(cr[1] - c0[1], cr[0] - c0[0])
        got = math.atan2(c1[1] - cr[1], c1[0] - cr[0])
        dev = abs(math.degrees((got - want + math.pi) % (2 * math.pi) - math.pi))
        add("on the far side", dev <= cfg["CHECK_MAX_DIR_DEG"], f"{dev:.0f} deg off the far side")

    # 3. standing, on the table
    z = np.array([0.0, 0.0, 1.0])
    Rd = T1[:3, :3] @ T0[:3, :3].T
    tilt = math.degrees(math.acos(max(-1.0, min(1.0, float((Rd @ z) @ z)))))
    add("upright", tilt <= cfg["CHECK_MAX_TILT_DEG"], f"tilted {tilt:.0f} deg")
    dz = float(c1[2] - c0[2])
    add("on the table", abs(dz) <= cfg["CHECK_MAX_DZ_M"], f"height change {dz * 1e3:+.0f} mm")

    # 4. nothing else knocked over or pushed
    moved = []
    for p in objs:
        if p == tgt:
            continue
        d = float(np.linalg.norm(moved_center(p)[0] - np.asarray(objs[p]["center"], float)))
        if d > cfg["CHECK_MAX_DISTURB_M"]:
            moved.append(f"{p.rsplit('/', 1)[-1]} {d * 1e3:.0f} mm")
    add("other objects untouched", not moved, ", ".join(moved) if moved else "none moved")

    passed = all(c["ok"] for c in checks)
    bad = [f"{c['name']}: {c['detail']}" for c in checks if not c["ok"]]
    if passed:
        side = next((c["detail"] for c in checks if c["name"] in ("on the asked side", "on the far side")), None)
        summary = f"{gap * 1e3:.0f} mm from the reference" + (f", {side}" if side else "") + \
            ", upright, on the table, nothing else moved"
    else:
        summary = "; ".join(bad)
    return {"passed": passed, "checks": checks, "gap_m": gap, "summary": summary}



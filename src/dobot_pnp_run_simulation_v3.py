def _find_v2(cfg):
    if cfg["V2_PATH"]:
        return cfg["V2_PATH"] if os.path.isfile(cfg["V2_PATH"]) else None
    skip = {".git", "node_modules", "__pycache__", ".cache", ".local", "site-packages", "env_isaacsim",
            ".nvidia-omniverse", "snap"}
    for root in cfg["V2_SEARCH_ROOTS"]:
        if not os.path.isdir(root):
            continue
        base_depth = root.rstrip("/").count("/")
        for r, dirs, files in os.walk(root):
            dirs[:] = [d for d in dirs if d not in skip]
            if r.count("/") - base_depth >= 7:
                dirs[:] = []
            if cfg["V2_FILE_NAME"] in files:
                p = os.path.join(r, cfg["V2_FILE_NAME"])
                if _sha256(p) == cfg["V2_SHA256"] or cfg["ALLOW_V2_HASH_MISMATCH"]:
                    return p
    return None


def _load_v2(cfg):
    path = _find_v2(cfg)
    if path is None:
        raise RuntimeError(f"{cfg['V2_FILE_NAME']} with SHA-256 {cfg['V2_SHA256'][:12]}... not found under "
                           f"{cfg['V2_SEARCH_ROOTS']}; set V3['V2_PATH'] to the handoff copy")
    sha = _sha256(path)
    if sha != cfg["V2_SHA256"]:
        if not cfg["ALLOW_V2_HASH_MISMATCH"]:
            raise RuntimeError(f"{path} differs from the reviewed V2 (SHA-256 {sha[:12]}...)")
        _say(f"WARNING: using modified V2 {path} (SHA-256 {sha[:12]}...)")
    with open(path, "r", encoding="utf-8") as f:
        src = f.read()
    marker = '\n_MODE = str(CFG.get("RUN_MODE", "SIMULATION")).strip().upper()'
    idx = src.rfind(marker)
    if idx < 0:
        raise RuntimeError("V2 auto-run block not found; refusing to execute it (it would start on its own)")
    ns = {"__name__": "dobot_pnp_v2_lib", "__file__": path, "__builtins__": builtins}
    exec(compile(src[:idx], path, "exec"), ns)
    for name in ("CFG", "DobotPickPlace", "_prepare_scene_for_simulation", "_run_preflight",
                 "_resolve_required_files", "_stop_timeline_and_wait"):
        if name not in ns:
            raise RuntimeError(f"V2 library is missing {name}")
    _say(f"loaded V2 controller from {path}")
    return ns


def _live_state_fn(ns, stage_getter, paths=None):
    """live_fn for bind(): the controller's own camera model and USD poses on the current stage.

    paths: every object recorded in the capture (default: V2's three role prims)."""
    from pxr import UsdGeom

    def live(W, H):
        stage = stage_getter()
        mpu = float(UsdGeom.GetStageMetersPerUnit(stage) or 1.0)
        c = ns["CFG"]
        cam_prim = stage.GetPrimAtPath(c["CAMERA_PRIM"])
        cam = UsdGeom.Camera(cam_prim)
        f = float(cam.GetFocalLengthAttr().Get())
        ha = float(cam.GetHorizontalApertureAttr().Get())
        hoff = float(cam.GetHorizontalApertureOffsetAttr().Get() or 0.0)
        voff = float(cam.GetVerticalApertureOffsetAttr().Get() or 0.0)
        fx = f / ha * W                                   # == DobotPickPlace._intrinsics
        K = {"fx": fx, "fy": fx, "cx": W * 0.5 + hoff / ha * W, "cy": H * 0.5 - voff / ha * W}

        def world(prim):
            M = ns["_gf_to_np"](UsdGeom.Xformable(prim).ComputeLocalToWorldTransform(ns["Usd"].TimeCode.Default()))
            M[:3, 3] *= mpu
            M[:3, :3] = ns["_orthonormalize"](M[:3, :3])
            return M
        objs = {}
        for path in (paths if paths is not None else [c[k] for k in ("RED_PRIM", "CONE_PRIM", "SPHERE_PRIM")]):
            p = stage.GetPrimAtPath(path)
            if p.IsValid():
                objs[path] = world(p)
        root = stage.GetRootLayer()
        return {"K": K, "T_cam": world(cam_prim), "objects": objs,
                "stage_file": getattr(root, "realPath", "") or root.identifier}
    return live


def _install_guard(ns, cfg, paths=None, log_dir=None):
    import omni.usd
    live = _live_state_fn(ns, lambda: omni.usd.get_context().get_stage(), paths)
    orig_resolve = ns["_resolve_required_files"]
    orig_load = ns["DobotPickPlace"]._load_keypoints

    def guarded_resolve(c):
        ok, kp_path, lines = bind(cfg, live)
        for l in lines:
            print(f"[BIND] {l}")
        if not ok:
            print("[BLOCK] Keypoints are not bound to the live scene. Run dobot_capture_overhead.py on this stage "
                  "(timeline stopped), then rerun V3.")
            return False
        c["JSON_DIR"], c["JSON_FILE"] = os.path.dirname(kp_path), os.path.basename(kp_path)
        if not orig_resolve(c):
            return False
        if os.path.join(c["JSON_DIR"], c["JSON_FILE"]) != kp_path:
            print(f"[BLOCK] V2 switched the keypoint file to {c['JSON_DIR']}/{c['JSON_FILE']}; refusing")
            return False
        return True

    def guarded_load(self):
        ok, kp_path, lines = bind(cfg, live)
        if not ok or os.path.join(self.cfg["JSON_DIR"], self.cfg["JSON_FILE"]) != kp_path:
            raise RuntimeError("keypoint binding failed at controller start: " + " | ".join(lines))
        return orig_load(self)

    ns["_resolve_required_files"] = guarded_resolve      # V2's _prepare_scene_for_simulation looks it up here
    ns["DobotPickPlace"]._load_keypoints = guarded_load

    # VLM keypoints define every placement: no automatic "near the cone" extras that would silently
    # place the object somewhere the task did not ask for.
    orig_auto = ns["DobotPickPlace"]._auto_placement_pixels_near_cone

    def vlm_only_placements(self, support_z_base):
        if "vlm" in str(self.cfg.get("JSON_FILE", "")):
            return []
        return orig_auto(self, support_z_base)
    ns["DobotPickPlace"]._auto_placement_pixels_near_cone = vlm_only_placements

    # Recovery for Cartesian moves made while NOT carrying (release back-off, retract, approach): near the edge
    # of the reach a straight line can make the IK flip branch, which V2 correctly refuses. Instead of stopping,
    # try the same move leaning inward toward the base (away from the reach limit), then a joint-space move.
    # While the payload is held the strict behaviour is kept: no detours, the error stops the arm.
    PlanningError = ns["_PlanningError"]
    orig_move = ns["DobotPickPlace"]._move_tip_path

    async def move_tip_path_recovering(self, pts_b, label, settle=True):
        try:
            return await orig_move(self, pts_b, label, settle)
        except PlanningError as e:
            latch = self._latch
            if (latch is not None and latch.get("active")) or not pts_b:
                raise
            goal = np.asarray(pts_b[-1], dtype=float)
            start = self._fk_tip(self._q_cmd)
            r = float(np.hypot(goal[0], goal[1]))
            _say(f"{label}: straight path near the reach limit ({e}); trying a recovery move")
            for d_in in (0.01, 0.02, 0.04):
                if r <= d_in + 0.05:
                    break
                alt = goal.copy()
                alt[:2] *= (r - d_in) / r
                try:
                    await orig_move(self, self._line_points(start, alt), f"{label} (leaning {d_in * 1e3:.0f} mm inward)",
                                    settle)
                    return None
                except PlanningError:
                    continue
            for seed in (self._q_cmd, getattr(self, "_q_home", None)):
                if seed is None:
                    continue
                q = self._ik_tip_base(goal, seed)
                if q is not None:
                    await self._move_joint(q, f"{label} (joint-space)", settle)
                    return None
            raise
    ns["DobotPickPlace"]._move_tip_path = move_tip_path_recovering
    _install_motion_guard(ns, cfg, log_dir, paths)


class TrackingStop(RuntimeError):
    """The measured tip stayed far from the commanded tip; the arm was frozen."""


class MotionMonitor:
    """Per-tick record of commanded vs measured tip, and the tracking watchdog. Pure numpy (testable)."""
    FIELDS = ("sim_t", "move", "latched", "cmd_x", "cmd_y", "cmd_z", "meas_x", "meas_y", "meas_z", "err_mm",
              "q_cmd", "q_meas")

    def __init__(self, cfg, path=None):
        self.warn_m = float(cfg["TRACK_WARN_MM"]) * 1e-3
        self.stop_m = float(cfg["TRACK_STOP_MM"]) * 1e-3
        self.stop_s = float(cfg["TRACK_STOP_S"])
        self.path = path
        self.rows = []
        self.label = "setup"
        self.since = None
        self.worst = {}                  # move label -> worst error (m)
        self.warned = set()

    def step(self, t, cmd_tip, meas_tip, q_cmd, q_meas, latched):
        """Record one tick; returns None, or a message when the watchdog must stop the arm."""
        e = float(np.linalg.norm(np.asarray(meas_tip) - np.asarray(cmd_tip)))
        if self.path is not None:
            self.rows.append((round(t, 4), self.label, int(bool(latched)),
                              *np.round(np.asarray(cmd_tip) * 1e3, 2), *np.round(np.asarray(meas_tip) * 1e3, 2),
                              round(e * 1e3, 2), " ".join(f"{x:.4f}" for x in q_cmd),
                              " ".join(f"{x:.4f}" for x in q_meas)))
        self.worst[self.label] = max(self.worst.get(self.label, 0.0), e)
        if e > self.warn_m and self.label not in self.warned:
            self.warned.add(self.label)
            _say(f"tracking: '{self.label}' measured tip {e * 1e3:.0f} mm from the commanded tip "
                 f"({'carrying' if latched else 'empty'})")
        if e > self.stop_m:
            self.since = t if self.since is None else self.since
            if t - self.since >= self.stop_s:
                return (f"tracking watchdog: during '{self.label}' the measured tip stayed "
                        f"{e * 1e3:.0f} mm from the commanded tip for {t - self.since:.1f} s; arm frozen")
        else:
            self.since = None
        return None

    def flush(self):
        if self.path is None or not self.rows:
            return None
        try:
            with open(self.path, "w") as f:
                f.write(",".join(self.FIELDS) + "\n")
                for r in self.rows:
                    f.write(",".join(f'"{x}"' if isinstance(x, str) else str(x) for x in r) + "\n")
        except OSError as e:
            _say(f"motion log not written ({e})")
            return None
        worst = ", ".join(f"{k} {v * 1e3:.0f} mm" for k, v in self.worst.items() if v * 1e3 >= 5.0)
        _say(f"motion log: {len(self.rows)} ticks in {self.path}" + (f"; worst tracking: {worst}" if worst else ""))
        self.rows = []
        return self.path


def _install_motion_guard(ns, cfg, log_dir, paths=None):
    cls = ns["DobotPickPlace"]
    log_path = os.path.join(log_dir, "motion_log.csv") if (log_dir and cfg.get("MOTION_LOG", True)) else None

    # 1. The held payload ignores the whole robot, not just the suction link and its parent.
    orig_filter = cls._filter_link_paths

    def filter_links(self):
        base = list(orig_filter(self))
        if not cfg.get("FILTER_ALL_ROBOT_LINKS", True):
            return base
        return base + [p for p in self._robot_links if p not in base]
    cls._filter_link_paths = filter_links

    # 2. Move labels for the log / watchdog messages.
    def labelled(name):
        orig = getattr(cls, name)

        async def wrapper(self, *a, **k):
            mon = getattr(self, "_v3_monitor", None)
            label = next((x for x in a if isinstance(x, str)), name.strip("_"))
            prev = None
            if mon is not None:
                prev, mon.label = mon.label, label
            try:
                return await orig(self, *a, **k)
            finally:
                if mon is not None and prev is not None:
                    mon.label = prev
        return wrapper
    for name in ("_move_joint", "descend_cartesian_to_touch"):
        setattr(cls, name, labelled(name))
    rec = cls._move_tip_path                      # already the recovering wrapper

    async def move_tip_labelled(self, pts_b, label, settle=True):
        mon = getattr(self, "_v3_monitor", None)
        prev = None
        if mon is not None:
            prev, mon.label = mon.label, label
        try:
            return await rec(self, pts_b, label, settle)
        finally:
            if mon is not None and prev is not None:
                mon.label = prev
    cls._move_tip_path = move_tip_labelled

    # 3. Every control tick: record and check tracking.
    orig_tick = cls._tick

    async def tick(self):
        await orig_tick(self)
        if self._q_cmd is None or self._joints is None or getattr(self, "_lula", None) is None:
            return
        mon = getattr(self, "_v3_monitor", None)
        if mon is None:
            mon = self._v3_monitor = MotionMonitor(cfg, log_path)
        q = self._q_meas()
        if q is None:
            return
        try:
            cmd, meas = self._fk_tip(self._q_cmd), self._fk_tip(q)
        except Exception:
            return
        msg = mon.step(self._sim_clock, cmd, meas, self._q_cmd, q, self._latch is not None and self._latch.get("active"))
        if msg is not None:
            self._command(q)                      # freeze where the arm is
            raise TrackingStop(msg)
    cls._tick = tick

    orig_pipeline = cls._pipeline

    async def pipeline(self):
        await orig_pipeline(self)
        final = {}
        for p in (paths or []):
            try:
                T = self._physx_pose(p)
                if T is None:
                    T = self._usd_world(self._stage.GetPrimAtPath(p))
                final[p] = np.asarray(T, float).tolist()
            except Exception as e:
                _say(f"final pose of {p} unavailable ({e})")
        builtins._DOBOT_PNP_LAST_FINAL = final
    cls._pipeline = pipeline

    orig_shutdown = cls.shutdown

    def shutdown(self, reason="shutdown", from_task=False):
        mon = getattr(self, "_v3_monitor", None)
        if mon is not None:
            builtins._DOBOT_PNP_LAST_TRACKING = {k: round(v * 1e3, 1) for k, v in mon.worst.items()}
            mon.flush()
        return orig_shutdown(self, reason, from_task)
    cls.shutdown = shutdown



"""
Dobot pick-and-place SIMULATION runner V3 (Isaac Sim 6.0.x Script Editor).

V3 = the reviewed V2 controller + a keypoint-binding guard. It does not fork V2:
it loads dobot_pnp_run_simulation_isaacsim6_v2.py from disk, checks its SHA-256,
executes it WITHOUT its auto-run block, patches two functions and runs.

What the guard enforces
    The controller may only use keypoints that are bound to a capture made by
    dobot_capture_overhead.py, and only while that capture still describes the
    live scene:
      * capture.json exists, its camera-model check passed, rgb.png matches the
        recorded SHA-256;
      * the keypoint file names that capture id and image hash;
      * the keypoint image size and intrinsics equal the live /overhead_camera
        model (within K_TOL_PX);
      * the camera pose and the red cylinder / cone / sphere poses equal the
        capture (within POSE_TOL_M / ROT_TOL_DEG).
    Anything else (an old KALM JSON, a viewport screenshot, a capture made
    before an object moved) is refused before the robot can move. V2's own
    fallback search for "any keypoints_2d.json under the data folder" can no
    longer pick a stale file.

Run order
    1. Open the Dobot test stage, timeline stopped, run dobot_capture_overhead.py.
    2. Run this file. It reloads the SAME stage file the capture was taken from
       (not a hard-coded baseline), stops the timeline, applies V2's in-memory
       preparation, binds the keypoints, runs V2's preflight and only then starts
       the reduced-speed controller.

Keypoints: keypoints_2d_vlm.json written by dobot_vlm_keypoints.py (set
KEYPOINT_FILES to use the oracle keypoints_2d_groundtruth.json instead). When the
file carries a "task" block, its target / reference / avoid prims replace the
controller's RED_PRIM / CONE_PRIM / SPHERE_PRIM before preparation.
"""


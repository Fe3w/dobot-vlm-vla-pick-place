def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def _rot_angle_deg(Ra, Rb):
    c = (np.trace(np.asarray(Ra).T @ np.asarray(Rb)) - 1.0) / 2.0
    return math.degrees(math.acos(max(-1.0, min(1.0, c))))


def resolve_capture_dir(cfg):
    if cfg["CAPTURE_DIR"]:
        return cfg["CAPTURE_DIR"], None
    latest = os.path.join(cfg["CAPTURE_ROOT"], "latest.json")
    if not os.path.isfile(latest):
        return None, f"no capture yet: {latest} is missing. Run dobot_capture_overhead.py first"
    with open(latest) as f:
        d = json.load(f)
    return d.get("capture_dir"), None


def load_capture(cap_dir):
    """(capture dict, [problems]) for a capture folder, checking its own integrity."""
    problems = []
    path = os.path.join(cap_dir or "", "capture.json")
    if not cap_dir or not os.path.isfile(path):
        return None, [f"capture.json not found in {cap_dir}"]
    with open(path) as f:
        cap = json.load(f)
    if cap.get("schema") not in ("dobot.capture/1", "dobot.capture/2"):
        problems.append(f"unexpected capture schema {cap.get('schema')!r}")
    if not cap.get("camera_check", {}).get("passed", False):
        problems.append("the capture's camera-model check did not pass")
    img = os.path.join(cap_dir, cap.get("image", {}).get("file", "rgb.png"))
    if not os.path.isfile(img):
        problems.append(f"capture image missing: {img}")
    elif _sha256(img) != cap.get("image", {}).get("sha256"):
        problems.append("rgb.png was modified after capture (SHA-256 mismatch)")
    return cap, problems


def pick_keypoint_file(cap_dir, cap, names):
    """First keypoint file in `names` that is bound to this capture; (path, data, notes)."""
    notes = []
    for name in names:
        p = os.path.join(cap_dir, name)
        if not os.path.isfile(p):
            continue
        try:
            with open(p) as f:
                d = json.load(f)
        except Exception as e:
            notes.append(f"{name}: unreadable ({e})")
            continue
        b = d.get("capture", {}) if isinstance(d, dict) else {}
        if b.get("capture_id") != cap["capture_id"] or b.get("image_sha256") != cap["image"]["sha256"]:
            notes.append(f"{name}: not bound to capture {cap['capture_id']} (capture={b})")
            continue
        size = d.get("image_size")
        if list(size or []) != [cap["image"]["width"], cap["image"]["height"]]:
            notes.append(f"{name}: image_size {size} != capture {cap['image']['width']}x{cap['image']['height']}")
            continue
        if not d.get("grasp_points") or not d.get("placement_candidates"):
            notes.append(f"{name}: needs at least one grasp point and one placement candidate")
            continue
        return p, d, notes
    return None, None, notes


def compare_live(cap, kp, live, tol):
    """Problems if the live scene no longer matches the capture. `live` holds K, T_cam, objects, stage_file."""
    problems = []
    if os.path.basename(live["stage_file"]) != os.path.basename(cap["stage_file"]):
        problems.append(f"open stage {os.path.basename(live['stage_file'])} is not the captured "
                        f"{os.path.basename(cap['stage_file'])}")
    Kc = kp.get("K") or cap["intrinsics"]
    for k in ("fx", "fy", "cx", "cy"):
        if abs(float(Kc[k]) - float(live["K"][k])) > tol["K_TOL_PX"]:
            problems.append(f"intrinsic {k}: keypoints {float(Kc[k]):.2f} vs live camera {float(live['K'][k]):.2f}")
    Tc, Tl = np.asarray(cap["camera_to_world"]), np.asarray(live["T_cam"])
    dt = float(np.linalg.norm(Tc[:3, 3] - Tl[:3, 3]))
    dr = _rot_angle_deg(Tc[:3, :3], Tl[:3, :3])
    if dt > tol["POSE_TOL_M"] or dr > tol["ROT_TOL_DEG"]:
        problems.append(f"camera moved since capture: {dt * 1e3:.2f} mm, {dr:.3f} deg")
    for path, o in cap["objects"].items():
        Tl_o = live["objects"].get(path)
        if Tl_o is None:
            problems.append(f"{path} no longer exists")
            continue
        To = np.asarray(o["world_matrix"])
        dt = float(np.linalg.norm(To[:3, 3] - np.asarray(Tl_o)[:3, 3]))
        dr = _rot_angle_deg(To[:3, :3], np.asarray(Tl_o)[:3, :3])
        if dt > tol["OBJECT_POSE_TOL_M"] or dr > tol["OBJECT_ROT_TOL_DEG"]:
            problems.append(f"{path} moved since capture: {dt * 1e3:.1f} mm, {dr:.2f} deg")
    return problems


def apply_task_prims(c, kp, all_prims, robot_prim=None):
    """Map a keypoint file's task block onto the controller's RED/CONE/SPHERE prims. Returns lines or raises."""
    t = kp.get("task") if isinstance(kp, dict) else None
    if not t:
        return [f"no task block: keeping RED={c['RED_PRIM']} CONE={c['CONE_PRIM']} SPHERE={c['SPHERE_PRIM']}"]
    tgt, ref = t.get("target_prim"), t.get("reference_prim")
    robot_ref = robot_prim is not None and ref == robot_prim
    if tgt not in all_prims or (ref not in all_prims and not robot_ref) or tgt == ref:
        raise RuntimeError(f"task prims not in the captured scene: target={tgt} reference={ref}")
    # V2 knows three roles. Every other captured object is still an obstacle: the keypoint file carries
    # obstacle points for all of them. A role with no object left points at the target (harmless: V2 skips
    # depth hits on the target when it builds obstacles).
    if robot_ref:
        others = [p for p in all_prims if p != tgt]
        c["RED_PRIM"] = tgt
        c["CONE_PRIM"] = others[0] if others else tgt
        c["SPHERE_PRIM"] = others[1] if len(others) > 1 else tgt
    else:
        rest = [p for p in t.get("avoid_prims", []) if p in all_prims and p not in (tgt, ref)]
        rest += [p for p in all_prims if p not in (tgt, ref) and p not in rest]
        c["RED_PRIM"], c["CONE_PRIM"] = tgt, ref
        c["SPHERE_PRIM"] = rest[0] if rest else tgt
    return [f"task: \"{t.get('task_text', '')}\"",
            f"target {tgt} | {t.get('relation', 'beside')} {ref} | avoid {t.get('avoid_prims') or 'none'} "
            f"| model {t.get('routed_via') or '?'} | confidence {t.get('confidence')}"]


def bind(cfg, live_fn):
    """Full binding check. live_fn(W, H) -> live dict. Returns (ok, json_path, info_lines)."""
    lines = []
    cap_dir, err = resolve_capture_dir(cfg)
    if err:
        return False, None, [err]
    cap, problems = load_capture(cap_dir)
    if cap is None:
        return False, None, problems
    lines.append(f"capture {cap['capture_id']} ({cap.get('created_local')}) from {cap_dir}")
    kp_path, kp, notes = pick_keypoint_file(cap_dir, cap, cfg["KEYPOINT_FILES"])
    lines += [f"  skipped {n}" for n in notes]
    if kp_path is None:
        problems.append(f"no keypoint file in {cap_dir} is bound to this capture "
                        f"(looked for {list(cfg['KEYPOINT_FILES'])})")
    else:
        lines.append(f"keypoints: {os.path.basename(kp_path)} (source {kp.get('source', '?')}), "
                     f"{len(kp['grasp_points'])} grasp / {len(kp['placement_candidates'])} placement / "
                     f"{len(kp.get('obstacle_points', []))} obstacle")
        live = live_fn(cap["image"]["width"], cap["image"]["height"])
        problems += compare_live(cap, kp, live, cfg)
    if problems:
        return False, None, lines + [f"  problem: {p}" for p in problems]
    return True, kp_path, lines + ["binding OK: keypoints match the live camera and object poses"]



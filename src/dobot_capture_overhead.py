def intrinsics_horizontal_fit(cam_prim, W, H):
    cam = UsdGeom.Camera(cam_prim)
    f = float(cam.GetFocalLengthAttr().Get())
    ha = float(cam.GetHorizontalApertureAttr().Get())
    hoff = float(cam.GetHorizontalApertureOffsetAttr().Get() or 0.0)
    voff = float(cam.GetVerticalApertureOffsetAttr().Get() or 0.0)
    fx = f / ha * W
    return {"fx": fx, "fy": fx, "cx": W * 0.5 + hoff / ha * W, "cy": H * 0.5 - voff / ha * W,
            "model": "usd_horizontal_aperture_fit_square_pixels"}


def intrinsics_vertical_fit(cam_prim, W, H):
    cam = UsdGeom.Camera(cam_prim)
    f = float(cam.GetFocalLengthAttr().Get())
    ha = float(cam.GetHorizontalApertureAttr().Get())
    va = cam.GetVerticalApertureAttr().Get()
    va = float(va) if va else ha * H / W
    hoff = float(cam.GetHorizontalApertureOffsetAttr().Get() or 0.0)
    voff = float(cam.GetVerticalApertureOffsetAttr().Get() or 0.0)
    fy = f / va * H
    return {"fx": fy, "fy": fy, "cx": W * 0.5 + hoff / va * H, "cy": H * 0.5 - voff / va * H,
            "model": "usd_vertical_aperture_fit_square_pixels"}


def project(K, T_cam, P, off):
    P = np.atleast_2d(np.asarray(P, dtype=float))
    pc = (P - T_cam[:3, 3]) @ T_cam[:3, :3]
    z = -pc[:, 2]
    with np.errstate(divide="ignore", invalid="ignore"):
        u = K["fx"] * pc[:, 0] / z + K["cx"] - off
        v = K["cy"] - K["fy"] * pc[:, 1] / z - off
    bad = ~(z > 1e-6)
    u[bad], v[bad] = np.nan, np.nan
    return np.stack([u, v], axis=1)


def pixel_ray(K, T_cam, u, v, off):
    d_cam = np.array([(u + off - K["cx"]) / K["fx"], -(v + off - K["cy"]) / K["fy"], -1.0])
    d = T_cam[:3, :3] @ d_cam
    return T_cam[:3, 3].copy(), d / np.linalg.norm(d)



def colour_masks(rgb):
    """Boolean masks for the three coloured objects in a rendered RGB uint8 image."""
    x = rgb[..., :3].astype(np.int32)
    R, G, B = x[..., 0], x[..., 1], x[..., 2]
    red = (R > 70) & (R > 2 * G + 10) & (R > 2 * B + 10)
    green = (G > 60) & (G > 1.6 * R + 10) & (G > 1.6 * B + 10)
    purple = (B > 60) & (R > 35) & (G * 2 < B) & (G * 10 < R * 7)
    return {"red": red, "green": green, "purple": purple}


def mask_box(mask, min_px=150):
    ys, xs = np.nonzero(mask)
    if len(xs) < min_px:
        return None, int(len(xs))
    lo_x, hi_x = np.percentile(xs, [0.5, 99.5])
    lo_y, hi_y = np.percentile(ys, [0.5, 99.5])
    return [float(lo_x), float(lo_y), float(hi_x) + 1.0, float(hi_y) + 1.0], int(len(xs))


def box_iou(a, b):
    ix = max(0.0, min(a[2], b[2]) - max(a[0], b[0]))
    iy = max(0.0, min(a[3], b[3]) - max(a[1], b[1]))
    inter = ix * iy
    ua = (a[2] - a[0]) * (a[3] - a[1]) + (b[2] - b[0]) * (b[3] - b[1]) - inter
    return inter / ua if ua > 0 else 0.0


def proj_box(uv):
    ok = np.all(np.isfinite(uv), axis=1)
    if not np.any(ok):
        return None
    return [float(uv[ok, 0].min()), float(uv[ok, 1].min()), float(uv[ok, 0].max()), float(uv[ok, 1].max())]


def write_png(path, rgb):
    try:
        from PIL import Image
        Image.fromarray(np.ascontiguousarray(rgb[..., :3], dtype=np.uint8)).save(path)
        return
    except Exception:
        pass
    import struct
    import zlib
    rgb = np.ascontiguousarray(rgb[..., :3], dtype=np.uint8)
    h, w = rgb.shape[:2]
    raw = b"".join(b"\x00" + rgb[y].tobytes() for y in range(h))

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
                + chunk(b"IDAT", zlib.compress(raw, 6)) + chunk(b"IEND", b""))


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()



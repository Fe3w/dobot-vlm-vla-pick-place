_SHAPE_WORDS = {"box": ["box", "cube", "block", "brick"], "cylinder": ["cylinder", "can", "tube", "puck"],
                "sphere": ["sphere", "ball", "orb"], "cone": ["cone", "pyramid"], "capsule": ["capsule", "pill"],
                "object": ["object", "thing", "item"]}
_TYPE_SHAPE = {"Cube": "box", "Cylinder": "cylinder", "Sphere": "sphere", "Cone": "cone", "Capsule": "capsule"}


def _hull_area(P):
    P = np.unique(np.round(np.asarray(P, float), 5), axis=0)
    if len(P) < 3:
        return 0.0
    P = P[np.lexsort((P[:, 1], P[:, 0]))]

    def half(pts):
        h = []
        for p in pts:
            while len(h) >= 2 and ((h[-1][0] - h[-2][0]) * (p[1] - h[-2][1])
                                   - (h[-1][1] - h[-2][1]) * (p[0] - h[-2][0])) <= 0.0:
                h.pop()
            h.append(p)
        return h[:-1]
    H_ = np.array(half(P) + half(P[::-1]))
    x, y = H_[:, 0], H_[:, 1]
    return 0.5 * abs(float(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1))))


def shape_of(stage, path, info):
    """'box' | 'cylinder' | 'sphere' | 'cone' | 'capsule' | 'object' from prim types, names, then geometry."""
    root = stage.GetPrimAtPath(path)
    for p in Usd.PrimRange(root):
        if p.IsA(UsdGeom.Gprim) and p.GetTypeName() in _TYPE_SHAPE:
            return _TYPE_SHAPE[p.GetTypeName()]
    for p in Usd.PrimRange(root):
        n = p.GetName().lower()
        for shape, words in _SHAPE_WORDS.items():
            if shape != "object" and any(w in n for w in words):
                return shape
    P = info["points"]
    lo, hi = info["min"], info["max"]
    h = hi[2] - lo[2]
    if h <= 1e-6 or len(P) < 8:
        return "object"
    c = (lo[:2] + hi[:2]) / 2
    rad = np.hypot(P[:, 0] - c[0], P[:, 1] - c[1])
    r_all = float(rad.max()) or 1e-9
    top = float(rad[P[:, 2] > lo[2] + 0.85 * h].max(initial=0.0)) / r_all
    bot = float(rad[P[:, 2] < lo[2] + 0.15 * h].max(initial=0.0)) / r_all
    if top < 0.35 and bot > 0.7:
        return "cone"
    if top < 0.6 and bot < 0.6:
        return "sphere"
    ext = hi[:2] - lo[:2]
    fill = _hull_area(P[:, :2]) / max(float(ext[0] * ext[1]), 1e-12)
    return "box" if fill > 0.92 else "cylinder"


def colour_name(rgb):
    import colorsys
    r, g, b = [float(x) / 255.0 for x in rgb[:3]]
    hh, s, v = colorsys.rgb_to_hsv(r, g, b)
    if v < 0.16:
        return "black"
    if s < 0.22:
        return "white" if v > 0.78 else "grey"
    hue = hh * 360.0
    if hue < 15 or hue >= 345:
        return "red" if v > 0.35 else "dark red"
    for limit, name in ((40, "orange"), (70, "yellow"), (165, "green"), (200, "cyan"), (255, "blue"),
                        (290, "purple"), (345, "pink")):
        if hue < limit:
            return name
    return "red"


def _display_colour(stage, path):
    for p in Usd.PrimRange(stage.GetPrimAtPath(path)):
        if p.IsA(UsdGeom.Gprim):
            try:
                c = UsdGeom.Gprim(p).GetDisplayColorAttr().Get()
                if c is not None and len(c):
                    return [int(255 * max(0.0, min(1.0, float(x)))) for x in c[0]]
            except Exception:
                pass
    return None


def is_pickable(stage, path):
    prim = stage.GetPrimAtPath(path)
    if not prim.HasAPI(UsdPhysics.RigidBodyAPI):
        return False
    if UsdPhysics.RigidBodyAPI(prim).GetKinematicEnabledAttr().Get():
        return False
    return any(p.HasAPI(UsdPhysics.CollisionAPI) for p in Usd.PrimRange(prim))


def discover_objects(stage, cfg, mpu, exclude):
    """{path: info} for every compact visible object (rigid-body root, or a stand-alone Gprim)."""
    t = Usd.TimeCode.Default()
    pats = tuple(x.lower() for x in cfg["IGNORE_NAME_PATTERNS"])
    roots = {}
    it = iter(Usd.PrimRange.Stage(stage, Usd.TraverseInstanceProxies()))
    for prim in it:
        path = str(prim.GetPath())
        if any(_under(path, e) for e in exclude) or any(x in prim.GetName().lower() for x in pats):
            it.PruneChildren()
            continue
        if not prim.IsA(UsdGeom.Gprim):
            continue
        img = UsdGeom.Imageable(prim)
        if img.ComputeVisibility(t) == UsdGeom.Tokens.invisible or \
                img.ComputePurpose() in (UsdGeom.Tokens.guide, UsdGeom.Tokens.proxy):
            continue
        root, p = prim, prim
        while p.IsValid() and not p.IsPseudoRoot():
            if p.HasAPI(UsdPhysics.RigidBodyAPI):
                root = p
                break
            p = p.GetParent()
        roots.setdefault(str(root.GetPath()), root)
    out = {}
    for path, root in sorted(roots.items()):
        info = object_info(stage, path, mpu)
        if info is None:
            continue
        ext = info["max"] - info["min"]
        if float(ext.max()) > cfg["OBJECT_MAX_SIZE_M"] or float(ext.max()) < cfg["OBJECT_MIN_SIZE_M"]:
            continue
        info["T"] = _usd_world(root, mpu)
        out[path] = info
    return out



def robot_record(stage, cfg, mpu, K, T_cam):
    """Robot base footprint for use as a placement reference ("behind the robot"). Never pickable.

    Only the base link's own geometry is used (the arm moves; the base does not)."""
    try:
        info = object_info(stage, cfg["BASE_PRIM"], mpu)
        if info is None:
            return None
        uv = project(K, T_cam, info["points"], cfg["PIXEL_CENTER_OFFSET"])
        return {"prim": cfg["BASE_PRIM"], "min": np.round(info["min"], 6).tolist(),
                "max": np.round(info["max"], 6).tolist(), "center": np.round(info["center"], 6).tolist(),
                "projected_box": proj_box(uv)}
    except Exception as e:
        _log(f"robot base not recorded ({e}); 'behind the robot' style tasks will be unavailable")
        return None


def scene_snapshot(stage, cfg, W, H):
    """Everything about the scene the capture depends on (no rendering)."""
    mpu = float(UsdGeom.GetStageMetersPerUnit(stage) or 1.0)
    cam_prim = stage.GetPrimAtPath(cfg["CAMERA_PRIM"])
    if not cam_prim.IsValid() or not cam_prim.IsA(UsdGeom.Camera):
        raise RuntimeError(f"{cfg['CAMERA_PRIM']} is missing or not a Camera")
    proj_attr = UsdGeom.Camera(cam_prim).GetProjectionAttr().Get()
    if str(proj_attr).lower() != "perspective":
        raise RuntimeError(f"camera projection is {proj_attr}; the controller needs a perspective camera")
    K = intrinsics_horizontal_fit(cam_prim, W, H)
    Kv = intrinsics_vertical_fit(cam_prim, W, H)
    T_cam = _usd_world(cam_prim, mpu)
    robot_links = _robot_link_paths(stage, cfg["ROBOT_PRIM"], cfg["URDF_PATH"]) \
        if os.path.isfile(cfg["URDF_PATH"]) else []
    markers = _marker_paths(stage, robot_links, cfg["DEPTH_IGNORE_NAME_PATTERNS"])
    exclude = robot_links + markers + [cfg["CAMERA_PRIM"], cfg["BASE_PRIM"]]
    objs = discover_objects(stage, cfg, mpu, exclude)
    base = stage.GetPrimAtPath(cfg["BASE_PRIM"])
    if not base.IsValid():
        base = stage.GetPrimAtPath(cfg["ROBOT_PRIM"])
    base_xy = _usd_world(base, mpu)[:3, 3][:2]
    return mpu, cam_prim, K, Kv, T_cam, objs, base_xy, robot_links, markers


def _seg_masks(seg, paths):
    """{object path: boolean mask} from an instance segmentation (prim paths may be child Gprims)."""
    if seg is None:
        return None
    arr, mapping = seg
    masks = {p: np.zeros(arr.shape, bool) for p in paths}
    for i, lab in mapping.items():
        owner = next((p for p in paths if _under(lab, p)), None)
        if owner is not None:
            masks[owner] |= (arr == i)
    return masks


def _legacy_colour_check(cfg, rgb, objs, K, T_cam, off):
    """Fallback camera check when segmentation is unavailable: the original red / purple / green objects."""
    masks = colour_masks(rgb)
    res = {}
    for path, mkey in ((cfg["RED_PRIM"], "red"), (cfg["CONE_PRIM"], "purple"), (cfg["SPHERE_PRIM"], "green")):
        if path not in objs:
            continue
        pb = proj_box(project(K, T_cam, objs[path]["points"], off))
        mb, n = mask_box(masks[mkey])
        res[path] = {"projected_box": pb, "mask_box": mb, "mask_pixels": n,
                     "iou": round(box_iou(pb, mb), 3) if (pb and mb) else None}
    return res


async def capture(cfg=CAP):
    t0 = time.time()
    tl = omni.timeline.get_timeline_interface()
    ctx = omni.usd.get_context()
    stage = ctx.get_stage()
    if stage is None:
        _log("BLOCK: no stage open")
        return None
    if not tl.is_stopped():
        _log("BLOCK: the timeline is not stopped. Stop it (and reload the stage if objects moved), then rerun.")
        return None
    W, H = int(cfg["WIDTH"]), int(cfg["HEIGHT"])
    root = stage.GetRootLayer()
    stage_file = getattr(root, "realPath", "") or root.identifier
    if root.dirty:
        _log("WARNING: the stage has unsaved edits; the runner reloads the saved file before moving the robot.")
    mpu, cam_prim, K, Kv, T_cam, objs, base_xy, robot_links, markers = scene_snapshot(stage, cfg, W, H)
    if not objs:
        _log("BLOCK: no objects found on the table (check OBJECT_MAX_SIZE_M / IGNORE_NAME_PATTERNS)")
        return None
    _log(f"objects found: {list(objs)}")

    _log(f"rendering {cfg['CAMERA_PRIM']} at {W}x{H} ...")
    rgb, how, seg = await render_rgb(cfg["CAMERA_PRIM"], W, H, cfg)
    if not tl.is_stopped():
        _log("BLOCK: the timeline is no longer stopped after rendering; nothing saved")
        return None
    snap2 = scene_snapshot(stage, cfg, W, H)
    objs2, T2 = snap2[5], snap2[4]
    moved = [k for k in objs if k not in objs2 or np.linalg.norm(objs[k]["center"] - objs2[k]["center"]) > 1e-4]
    if moved or set(objs2) != set(objs) or np.abs(T2 - T_cam).max() > 1e-6:
        _log(f"BLOCK: scene changed while rendering ({moved or 'objects/camera'}); nothing saved")
        return None

    cap_id = time.strftime("%Y%m%dT%H%M%S") + "_" + uuid.uuid4().hex[:6]
    out_dir = os.path.join(cfg["CAPTURE_ROOT"], cap_id)
    os.makedirs(out_dir, exist_ok=False)
    png = os.path.join(out_dir, "rgb.png")
    write_png(png, rgb)
    img_sha = sha256_file(png)
    off = cfg["PIXEL_CENTER_OFFSET"]

    # --- per-object record + camera-model check against the render ----------------------------------
    masks = _seg_masks(seg, list(objs))
    records, check, boxes, ious = {}, {}, {}, []
    for path, info in objs.items():
        pb = proj_box(project(K, T_cam, info["points"], off))
        mb, n, col = None, 0, None
        if masks is not None:
            m = masks[path]
            n = int(m.sum())
            if n >= 1:
                ys, xs = np.nonzero(m)
                mb = [float(xs.min()), float(ys.min()), float(xs.max()) + 1.0, float(ys.max()) + 1.0]
                col = [int(x) for x in np.median(rgb[m], axis=0)]
        iou, cut = None, False
        if pb and mb:
            pc = [max(0.0, pb[0]), max(0.0, pb[1]), min(float(W), pb[2]), min(float(H), pb[3])]   # the visible part
            full = max(1e-9, (pb[2] - pb[0]) * (pb[3] - pb[1]))
            inside = max(0.0, pc[2] - pc[0]) * max(0.0, pc[3] - pc[1])
            cut = inside < 0.999 * full
            iou = box_iou(pc, mb) if inside > 0 else None
            if cut and inside < 0.5 * full:
                _log(f"object {path} is mostly outside the camera picture; not used for the camera check")
                iou = None
        if iou is not None and n >= cfg["CHECK_MIN_PIXELS"]:
            ious.append(iou)
        if col is None:
            col = _display_colour(stage, path)
        if col is None and pb:
            cx, cy = int((pb[0] + pb[2]) / 2), int((pb[1] + pb[3]) / 2)
            if 0 <= cx < W and 0 <= cy < H:
                col = [int(x) for x in np.median(rgb[max(0, cy - 3):cy + 4, max(0, cx - 3):cx + 4].reshape(-1, 3), 0)]
        shape = shape_of(stage, path, info)
        cname = colour_name(col) if col is not None else ""
        name = cfg["NAME_OVERRIDES"].get(path) or f"{cname} {shape}".strip()
        words = sorted(set(name.split()) | set(_SHAPE_WORDS.get(shape, [])) |
                       {w for w in re.split(r"[^a-z]+", path.rsplit("/", 1)[-1].lower()) if len(w) > 2})
        visible = (n >= cfg["CHECK_MIN_PIXELS"]) if masks is not None else bool(pb)
        records[path] = {"min": np.round(info["min"], 6).tolist(), "max": np.round(info["max"], 6).tolist(),
                         "center": np.round(info["center"], 6).tolist(),
                         "world_matrix": np.round(info["T"], 9).tolist(),
                         "name": name, "words": words, "shape": shape, "colour": cname, "colour_rgb": col,
                         "pickable": is_pickable(stage, path), "visible": visible,
                         "box": mb if mb is not None else pb, "visible_px": n}
        check[path] = {"projected_box": pb, "mask_box": mb, "mask_pixels": n,
                       "iou": None if iou is None else round(iou, 3)}
        boxes[path] = (pb, mb)
        _log(f"object {path}: '{name}', pickable={records[path]['pickable']}, visible px={n}, "
             f"IoU {None if iou is None else round(iou, 2)}")

    if masks is not None and ious:
        med = float(np.median(ious))
        passed, method = med >= cfg["CHECK_MIN_IOU"], f"segmentation (median IoU {med:.2f} over {len(ious)} objects)"
    else:
        legacy = _legacy_colour_check(cfg, rgb, objs, K, T_cam, off)
        good = [v["iou"] for v in legacy.values() if v["iou"] is not None]
        passed = bool(good) and float(np.median(good)) >= cfg["CHECK_MIN_IOU"]
        method = "colour masks (segmentation unavailable)"
        check.update({k: dict(check.get(k, {}), **v) for k, v in legacy.items()})
    _log(f"camera check {'passed' if passed else 'FAILED'}: {method}")
    if not passed:
        _log("FAIL: the camera model does not match the render; this capture is not used for motion.")

    capture_json = {
        "schema": "dobot.capture/2",
        "capture_id": cap_id,
        "created_local": time.strftime("%Y-%m-%d %H:%M:%S"),
        "stage_file": stage_file,
        "stage_dirty_at_capture": bool(root.dirty),
        "camera_prim": cfg["CAMERA_PRIM"],
        "image": {"file": "rgb.png", "width": W, "height": H, "sha256": img_sha, "render": how},
        "intrinsics": dict(K, pixel_center_offset=off),
        "camera_to_world": np.round(T_cam, 9).tolist(),
        "meters_per_unit": mpu,
        "objects": records,
        "camera_check": {"passed": bool(passed), "method": method, "objects": check},
        "robot": robot_record(stage, cfg, mpu, K, T_cam),
    }

    # Oracle keypoints for the original three-object scene (motion testing only; the VLM path does not need them).
    kp_path = None
    if passed and cfg.get("WRITE_ORACLE_KEYPOINTS", True) and \
            all(cfg[k] in objs for k in ("RED_PRIM", "CONE_PRIM", "SPHERE_PRIM")):
        try:
            legacy_objs = {"red": objs[cfg["RED_PRIM"]], "cone": objs[cfg["CONE_PRIM"]],
                           "sphere": objs[cfg["SPHERE_PRIM"]]}
            for v in legacy_objs.values():
                lo, hi = v["min"], v["max"]
                v["radius_xy"] = 0.5 * float(min(hi[0] - lo[0], hi[1] - lo[1]))
            caster = TriCaster(stage, mpu, robot_links + markers + [cfg["CAMERA_PRIM"]])
            kp, notes = make_keypoints(cfg, K, T_cam, legacy_objs, base_xy, caster, W, H)
            if kp["grasp_points"] and kp["placement_candidates"]:
                doc = {"schema": "dobot.keypoints/1", "source": "usd_projection_oracle",
                       "note": "Ground-truth keypoints from the USD scene for testing motion; not perception output.",
                       "capture": {"capture_id": cap_id, "image_sha256": img_sha},
                       "image_size": [W, H], "K": {k: K[k] for k in ("fx", "fy", "cx", "cy")}}
                doc.update(kp)
                kp_path = os.path.join(out_dir, "keypoints_2d_groundtruth.json")
                with open(kp_path, "w") as f:
                    json.dump(doc, f, indent=2)
        except Exception as e:
            _log(f"oracle keypoints skipped ({e})")
    try:
        draw_overlay(rgb, {}, boxes, os.path.join(out_dir, "capture_overlay.png"))
    except Exception:
        pass

    capture_json["keypoint_files"] = [os.path.basename(kp_path)] if kp_path else []
    with open(os.path.join(out_dir, "capture.json"), "w") as f:
        json.dump(capture_json, f, indent=2)
    if passed:
        with open(os.path.join(cfg["CAPTURE_ROOT"], "latest.json"), "w") as f:
            json.dump({"capture_id": cap_id, "capture_dir": out_dir}, f, indent=2)
        _log(f"OK: capture {cap_id} saved in {out_dir} and marked latest ({time.time() - t0:.1f} s); "
             f"{len(records)} objects: {', '.join(r['name'] for r in records.values())}")
    else:
        _log(f"capture {cap_id} saved for inspection in {out_dir} but NOT marked latest")
    return capture_json



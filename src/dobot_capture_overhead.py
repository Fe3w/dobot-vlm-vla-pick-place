def _gf_to_np(m):
    return np.array([[m[i][j] for j in range(4)] for i in range(4)], dtype=float).T


def _orthonormalize(R):
    U, _, Vt = np.linalg.svd(R)
    Rn = U @ Vt
    if np.linalg.det(Rn) < 0.0:
        U[:, -1] *= -1.0
        Rn = U @ Vt
    return Rn


def _under(path, prefix):
    if not path or not prefix:
        return False
    return path == prefix or path.startswith(prefix.rstrip("/") + "/")


def _usd_world(prim, mpu):
    M = _gf_to_np(UsdGeom.Xformable(prim).ComputeLocalToWorldTransform(Usd.TimeCode.Default()))
    M[:3, 3] *= mpu
    M[:3, :3] = _orthonormalize(M[:3, :3])
    return M


def _triangles_local(prim, t):
    if prim.IsA(UsdGeom.Mesh):
        mesh = UsdGeom.Mesh(prim)
        pts = mesh.GetPointsAttr().Get(t)
        counts = mesh.GetFaceVertexCountsAttr().Get(t)
        idx = mesh.GetFaceVertexIndicesAttr().Get(t)
        if pts is None or counts is None or idx is None or len(pts) == 0 or len(counts) == 0:
            return None
        pts = np.array(pts, dtype=float)
        counts = np.array(counts, dtype=np.int64)
        idx = np.array(idx, dtype=np.int64)
        starts = np.concatenate([[0], np.cumsum(counts)[:-1]])
        tris = []
        for k in range(1, int(counts.max()) - 1):
            s = starts[counts > k + 1]
            tris.append(np.stack([idx[s], idx[s + k], idx[s + k + 1]], axis=1))
        if not tris:
            return None
        tri = np.concatenate(tris)
        tri = tri[np.all(tri < len(pts), axis=1)]
        return pts[tri]
    ext = UsdGeom.Boundable.ComputeExtentFromPlugins(UsdGeom.Boundable(prim), t)
    if ext is None or len(ext) < 2:
        return None
    lo, hi = np.array(ext[0], dtype=float), np.array(ext[1], dtype=float)
    c = np.array([[lo[0], lo[1], lo[2]], [hi[0], lo[1], lo[2]], [hi[0], hi[1], lo[2]], [lo[0], hi[1], lo[2]],
                  [lo[0], lo[1], hi[2]], [hi[0], lo[1], hi[2]], [hi[0], hi[1], hi[2]], [lo[0], hi[1], hi[2]]])
    f = np.array([[0, 2, 1], [0, 3, 2], [4, 5, 6], [4, 6, 7], [0, 1, 5], [0, 5, 4],
                  [1, 2, 6], [1, 6, 5], [2, 3, 7], [2, 7, 6], [3, 0, 4], [3, 4, 7]])
    return c[f]


def _world_points(stage, root_path, mpu, max_pts=20000):
    root = stage.GetPrimAtPath(root_path)
    if not root.IsValid():
        return None
    t = Usd.TimeCode.Default()
    xc = UsdGeom.XformCache(t)
    pts = []
    for p in Usd.PrimRange(root, Usd.TraverseInstanceProxies()):
        if not p.IsA(UsdGeom.Gprim):
            continue
        tris = _triangles_local(p, t)
        if tris is None:
            continue
        L = np.unique(tris.reshape(-1, 3), axis=0)
        if len(L) > max_pts:
            L = L[:: len(L) // max_pts + 1]
        M = _gf_to_np(xc.GetLocalToWorldTransform(p))
        pts.append((L @ M[:3, :3].T + M[:3, 3]) * mpu)
    return np.concatenate(pts) if pts else None


class TriCaster:
    """CPU ray caster over visible Gprims (rigid bodies included)."""

    def __init__(self, stage, mpu, exclude):
        self.geoms = []
        t = Usd.TimeCode.Default()
        xc = UsdGeom.XformCache(t)
        for prim in Usd.PrimRange.Stage(stage, Usd.TraverseInstanceProxies()):
            if not prim.IsA(UsdGeom.Gprim):
                continue
            path = str(prim.GetPath())
            if any(_under(path, e) for e in exclude):
                continue
            img = UsdGeom.Imageable(prim)
            if img.ComputeVisibility(t) == UsdGeom.Tokens.invisible:
                continue
            if img.ComputePurpose() in (UsdGeom.Tokens.guide, UsdGeom.Tokens.proxy):
                continue
            tris = _triangles_local(prim, t)
            if tris is None or len(tris) == 0 or len(tris) > 400000:
                continue
            M = _gf_to_np(xc.GetLocalToWorldTransform(prim))
            Pw = ((tris.reshape(-1, 3) @ M[:3, :3].T) + M[:3, 3]) * mpu
            T = Pw.reshape(-1, 3, 3)
            self.add(path, T)

    def add(self, path, T):
        Pw = T.reshape(-1, 3)
        self.geoms.append({"path": path, "v0": T[:, 0], "e1": T[:, 1] - T[:, 0], "e2": T[:, 2] - T[:, 0],
                           "bmin": Pw.min(axis=0), "bmax": Pw.max(axis=0)})

    def first(self, o, d, max_dist=50.0):
        best = None
        with np.errstate(divide="ignore", invalid="ignore"):
            inv = 1.0 / d
        for g in self.geoms:
            with np.errstate(invalid="ignore"):
                t1, t2 = (g["bmin"] - 1e-6 - o) * inv, (g["bmax"] + 1e-6 - o) * inv
            t1 = np.where(np.isnan(t1), -np.inf, t1)
            t2 = np.where(np.isnan(t2), np.inf, t2)
            tn, tf = np.max(np.minimum(t1, t2)), np.min(np.maximum(t1, t2))
            if not (tf >= max(tn, 0.0) and tn <= max_dist):
                continue
            e1, e2 = g["e1"], g["e2"]
            p = np.cross(d, e2)
            det = np.einsum("ij,ij->i", e1, p)
            ok = np.abs(det) > 1e-14
            inv_det = np.where(ok, 1.0 / np.where(ok, det, 1.0), 0.0)
            s = o - g["v0"]
            u = np.einsum("ij,ij->i", s, p) * inv_det
            q = np.cross(s, e1)
            v = (q @ d) * inv_det
            tt = np.einsum("ij,ij->i", e2, q) * inv_det
            valid = ok & (u >= 0) & (v >= 0) & (u + v <= 1) & (tt > 1e-6) & (tt < max_dist)
            if np.any(valid):
                k = int(np.argmin(np.where(valid, tt, np.inf)))
                if best is None or tt[k] < best[0]:
                    best = (float(tt[k]), g["path"], o + float(tt[k]) * d)
        return best


def _robot_link_paths(stage, robot_path, urdf_path):
    """The controller's robot-link exclusion (URDF link names + joint bodies)."""
    import xml.etree.ElementTree as ET
    root = ET.parse(urdf_path).getroot()
    link_names = {l.get("name") for l in root.findall("link")}
    joint_names = {j.get("name") for j in root.findall("joint")}
    robot = stage.GetPrimAtPath(robot_path)
    paths = set()
    for p in Usd.PrimRange(robot, Usd.TraverseInstanceProxies()):
        if p == robot:
            continue
        if p.GetName() in link_names:
            paths.add(str(p.GetPath()))
        if p.GetName() in joint_names and p.IsA(UsdPhysics.Joint):
            j = UsdPhysics.Joint(p)
            for rel in (j.GetBody0Rel(), j.GetBody1Rel()):
                for t in rel.GetTargets():
                    if str(t) != robot_path:
                        paths.add(str(t))
    res = []
    for p in sorted(paths, key=len):
        if not any(_under(p, q) for q in res):
            res.append(p)
    return res


def _marker_paths(stage, robot_links, patterns):
    pats = tuple(p.lower() for p in patterns)
    found = []
    for p in Usd.PrimRange.Stage(stage, Usd.TraverseInstanceProxies()):
        path = str(p.GetPath())
        if any(_under(path, q) for q in found) or any(_under(path, r) for r in robot_links):
            continue
        if any(x in p.GetName().lower() for x in pats) and p.IsA(UsdGeom.Imageable):
            found.append(path)
    return found



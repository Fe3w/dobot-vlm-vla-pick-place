"""
Dobot overhead-camera capture (Isaac Sim 6.0.x Script Editor).

Makes the ONLY image source the pick-and-place pipeline should trust:
    1. renders /overhead_camera at exactly WIDTH x HEIGHT through a temporary
       Replicator render product (no viewport screenshot, no crop);
    2. saves rgb.png and capture.json next to it: image size + SHA-256,
       the intrinsics the controller will use, the camera-to-world pose, the
       object poses at capture time, the stage file, a capture id;
    3. checks the controller's camera model against the actual render: the red
       cylinder / purple cone / green sphere are found by colour in the PNG and
       compared with where the model projects them. If the red cylinder does
       not match, no keypoints are written;
    4. writes keypoints_2d_groundtruth.json bound to this capture (grasp points
       on the cylinder top, placement candidates beside the cone, obstacle
       points on cone and sphere), every pixel verified by a ray that hits the
       intended surface. These are ORACLE keypoints from the scene description,
       for testing the motion pipeline; the VLM step will later write
       keypoints_2d_vlm.json into the same folder, bound the same way;
    5. updates <CAPTURE_ROOT>/latest.json to point at this capture.

Safety: never starts/steps physics, never edits or saves the stage, never
commands joints. Run with the timeline STOPPED. Rendering happens on plain app
updates; only if that yields no frame does it ask Replicator to render one
frame with delta_time=0 and then confirms the timeline is still stopped.
"""


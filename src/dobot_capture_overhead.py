def object_info(stage, path, mpu):
    P = _world_points(stage, path, mpu)
    if P is None:
        return None
    lo, hi = P.min(axis=0), P.max(axis=0)
    return {"points": P, "min": lo, "max": hi, "center": (lo + hi) / 2,
            "radius_xy": 0.5 * float(min(hi[0] - lo[0], hi[1] - lo[1]))}


def make_keypoints(cfg, K, T_cam, objs, base_xy, caster, W, H):
    """Ray-verified grasp / placement / obstacle pixels. Returns (dict, list_of_notes)."""
    off = cfg["PIXEL_CENTER_OFFSET"]
    notes = []

    def first_hit(uv):
        o, d = pixel_ray(K, T_cam, uv[0], uv[1], off)
        return caster.first(o, d)

    def inside(uv, m=2.0):
        return np.all(np.isfinite(uv)) and m <= uv[0] < W - m and m <= uv[1] < H - m

    red, cone, sph = objs["red"], objs["cone"], objs["sphere"]
    grasps = []
    top_z = red["max"][2] - max(0.0005, min(0.002, (red["max"][2] - red["min"][2]) * 0.02))
    c = red["center"]
    r = red["radius_xy"]
    for k, (dx, dy) in enumerate([(0, 0), (0.3, 0), (-0.3, 0), (0, 0.3), (0, -0.3)]):
        p = np.array([c[0] + dx * r, c[1] + dy * r, top_z])
        uv = project(K, T_cam, p, off)[0]
        if not inside(uv):
            continue
        h = first_hit(uv)
        if h is None or not _under(h[1], cfg["RED_PRIM"]):
            notes.append(f"grasp candidate {k} skipped: first hit {h[1] if h else None}")
            continue
        grasps.append({"pixel_xy": [round(float(uv[0]), 2), round(float(uv[1]), 2)], "object": "red cylinder",
                       "prim": cfg["RED_PRIM"], "world_m": [round(float(x), 5) for x in h[2]]})

    places = []
    z_table = float(red["min"][2])
    dist = cone["radius_xy"] + r + cfg["PLACE_CLEARANCE_M"]
    cands = []
    for a_deg in range(0, 360, 45):
        a = math.radians(a_deg)
        p = np.array([cone["center"][0] + dist * math.cos(a), cone["center"][1] + dist * math.sin(a), z_table])
        if np.hypot(*(p[:2] - sph["center"][:2])) < sph["radius_xy"] + r + cfg["PLACE_SPHERE_MARGIN_M"]:
            notes.append(f"placement at {a_deg} deg skipped: too close to the sphere")
            continue
        if np.hypot(*(p[:2] - red["center"][:2])) < 2 * r:
            notes.append(f"placement at {a_deg} deg skipped: overlaps the cylinder's current spot")
            continue
        cands.append((float(np.hypot(*(p[:2] - base_xy))), a_deg, p))
    for _, a_deg, p in sorted(cands):              # nearest to the robot base first
        uv = project(K, T_cam, p, off)[0]
        if not inside(uv):
            notes.append(f"placement at {a_deg} deg skipped: outside the image")
            continue
        h = first_hit(uv)
        if h is None or any(_under(h[1], q) for q in (cfg["RED_PRIM"], cfg["CONE_PRIM"], cfg["SPHERE_PRIM"])):
            notes.append(f"placement at {a_deg} deg skipped: ray hits {h[1] if h else 'nothing'}, not the table")
            continue
        places.append({"pixel_xy": [round(float(uv[0]), 2), round(float(uv[1]), 2)],
                       "label": f"beside purple cone ({a_deg} deg)", "world_m": [round(float(x), 5) for x in h[2]]})

    obstacles = []
    for name, key, prim in (("green sphere", "sphere", cfg["SPHERE_PRIM"]), ("purple cone", "cone", cfg["CONE_PRIM"])):
        o = objs[key]
        h_lo, h_hi = o["min"][2], o["max"][2]
        pts = [np.array([o["center"][0], o["center"][1], h_lo + 0.9 * (h_hi - h_lo)])]
        for a_deg in range(0, 360, 60):
            a = math.radians(a_deg)
            pts.append(np.array([o["center"][0] + 0.6 * o["radius_xy"] * math.cos(a),
                                 o["center"][1] + 0.6 * o["radius_xy"] * math.sin(a), h_lo + 0.5 * (h_hi - h_lo)]))
        for p in pts:
            uv = project(K, T_cam, p, off)[0]
            if not inside(uv):
                continue
            h = first_hit(uv)
            if h is not None and _under(h[1], prim):
                obstacles.append({"pixel_xy": [round(float(uv[0]), 2), round(float(uv[1]), 2)], "object": name,
                                  "prim": prim})
    return {"grasp_points": grasps, "placement_candidates": places, "obstacle_points": obstacles}, notes


def draw_overlay(rgb, kp, boxes, path):
    try:
        from PIL import Image, ImageDraw
    except Exception:
        return False
    im = Image.fromarray(np.ascontiguousarray(rgb[..., :3], dtype=np.uint8))
    dr = ImageDraw.Draw(im)
    for name, (pbox, mbox) in boxes.items():
        if pbox:
            dr.rectangle(pbox, outline=(255, 255, 0), width=1)
        if mbox:
            dr.rectangle(mbox, outline=(0, 255, 255), width=1)
    for key, col, r in (("obstacle_points", (255, 60, 255), 4), ("placement_candidates", (255, 255, 255), 6),
                        ("grasp_points", (40, 255, 40), 6)):
        for i, p in enumerate(kp.get(key, [])):
            u, v = p["pixel_xy"]
            dr.ellipse([u - r, v - r, u + r, v + r], outline=col, width=2)
            if key != "obstacle_points":
                dr.text((u + 8, v - 12), f"{'G' if key == 'grasp_points' else 'P'}{i}", fill=col)
    dr.text((8, 8), "yellow = model projection, cyan = colour mask in render", fill=(255, 255, 255))
    im.save(path)
    return True



async def render_rgb(cam_path, W, H, cfg):
    """One RGB frame of cam_path at W x H plus, when available, instance segmentation of the same frame.

    Returns (rgb uint8 HxWx3, how, seg) where seg is (id_image HxW, {id: prim path}) or None.
    A paused render product kept from an earlier capture is tried first; if it gives no image it is destroyed,
    reuse is switched off for this Isaac Sim session and a new render product is made."""
    import builtins
    allow = bool(cfg.get("REUSE_RENDER_PRODUCT", True)) and not getattr(builtins, "_DOBOT_RP_REUSE_OFF", False)
    try:
        return await _render_once(cam_path, W, H, cfg, allow)
    except Exception as e:
        if not allow or getattr(builtins, "_DOBOT_CAPTURE_RP", None) is None or "Replicator started" in str(e):
            raise
        _log(f"the kept camera render product failed ({e}); making a new one (reuse off for this session)")
        c = builtins._DOBOT_CAPTURE_RP
        builtins._DOBOT_CAPTURE_RP = None
        builtins._DOBOT_RP_REUSE_OFF = True
        for a in (c.get("ann"), c.get("seg")):
            try:
                if a is not None:
                    a.detach([c["rp"]])
            except Exception:
                pass
        try:
            c["rp"].destroy()
        except Exception:
            pass
        return await _render_once(cam_path, W, H, cfg, False)


async def _render_once(cam_path, W, H, cfg, reuse):
    app = omni.kit.app.get_app()
    tl = omni.timeline.get_timeline_interface()
    mgr = app.get_extension_manager()
    if not mgr.is_extension_enabled("omni.replicator.core"):
        mgr.set_extension_enabled_immediate("omni.replicator.core", True)
    import omni.replicator.core as rep
    prev_cop = None
    try:
        prev_cop = rep.orchestrator.get_capture_on_play()
        rep.orchestrator.set_capture_on_play(False)    # let annotators update while the timeline is stopped
    except Exception:
        prev_cop = None
    rp, ann, seg_ann = None, None, None
    import builtins
    stage = omni.usd.get_context().get_stage()
    key = (id(stage), cam_path, W, H)
    cache = getattr(builtins, "_DOBOT_CAPTURE_RP", None)
    keep = False

    def drop(c):
        for a in (c.get("ann"), c.get("seg")):
            try:
                if a is not None:
                    a.detach([c["rp"]])
            except Exception:
                pass
        try:
            c["rp"].destroy()
        except Exception:
            pass

    def set_updates(r, on):
        try:
            r.hydra_texture.set_updates_enabled(bool(on))
            return True
        except Exception:
            return False

    def grab():
        d = ann.get_data()
        if isinstance(d, dict):
            d = d.get("data")
        if d is None:
            return None
        d = np.asarray(d)
        if d.ndim != 3 or d.shape[0] != H or d.shape[1] != W or d.shape[2] < 3:
            return None
        if float(d[..., :3].mean()) < 3.0:             # black frame: not rendered yet
            return None
        return np.array(d[..., :3], dtype=np.uint8)

    def grab_seg():
        if seg_ann is None:
            return None
        try:
            d = seg_ann.get_data()
            arr = np.asarray(d.get("data") if isinstance(d, dict) else d)
            info = d.get("info", {}) if isinstance(d, dict) else {}
            labels = info.get("idToLabels") or {}
            if arr.ndim == 3:
                arr = arr[..., 0]
            if arr.shape != (H, W) or not labels:
                return None
            mapping = {}
            for k, v in labels.items():
                if isinstance(v, dict):
                    v = v.get("class") or v.get("prim") or next(iter(v.values()), "")
                mapping[int(k)] = str(v)
            return arr.astype(np.int64), mapping
        except Exception:
            return None

    try:
        resumed = False
        if reuse and cache is not None and cache.get("key") == key:
            try:
                path = getattr(cache["rp"], "path", None)
                if (path is None or stage.GetPrimAtPath(str(path)).IsValid()) and set_updates(cache["rp"], True):
                    rp, ann, seg_ann, resumed = cache["rp"], cache["ann"], cache["seg"], True
            except Exception:
                resumed = False
        if not resumed:
            if cache is not None:
                drop(cache)
                builtins._DOBOT_CAPTURE_RP = None
            rp = rep.create.render_product(cam_path, (W, H))
            ann = rep.AnnotatorRegistry.get_annotator("rgb")
            ann.attach([rp])
            for name in ("instance_id_segmentation_fast", "instance_id_segmentation"):
                try:
                    seg_ann = rep.AnnotatorRegistry.get_annotator(name)
                    seg_ann.attach([rp])
                    break
                except Exception:
                    seg_ann = None
        else:
            for _ in range(int(cfg.get("FRESH_FRAMES", 8))):   # frames rendered before the resume are stale
                await app.next_update_async()
        good, frame = 0, None
        for _ in range(int(cfg["MAX_FRAMES"])):
            await app.next_update_async()
            f = grab()
            if f is None:
                good = 0
                continue
            good += 1
            frame = f
            if good >= int(cfg["WARMUP_FRAMES"]):
                return frame, "app updates", grab_seg()
        # Fallback: ask Replicator to render, without advancing simulation time.
        was_stopped = tl.is_stopped()
        for _ in range(int(cfg["WARMUP_FRAMES"])):
            try:
                await rep.orchestrator.step_async(rt_subframes=8, delta_time=0.0)
            except TypeError:
                await rep.orchestrator.step_async(rt_subframes=8)
            if was_stopped and not tl.is_stopped():
                tl.stop()
                for _ in range(30):
                    await app.next_update_async()
                raise RuntimeError("Replicator started the timeline while rendering; stopped it again. No image "
                                   "kept. Check the robot pose before continuing.")
            f = grab()
            if f is not None:
                frame = f
        if frame is None:
            raise RuntimeError("the render product produced no non-black RGB frame")
        return frame, "replicator step (delta_time=0)", grab_seg()
    finally:
        if rp is not None:
            # Keep it, paused (renders nothing while the robot moves), when the renderer lets us pause it.
            keep = reuse and set_updates(rp, False)
            if keep:
                builtins._DOBOT_CAPTURE_RP = {"key": key, "rp": rp, "ann": ann, "seg": seg_ann}
            else:
                drop({"rp": rp, "ann": ann, "seg": seg_ann})
                builtins._DOBOT_CAPTURE_RP = None
        if prev_cop is not None:
            try:
                rep.orchestrator.set_capture_on_play(prev_cop)
            except Exception:
                pass



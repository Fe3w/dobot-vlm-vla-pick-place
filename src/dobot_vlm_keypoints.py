def _read_file_key(path):
    if not path:
        return None
    if os.path.isfile(path):
        with open(path) as f:
            k = f.read().strip()
        return k or None
    return None


def _claude_bin(cfg=None):
    """The claude CLI. Isaac Sim started from the desktop often lacks the shell PATH, so look in the usual places."""
    import glob
    cands = [(cfg or {}).get("CLAUDE_BIN"), shutil.which("claude"),
             os.path.join(_HOME, ".local", "bin", "claude"), os.path.join(_HOME, ".claude", "local", "claude"),
             os.path.join(_HOME, ".npm-global", "bin", "claude"), "/usr/local/bin/claude", "/usr/bin/claude"]
    cands += sorted(glob.glob(os.path.join(_HOME, ".nvm", "versions", "node", "*", "bin", "claude")), reverse=True)
    for c in cands:
        if c and os.path.isfile(c) and os.access(c, os.X_OK):
            return c
    return None


def _claude_env(b):
    """Environment for the CLI: the subscription login is used, never an API key from Isaac Sim's environment."""
    env = dict(os.environ)
    for k in ("ANTHROPIC_API_KEY", "ANTHROPIC_AUTH_TOKEN", "CLAUDE_CODE_SIMPLE", "ANTHROPIC_BASE_URL"):
        env.pop(k, None)
    bindir = os.path.dirname(b)
    env["PATH"] = bindir + os.pathsep + env.get("PATH", "")          # node next to an nvm-installed CLI
    return env


def _http_json(url, headers=None, data=None, timeout=5.0, proxy=False):
    opener = urllib.request.build_opener() if proxy else urllib.request.build_opener(urllib.request.ProxyHandler({}))
    req = urllib.request.Request(url, data=data, headers=headers or {}, method="POST" if data else "GET")
    with opener.open(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8") or "{}"), dict(resp.headers)


def check_engines(cfg):
    """Health of every enabled route, checked in parallel (~1-5 s).

    Returns (usable_routes, report_lines). A route is usable when its endpoint answers, its key (if any)
    is accepted, and a named (non-"auto") model is offered by that endpoint."""
    engines = [e for e in cfg["ENGINES"] if e.get("enabled", True)]
    model_lists = {}

    def check(e):
        kind = e["kind"]
        if kind == "openai":
            key = _route_key(e)
            if e.get("key_file") and not key:
                return False, f"key file missing: {e['key_file']}"
            base = e["base"].rstrip("/")
            try:
                if base not in model_lists:
                    data, _ = _http_json(base + "/models",
                                         headers={"Authorization": f"Bearer {key}"} if key else {}, timeout=5,
                                         proxy=not _is_local(base))
                    model_lists[base] = [m.get("id", "") for m in data.get("data", []) if isinstance(m, dict)]
                ids = model_lists[base]
            except urllib.error.HTTPError as ex:
                if ex.code in (401, 403):
                    return False, f"key rejected (HTTP {ex.code})"
                return True, f"endpoint answered HTTP {ex.code}"
            except Exception as ex:
                return False, f"not reachable ({ex.__class__.__name__})"
            m = e["model"]
            if m.startswith("auto") or not ids:
                return True, f"ok ({len(ids)} models offered)"
            if any(i == m or i.endswith("/" + m) for i in ids):
                return True, "ok (model offered)"
            close = difflib.get_close_matches(m, ids, n=1, cutoff=0.6)
            return False, f"model '{m}' not offered" + (f" (closest: {close[0]})" if close else "")
        if kind == "claude_code":
            b = _claude_bin(cfg)
            if not b:
                return False, "claude CLI not found (set VLM['CLAUDE_BIN'])"
            try:
                r = subprocess.run([b, "auth", "status"], capture_output=True, text=True, timeout=15,
                                   env=_claude_env(b), stdin=subprocess.DEVNULL)
            except Exception as ex:
                return False, f"claude CLI failed ({ex.__class__.__name__})"
            if r.returncode != 0:
                return False, "not signed in (run `claude` once in a terminal and log in)"
            try:
                method = json.loads(r.stdout or "{}").get("authMethod")
            except Exception:
                method = None
            if method and method not in ("claude.ai", "oauth_token") and cfg.get("CLAUDE_REQUIRE_SUBSCRIPTION", True):
                return False, f"signed in with '{method}', not the Claude subscription (would bill API usage)"
            return True, f"signed in ({method or 'subscription'})"
        if kind == "anthropic":
            ok = bool(_route_key(e))
            return ok, "key found" if ok else "no key"
        return False, f"unknown kind {kind}"

    usable, lines = [], []
    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, len(engines))) as pool:
        for e, (ok, why) in zip(engines, pool.map(check, engines)):
            lines.append(f"{e['id']:13s} {'up  ' if ok else 'DOWN'} {why}")
            if ok:
                usable.append(e)
    for l in lines:
        _log("route " + l)
    return usable, lines


def _user_text(task, n_marks, hints=None):
    tags = ", ".join(str(i) for i in range(1, n_marks + 1))
    hint = ""
    if hints:
        hint = ("Scene-model guess for each tag (trust the image if it disagrees): "
                + "; ".join(f"{m} = {h}" for m, h in hints) + ".\n")
    return f"Instruction: {task}\nTagged objects: {tags}.\n{hint}Answer with the JSON object only."


def build_body(engine, task, img, n_marks, structured=True, hints=None):
    b64 = base64.b64encode(img).decode("ascii")
    if engine["kind"] == "anthropic":
        body = {"model": engine["model"], "max_tokens": 600, "system": SYSTEM_PROMPT,
                "messages": [{"role": "user", "content": [
                    {"type": "image", "source": {"type": "base64", "media_type": "image/jpeg", "data": b64}},
                    {"type": "text", "text": _user_text(task, n_marks, hints)}]}]}
        if structured:
            body["output_config"] = {"format": {"type": "json_schema", "schema": ANSWER_SCHEMA}}
        return body
    body = {"model": engine["model"], "temperature": 0, "max_tokens": 400,
            "messages": [{"role": "system", "content": SYSTEM_PROMPT},
                         {"role": "user", "content": [
                             {"type": "text", "text": _user_text(task, n_marks, hints)},
                             {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{b64}"}}]}]}
    if structured:
        body["response_format"] = {"type": "json_object"}
    return body


def redact(body, image_sha):
    def walk(x):
        if isinstance(x, dict):
            out = {}
            for k, v in x.items():
                if (k == "data" and x.get("type") == "base64") or \
                        (k == "url" and isinstance(v, str) and v.startswith("data:")):
                    out[k] = f"<image base64 omitted; sha256={image_sha}>"
                else:
                    out[k] = walk(v)
            return out
        if isinstance(x, list):
            return [walk(v) for v in x]
        return x
    return walk(body)


def _call_http(engine, cfg, task, img, n_marks, hints=None):
    kind = engine["kind"]
    if kind == "anthropic":
        key = _route_key(engine) or ""
        url = "https://api.anthropic.com/v1/messages"
        headers = {"content-type": "application/json", "anthropic-version": "2023-06-01", "x-api-key": key}
        proxy = True
    else:
        key = _route_key(engine)
        url = engine["base"].rstrip("/") + "/chat/completions"
        headers = {"Content-Type": "application/json"}
        if key:
            headers["Authorization"] = f"Bearer {key}"
        proxy = not _is_local(url)
    structured = True
    for _ in range(2):
        body = build_body(engine, task, img, n_marks, structured, hints)
        try:
            raw, hdrs = _http_json(url, headers=headers, data=json.dumps(body).encode("utf-8"),
                                   timeout=cfg["ROUTE_TIMEOUT_S"], proxy=proxy)
        except urllib.error.HTTPError as e:
            detail = e.read().decode("utf-8", "replace")[:300]
            if e.code == 400 and structured:
                structured = False
                continue
            raise RuntimeError(f"HTTP {e.code}: {detail}")
        if kind == "anthropic":
            if raw.get("stop_reason") == "refusal":
                raise RuntimeError("declined")
            text = "".join(b.get("text", "") for b in raw.get("content", []) if b.get("type") == "text")
            return text, raw.get("model"), raw
        content = raw["choices"][0]["message"]["content"]
        if isinstance(content, list):
            content = "".join(p.get("text", "") for p in content if isinstance(p, dict))
        served = hdrs.get("X-Routed-Via") or hdrs.get("x-routed-via") or raw.get("model") or engine["model"]
        return content, served, raw
    raise RuntimeError("request rejected")


_SAFE_MODE_OK = {"value": True}


def _call_claude_code(engine, cfg, task, img_path, n_marks, procs, hints=None):
    b = _claude_bin(cfg)
    if not b:
        raise RuntimeError("claude CLI not found")
    env = _claude_env(b)
    prompt = (f"Read the image file {img_path} (it is the overhead camera picture with numbered tags), "
              f"then answer.\n" + _user_text(task, n_marks, hints))
    for attempt in range(2):
        cmd = [b, "-p", prompt, "--output-format", "json", "--json-schema", json.dumps(ANSWER_SCHEMA),
               "--model", engine.get("model") or "haiku", "--tools", "Read", "--allowedTools", "Read",
               "--permission-mode", "dontAsk", "--no-session-persistence", "--max-turns", "4",
               "--system-prompt", SYSTEM_PROMPT + "\nUse the Read tool to view the image file you are given."]
        if _SAFE_MODE_OK["value"]:
            cmd.append("--safe-mode")
        p = subprocess.Popen(cmd, cwd=os.path.dirname(img_path), stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                             text=True, stdin=subprocess.DEVNULL, env=env, start_new_session=True)
        procs.append(p)
        try:
            out, err = p.communicate(timeout=cfg["CLI_TIMEOUT_S"])
        except subprocess.TimeoutExpired:
            try:
                os.killpg(p.pid, 9)
            except Exception:
                p.kill()
            raise RuntimeError("claude CLI timed out")
        if p.returncode != 0 and _SAFE_MODE_OK["value"] and "safe-mode" in (err or "") and attempt == 0:
            _SAFE_MODE_OK["value"] = False          # older CLI without --safe-mode
            continue
        try:
            raw = json.loads(out)
        except Exception:
            raise RuntimeError(f"claude CLI exit {p.returncode}: {(err or out)[:200]}")
        if raw.get("is_error"):
            raise RuntimeError(f"claude CLI error: {str(raw.get('result'))[:200]}")
        so = raw.get("structured_output")
        text = json.dumps(so) if so is not None else raw.get("result", "")
        return text, f"claude-code/{engine.get('model') or 'default'}", raw
    raise RuntimeError("claude CLI failed")



"""
Dobot VLM engine: typed task + captured image -> keypoints_2d_vlm.json

Turns a typed natural-language task into keypoints the V3 runner will accept,
using the latest capture from dobot_capture_overhead.py.

How it decides
    * Set-of-marks: every candidate object in the captured image gets a numbered
      tag. A vision-language model (VLM) only answers WHICH tag is the target,
      which is the placement reference, the relation and which tags to avoid.
      Exact pixels come from the capture's geometry; V3/V2 verify every pixel
      with live rays before the arm moves.
    * Multi-route racing: the request goes to several model routes at once
      (ENGINES). The first answer that agrees with an unambiguous reading of the
      typed task is accepted immediately; otherwise two routes must agree.
      A hard deadline (DEADLINE_S) bounds the wait.
    * Wording parser: reads object words (typo tolerant) and the relation phrase.
      Model answers that contradict an unambiguous wording are rejected. If no
      route answers in time, an unambiguous task is decided from its wording.

Routes (ENGINES; chosen by VLM_PROVIDER in the repo's .env, see .env.example)
    kind "openai"       any OpenAI-compatible endpoint: the local FreeLLMAPI
                        router (several models / strategies) or Ollama.
    kind "claude_code"  the Claude Code CLI in headless mode (claude -p) on the
                        signed-in Claude subscription (on by default, Sonnet);
                        one background process per request, read-only access
                        to the tagged image, killed at the deadline. API keys
                        in Isaac Sim's environment are removed for this call,
                        so it never bills API usage.
    kind "anthropic"    Claude API with a separately billed key.

Output
    <capture_dir>/keypoints_2d_vlm.json   bound to the capture (id + image hash)
    <capture_dir>/vlm_runs/<run_id>/      tagged image, redacted request, every
                                          route's raw response, decision record
    A previous keypoints_2d_vlm.json is moved aside first.

Secrets: keys are read from .env / the environment (VLM_API_KEY, ANTHROPIC_API_KEY) or a key file
(VLM_API_KEY_FILE), sent only in request headers to their own endpoint, never printed or written to any file.

Run: normally via dobot_run_task.py. Alone in the Script Editor a small task
window opens. Terminal: python3 dobot_vlm_keypoints.py [--task "..."]
[--capture DIR] [--dry-run] [--routes router-fast,local].
"""


def engine_label(cfg):
    return "VLM engine"


def clean_task(text, cfg=VLM):
    if not isinstance(text, str):
        raise ValueError("no task given")
    t = "".join(ch if ch.isprintable() else " " for ch in text)
    t = re.sub(r"\s+", " ", t).strip()
    if len(t) < 3:
        raise ValueError("type a task first, e.g. 'pick the red cylinder and place it beside the purple cone'")
    if len(t) > cfg["MAX_TASK_CHARS"]:
        raise ValueError(f"task is {len(t)} characters; keep it under {cfg['MAX_TASK_CHARS']}")
    return t


def _last_task_path(cfg):
    return os.path.join(cfg["CAPTURE_ROOT"], "last_task.txt")


def load_last_task(cfg=VLM):
    try:
        with open(_last_task_path(cfg)) as f:
            return f.read().strip() or TASK
    except OSError:
        return TASK


def save_last_task(cfg, text):
    try:
        os.makedirs(cfg["CAPTURE_ROOT"], exist_ok=True)
        with open(_last_task_path(cfg), "w") as f:
            f.write(text + "\n")
    except OSError:
        pass


def prepare(cfg, task_text):
    cap_dir, cap, png = load_capture(cfg)
    cfg = scene_cfg(cfg, cap)
    run_id = time.strftime("%Y%m%dT%H%M%S") + "_" + uuid.uuid4().hex[:6]
    run_dir = os.path.join(cap_dir, "vlm_runs", run_id)
    os.makedirs(run_dir)
    old = os.path.join(cap_dir, "keypoints_2d_vlm.json")
    if os.path.isfile(old):
        shutil.move(old, os.path.join(run_dir, "superseded_keypoints_2d_vlm.json"))
    cands = candidates(cap, cfg)
    if len(cands) < 2:
        raise RuntimeError("fewer than two objects visible in the capture (the target and a placement reference)")
    if not cfg["PICKABLE_PRIMS"]:
        raise RuntimeError("no object in the scene can be picked: give it Physics > Rigid Body with Colliders "
                           "and save the scene")
    pick = set(cfg["PICKABLE_PRIMS"])
    hints = [(m, ("robot base, never the target" if k == "robot" else
                  name_of(cfg, p) + (", pickable" if p in pick else ", fixed")))
             for m, k, p, _ in cands]
    img, img_path = draw_marks(png, cands, run_dir, cfg)
    img_sha = _sha256_bytes(img)
    sample = next((e for e in cfg["ENGINES"] if e.get("enabled", True) and e["kind"] != "claude_code"), None)
    with open(os.path.join(run_dir, "request_redacted.json"), "w") as f:
        json.dump({"task": task_text, "marks": {m: p for m, _, p, _ in cands}, "hints": hints,
                   "routes": [{k: v for k, v in e.items() if k != "key_file"} for e in cfg["ENGINES"]
                              if e.get("enabled", True)],
                   "example_body": redact(build_body(sample, task_text, img, len(cands)), img_sha) if sample else None},
                  f, indent=2)
    _log(f"capture {cap['capture_id']}; {len(cands)} tagged objects "
         f"({', '.join(f'{m}={name_of(cfg, p)}' for m, _, p, _ in cands)}); run {run_id}; image {len(img) // 1024} KB")
    return {"cap_dir": cap_dir, "cap": cap, "run_dir": run_dir, "run_id": run_id, "cands": cands,
            "img": img, "img_path": img_path, "img_sha": img_sha, "task_text": task_text, "cfg": cfg,
            "hints": hints}


def write_outputs(cfg, ctx, task, problems, meta):
    run_dir, cap = ctx["run_dir"], ctx["cap"]
    result = {"run_id": ctx["run_id"], "task_text": ctx["task_text"], "capture_id": cap["capture_id"],
              "marks": {m: p for m, _, p, _ in ctx["cands"]}, "decision": meta}
    kp = None
    if task is not None:
        kp = build_keypoints(cap, task, cfg, [p for _, _, p, _ in ctx["cands"]])
        if not kp["grasp_points"]:
            problems = problems + [f"the {name_of(cfg, task['target_prim'])} is not visible to the camera"]
        if not kp["placement_candidates"]:
            problems = problems + [f"no free table spot {RELATION_TEXT[task['relation']]} the "
                                   f"{name_of(cfg, task['reference_prim'])}"]
    result["problems"] = problems
    ctx["problems"] = problems
    if task is None or problems:
        result["status"] = "rejected"
        with open(os.path.join(run_dir, "result.json"), "w") as f:
            json.dump(result, f, indent=2)
        for p in problems:
            _log(f"REJECTED: {p}")
        return None
    doc = {"schema": "dobot.keypoints/1", "source": "vlm_engine_set_of_marks",
           "capture": {"capture_id": cap["capture_id"], "image_sha256": cap["image"]["sha256"]},
           "image_size": [cap["image"]["width"], cap["image"]["height"]],
           "K": {k: cap["intrinsics"][k] for k in ("fx", "fy", "cx", "cy")},
           "objects": {p: name_of(cfg, p) for _, _, p, _ in ctx["cands"]},
           "task": dict(task, task_text=ctx["task_text"], run_id=ctx["run_id"],
                        target_name=name_of(cfg, task["target_prim"]),
                        reference_name=name_of(cfg, task["reference_prim"]),
                        avoid_names=[name_of(cfg, p) for p in task["avoid_prims"]],
                        routed_via=", ".join(meta.get("served_by") or []) or None,
                        decided_by=meta.get("decided_by"), seconds=meta.get("seconds"))}
    doc.update(kp)
    out = os.path.join(ctx["cap_dir"], "keypoints_2d_vlm.json")
    with open(out, "w") as f:
        json.dump(doc, f, indent=2)
    result.update(status="accepted", task=task, keypoints_file=out, counts={k: len(v) for k, v in kp.items()})
    with open(os.path.join(run_dir, "result.json"), "w") as f:
        json.dump(result, f, indent=2)
    _log(f"decided by {meta.get('decided_by')} in {meta.get('seconds')} s via {doc['task']['routed_via'] or '-'}: "
         f"{summary(doc, cfg)}")
    return doc


def public(text):
    """Text for the window: route ids and provider/product names are replaced by 'VLM engine'."""
    t = re.sub(r"\s*\(set VLM\[[^\]]*\]\)", "", str(text))          # config hints belong in the terminal
    t = re.sub(r"\b(?:router-[\w-]+|claude-code|claude-api|local)\s*:\s*", "", t)
    t = re.sub(r"(?i)\b(?:claude[\s-]*code(?:\s*cli)?|claude\s*(?:cli|api)|claude|anthropic|freellmapi|ollama)\b",
               "VLM engine", t)
    t = re.sub(r"(?:VLM engine\s*){2,}", "VLM engine ", t)
    return re.sub(r"\s+", " ", t).strip()


def summary(doc, cfg=VLM):
    t = doc["task"]
    names = dict(cfg["OBJECT_NAMES"], **(doc.get("objects") or {}))
    cfg = dict(cfg, OBJECT_NAMES=names)
    avoid = ", ".join(name_of(cfg, p) for p in t["avoid_prims"]) or "nothing"
    how = re.sub(r"\s*\(.*?\)|\s*\d+/\d+", "", str(t.get("decided_by") or ""))   # route ids / counts: console only
    return (f"{name_of(cfg, t['target_prim'])} -> {RELATION_TEXT[t['relation']]} {name_of(cfg, t['reference_prim'])}"
            f" · avoid {avoid} · {how} · {t.get('seconds')} s")


def _ground_blocking(cfg, task_text, routes=None):
    ctx = prepare(cfg, task_text)
    cfg = ctx["cfg"]
    if routes is None:
        routes, _ = check_engines(cfg)
    if not routes:
        _log("no VLM route is up; deciding from the task wording if it is unambiguous")
    task, problems, meta = decide(cfg, ctx, routes) if routes else (None, ["VLM engine offline"], {"calls": []})
    if task is None and not routes and cfg["KEYWORD_FALLBACK"]:
        parse, notes = keyword_parse(task_text, cfg, [p for _, _, p, _ in ctx["cands"]])
        t = _task_from_parse(parse, ctx["cands"], cfg)
        if t is not None:
            task, problems = t, []
            meta = {"calls": [], "wording": parse, "decided_by": "task wording (VLM engine offline)", "seconds": 0.0}
        else:
            problems = problems + notes
    return write_outputs(cfg, ctx, task, problems, meta), ctx


def run_blocking(cfg=VLM, task_text=None, dry_run=False):
    task_text = clean_task(task_text if task_text is not None else cfg["TASK"], cfg)
    save_last_task(cfg, task_text)
    if dry_run:
        ctx = prepare(cfg, task_text)
        _log(f"dry run: request written to {ctx['run_dir']} (no model call)")
        return None
    doc, _ = _ground_blocking(cfg, task_text)
    return doc


async def run_async(cfg=VLM, task_text=None, routes=None):
    """Grounding on a worker thread. Returns (doc|None, one-line message)."""
    try:
        task_text = clean_task(task_text if task_text is not None else cfg["TASK"], cfg)
        save_last_task(cfg, task_text)
        loop = asyncio.get_event_loop()
        doc, ctx = await loop.run_in_executor(None, _ground_blocking, cfg, task_text, routes)
        if doc is None:
            probs = list(dict.fromkeys(public(p) for p in (ctx.get("problems") or ["no usable answer"])))
            return None, "Not understood: " + "; ".join(probs)
        return doc, public(summary(doc, cfg))
    except Exception as e:
        _log(f"FAILED: {e}")
        return None, public(f"VLM engine error: {e}")



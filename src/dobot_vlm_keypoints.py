_REL_PHRASES = [("on the other side of", "opposite_side"), ("other side of", "opposite_side"),
                ("opposite side of", "opposite_side"), ("far side of", "opposite_side"),
                ("across from", "opposite_side"), ("opposite", "opposite_side"),
                ("to the left of", "left_of"), ("left of", "left_of"), ("to the right of", "right_of"),
                ("right of", "right_of"), ("in front of", "in_front_of"), ("behind", "behind"),
                ("next to", "beside"), ("beside", "beside"), ("near", "beside"), ("by", "beside")]
_AVOID_PHRASES = ["avoiding", "avoid", "away from", "without touching", "don't touch", "do not touch",
                  "not touch", "keep clear of", "stay clear of", "steer clear of", "around"]


def _fix_typos(text, cfg):
    vocab = sorted({w for ws in cfg["OBJECT_WORDS"].values() for w in ws if len(w) >= 4})
    out = []
    for tok in text.split(" "):
        if len(tok) >= 4 and tok not in vocab and tok.rstrip("s") not in vocab:
            m = difflib.get_close_matches(tok, vocab, n=1, cutoff=0.8)
            if m:
                tok = m[0]
        out.append(tok)
    return " ".join(out)


def keyword_parse(task, cfg, prims):
    """{"target", "reference", "relation", "avoid"}; a role is set only when exactly one object is named."""
    t = " " + re.sub(r"[^a-z' ]+", " ", task.lower()) + " "
    t = re.sub(r"\s+", " ", t)
    t = _fix_typos(t, cfg)
    rel, rel_pos, rel_end = None, None, None
    for phrase, r in _REL_PHRASES:
        m = re.search(r"\b" + re.escape(phrase) + r"\b", t)
        if m and (rel_pos is None or m.start() < rel_pos):
            rel, rel_pos, rel_end = r, m.start(), m.end()
    avoid_pos = None
    for phrase in _AVOID_PHRASES:
        m = re.search(r"\b" + re.escape(phrase) + r"\b", t)
        if m and (avoid_pos is None or m.start() < avoid_pos):
            avoid_pos = m.start()
    end = len(t)
    seg_target = t[: min(x for x in (rel_pos, avoid_pos, end) if x is not None)]
    seg_ref = t[rel_end: (avoid_pos if avoid_pos is not None and avoid_pos > rel_pos else end)] \
        if rel_pos is not None else ""
    seg_avoid = t[avoid_pos: (rel_pos if rel_pos is not None and rel_pos > avoid_pos else end)] \
        if avoid_pos is not None else ""

    def named(seg):
        """Objects the segment names. With shared words ('red box' vs 'red cylinder') the best match wins;
        a tie between equally good matches returns all of them (ambiguous)."""
        score = {}
        for p in prims:
            n = sum(1 for w in cfg["OBJECT_WORDS"].get(p, []) if re.search(r"\b" + re.escape(w) + r"s?\b", seg))
            if n:
                score[p] = n
        if not score:
            return []
        hi = max(score.values())
        return [p for p in prims if score.get(p) == hi]
    notes = []
    tg, rf, av = named(seg_target), named(seg_ref), named(seg_avoid)
    target = tg[0] if len(tg) == 1 else None
    reference = rf[0] if len(rf) == 1 else None
    if len(tg) > 1:
        notes.append(f"several objects named before the placement phrase: {[name_of(cfg, p) for p in tg]}")
    if len(rf) > 1:
        notes.append(f"several objects named after the relation phrase: {[name_of(cfg, p) for p in rf]}")
    return {"target": target, "reference": reference, "relation": rel,
            "avoid": [p for p in av if p not in (target, reference)]}, notes



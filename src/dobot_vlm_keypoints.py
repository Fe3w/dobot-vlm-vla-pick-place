def scene_cfg(cfg, cap):
    """Per-run copy of cfg whose objects come from the capture (objects added to or deleted from the scene).

    Old captures (schema 1) keep the configured three objects. Configured names/words for a path are used
    only when they still describe the same kind of object (a prim reused for a different shape is renamed)."""
    objs = cap.get("objects") or {}
    if cap.get("schema") != "dobot.capture/2" or not objs:
        return cfg
    c = dict(cfg)
    vis = [(p, o) for p, o in objs.items() if o.get("visible") and o.get("box")]
    vis.sort(key=lambda po: ((po[1]["box"][0] + po[1]["box"][2]) / 2, po[0]))     # tags left to right
    names, words = {}, {}
    for p, o in vis:
        auto = o.get("name") or p.rsplit("/", 1)[-1]
        shape = o.get("shape") or "object"
        conf = cfg["OBJECT_NAMES"].get(p)
        same = conf and (shape == "object" or any(w in conf.split() for w in _SHAPE_SYNONYMS.get(shape, [shape])))
        names[p] = conf if same else auto
        ws = set(o.get("words") or []) | set(names[p].split())
        if same:
            ws |= set(cfg["OBJECT_WORDS"].get(p, []))
        words[p] = sorted(w.lower() for w in ws if w and not w.isdigit())
    seen = {}
    for p, _ in vis:
        seen.setdefault(names[p], []).append(p)
    for n, ps in seen.items():
        if len(ps) > 1:                                   # two objects look alike: number them left to right
            for i, p in enumerate(ps, 1):
                names[p] = f"{n} {i}"
    rob = (cap.get("robot") or {}).get("prim")
    if rob:
        names[rob] = cfg["OBJECT_NAMES"].get(rob, "robot")
        words[rob] = list(cfg["OBJECT_WORDS"].get(rob, ["robot"]))
    c["CANDIDATES"] = [(p, p) for p, _ in vis]
    c["OBJECT_NAMES"] = names
    c["OBJECT_WORDS"] = words
    c["PICKABLE_PRIMS"] = [p for p, o in vis if o.get("pickable")]
    return c


def candidates(cap, cfg):
    out = []
    if cap.get("schema") == "dobot.capture/2" and cap.get("objects"):
        for _, prim in cfg["CANDIDATES"]:
            o = cap["objects"].get(prim) or {}
            if o.get("visible") and o.get("box"):
                out.append((len(out) + 1, prim, prim, o["box"]))
        rob = cap.get("robot") or {}
        if cfg.get("ROBOT_AS_REFERENCE", True) and rob.get("prim") and rob.get("projected_box"):
            out.append((len(out) + 1, "robot", rob["prim"], rob["projected_box"]))
        return out
    checks = cap["camera_check"]["objects"]
    for key, prim in cfg["CANDIDATES"]:
        c = checks.get(key, {})
        box = c.get("mask_box") or c.get("projected_box")
        if box is None or prim not in cap["objects"]:
            continue
        out.append((len(out) + 1, key, prim, box))
    rob = cap.get("robot") or {}
    if cfg.get("ROBOT_AS_REFERENCE", True) and rob.get("prim") and rob.get("projected_box"):
        out.append((len(out) + 1, "robot", rob["prim"], rob["projected_box"]))
    return out


def draw_marks(png_bytes, cands, run_dir, cfg):
    """Tagged image: full-size PNG for the record, downscaled JPEG to send. Returns (jpeg_bytes, jpeg_path)."""
    from io import BytesIO

    from PIL import Image, ImageDraw, ImageFont
    im = Image.open(BytesIO(png_bytes)).convert("RGB")
    dr = ImageDraw.Draw(im)
    try:
        font = ImageFont.load_default(size=24)
    except TypeError:
        font = ImageFont.load_default()
    for mark, _, _, box in cands:
        x0, y0, x1, y1 = box
        dr.rectangle([x0 - 3, y0 - 3, x1 + 3, y1 + 3], outline=(255, 255, 255), width=3)
        cx, ty = (x0 + x1) / 2, max(18, y0 - 24)
        dr.ellipse([cx - 17, ty - 17, cx + 17, ty + 17], fill=(255, 255, 255), outline=(0, 0, 0), width=2)
        try:
            dr.text((cx, ty), str(mark), fill=(0, 0, 0), font=font, anchor="mm")
        except Exception:
            dr.text((cx - 6, ty - 9), str(mark), fill=(0, 0, 0), font=font)
    im.save(os.path.join(run_dir, "marked.png"))
    side = int(cfg["SEND_MAX_SIDE"])
    if max(im.size) > side:
        s = side / max(im.size)
        im = im.resize((round(im.size[0] * s), round(im.size[1] * s)), Image.LANCZOS)
    buf = BytesIO()
    im.save(buf, format="JPEG", quality=int(cfg["JPEG_QUALITY"]))
    path = os.path.join(run_dir, "marked_send.jpg")
    with open(path, "wb") as f:
        f.write(buf.getvalue())
    return buf.getvalue(), path



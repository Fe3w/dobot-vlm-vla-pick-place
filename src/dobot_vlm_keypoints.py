def _routes_from_env(cfg, env):
    """ENGINES from the .env settings (VLM_PROVIDER etc.). No VLM_PROVIDER: the ENGINES above are kept.

    VLM_PROVIDER=openai       any OpenAI-compatible endpoint (OpenAI, OpenRouter, Gemini's OpenAI endpoint,
                              Groq, Together, a local Ollama / vLLM / LM Studio / FreeLLMAPI router):
                              VLM_API_BASE, VLM_MODEL and VLM_API_KEY (or VLM_API_KEY_FILE; none for local servers)
    VLM_PROVIDER=anthropic    Claude API: ANTHROPIC_API_KEY (or VLM_API_KEY / VLM_API_KEY_FILE), VLM_MODEL
    VLM_PROVIDER=claude_code  the signed-in Claude Code CLI (subscription); VLM_MODEL = sonnet / haiku
    VLM_PROVIDER=none         no model: the typed task's wording decides (works for unambiguous tasks)
    Several providers: comma-separated (e.g. "openai,claude_code"); they are raced and must agree.
    """
    prov = [x.strip().lower() for x in (env.get("VLM_PROVIDER") or "").split(",") if x.strip()]
    if not prov:
        return
    model = env.get("VLM_MODEL") or ""
    key_file = env.get("VLM_API_KEY_FILE") or None
    engines = []
    for p in prov:
        if p == "openai":
            engines.append({"id": "openai", "kind": "openai", "base": env.get("VLM_API_BASE") or "https://api.openai.com/v1",
                            "model": model or "gpt-4o-mini", "key_env": "VLM_API_KEY", "key_file": key_file,
                            "enabled": True})
        elif p == "anthropic":
            engines.append({"id": "anthropic", "kind": "anthropic", "model": model or "claude-haiku-4-5",
                            "key_env": "VLM_API_KEY", "key_file": key_file, "enabled": True})
        elif p in ("claude_code", "claude-code"):
            engines.append({"id": "claude-code", "kind": "claude_code", "model": env.get("VLM_CLAUDE_CODE_MODEL")
                            or (model if model in ("sonnet", "haiku", "opus") else "sonnet"), "enabled": True})
        elif p != "none":
            raise ValueError(f"VLM_PROVIDER: unknown provider '{p}' (openai, anthropic, claude_code, none)")
    cfg["ENGINES"] = engines
    cfg["VOTES"] = max(1, min(int(cfg.get("VOTES", 2)), len(engines)))
    for k, cast in (("VLM_DEADLINE_S", "DEADLINE_S"), ("VLM_ROUTE_TIMEOUT_S", "ROUTE_TIMEOUT_S")):
        if env.get(k):
            cfg[cast] = float(env[k])



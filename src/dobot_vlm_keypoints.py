def parse_answer(text):
    if not isinstance(text, str) or not text.strip():
        raise ValueError("empty reply")
    t = re.sub(r"^```(?:json)?\s*|\s*```$", "", text.strip(), flags=re.S)
    try:
        return json.loads(t)
    except Exception:
        pass
    start = t.find("{")
    if start < 0:
        raise ValueError("no JSON object in reply")
    depth = 0
    for i in range(start, len(t)):
        depth += t[i] == "{"
        depth -= t[i] == "}"
        if depth == 0:
            return json.loads(t[start:i + 1])
    raise ValueError("unterminated JSON object")


def _as_mark(v, n):
    if v is None:
        return None
    if isinstance(v, bool):
        raise ValueError("mark must be a number")
    if isinstance(v, str) and v.strip().isdigit():
        v = int(v.strip())
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    if not isinstance(v, int) or not 1 <= v <= n:
        raise ValueError(f"mark {v!r} is not one of 1..{n}")
    return v


def _norm_relation(rel):
    rel = str(rel or "beside").strip().lower().replace(" ", "_").replace("-", "_")
    return {"next_to": "beside", "near": "beside", "left": "left_of", "right": "right_of",
            "in_front": "in_front_of", "front_of": "in_front_of", "behind_of": "behind",
            "opposite": "opposite_side", "other_side": "opposite_side", "far_side": "opposite_side",
            "other_side_of": "opposite_side", "opposite_side_of": "opposite_side"}.get(rel, rel)


def validate_answer(ans, cands, cfg):
    n = len(cands)
    by_mark = {m: p for m, _, p, _ in cands}
    if not isinstance(ans, dict):
        return None, ["reply is not a JSON object"]
    try:
        tgt = _as_mark(ans.get("target_mark"), n)
        ref = _as_mark(ans.get("reference_mark"), n)
        avoid = [_as_mark(a, n) for a in (ans.get("avoid_marks") or [])]
    except ValueError as e:
        return None, [str(e)]
    rel = _norm_relation(ans.get("relation"))
    try:
        conf = float(ans.get("confidence", 0.0))
    except (TypeError, ValueError):
        conf = float("nan")
    problems = []
    if tgt is None:
        problems.append("no tagged object matches the target")
    elif by_mark[tgt] not in cfg["PICKABLE_PRIMS"]:
        problems.append(f"the {name_of(cfg, by_mark[tgt])} cannot be picked: it is fixed in the scene (to make "
                        f"it pickable give it Physics > Rigid Body with Colliders and save)")
    if ref is None:
        problems.append("the task does not say where to place it relative to something the camera can see "
                        "(e.g. beside the purple cone, behind the robot)")
    elif ref == tgt:
        problems.append("reference and target are the same object")
    if rel not in RELATIONS:
        problems.append(f"relation {rel!r} not supported")
    if not (conf == conf) or not 0.0 <= conf <= 1.0:
        problems.append("confidence missing or out of range")
    elif conf < cfg["MIN_CONFIDENCE"]:
        problems.append(f"low confidence {conf:.2f}")
    if problems:
        return None, problems
    avoid = sorted({a for a in avoid if a not in (tgt, ref)})
    return {"target_mark": tgt, "target_prim": by_mark[tgt], "reference_mark": ref,
            "reference_prim": by_mark[ref], "relation": rel, "avoid_marks": avoid,
            "avoid_prims": [by_mark[a] for a in avoid], "confidence": conf,
            "target_description": str(ans.get("target_description", ""))[:200],
            "reference_description": str(ans.get("reference_description", ""))[:200],
            "notes": str(ans.get("notes", ""))[:400]}, []


def _contradicts(task, parse, cfg):
    out = []
    if parse["target"] and task["target_prim"] != parse["target"]:
        out.append(f"task names the {name_of(cfg, parse['target'])} to pick, route chose the "
                   f"{name_of(cfg, task['target_prim'])}")
    if parse["reference"] and task["reference_prim"] != parse["reference"]:
        out.append(f"task names the {name_of(cfg, parse['reference'])} as reference, route chose the "
                   f"{name_of(cfg, task['reference_prim'])}")
    if parse["relation"] and parse["relation"] != "beside" and task["relation"] != parse["relation"]:
        out.append(f"task says '{RELATION_TEXT[parse['relation']]}', route said '{RELATION_TEXT.get(task['relation'])}'")
    return out


def _task_from_parse(parse, cands, cfg):
    by_prim = {p: m for m, _, p, _ in cands}
    if not parse["target"] or not parse["reference"] or parse["target"] == parse["reference"]:
        return None
    if parse["target"] not in cfg["PICKABLE_PRIMS"]:
        return None
    return {"target_mark": by_prim[parse["target"]], "target_prim": parse["target"],
            "reference_mark": by_prim[parse["reference"]], "reference_prim": parse["reference"],
            "relation": parse["relation"] or "beside",
            "avoid_marks": sorted(by_prim[p] for p in parse["avoid"]), "avoid_prims": list(parse["avoid"]),
            "confidence": 1.0, "target_description": name_of(cfg, parse["target"]),
            "reference_description": name_of(cfg, parse["reference"]), "notes": "decided from the task wording"}


def decide(cfg, ctx, routes):
    """Race the routes; return (task|None, problems, meta). Blocking, bounded by DEADLINE_S."""
    cands = ctx["cands"]
    prims = [p for _, _, p, _ in cands]
    parse, parse_notes = keyword_parse(ctx["task_text"], cfg, prims)
    wording_clear = bool(parse["target"] and parse["reference"])
    meta = {"calls": [], "wording": parse, "wording_notes": parse_notes, "decided_by": None, "served_by": []}
    t0 = time.time()
    deadline = t0 + float(cfg["DEADLINE_S"])
    procs = []

    def one(route):
        t = time.time()
        rec = {"route": route["id"]}
        try:
            if route["kind"] == "claude_code":
                text, served, raw = _call_claude_code(route, cfg, ctx["task_text"], ctx["img_path"], len(cands), procs,
                                                      ctx.get("hints"))
            else:
                text, served, raw = _call_http(route, cfg, ctx["task_text"], ctx["img"], len(cands), ctx.get("hints"))
        except Exception as e:
            rec.update(error=str(e)[:300], seconds=round(time.time() - t, 2))
            return rec, None
        rec.update(served_by=served, seconds=round(time.time() - t, 2))
        try:
            ans = parse_answer(text)
        except Exception as e:
            rec["problems"] = [f"unparseable reply ({e})"]
            return rec, raw
        task, probs = validate_answer(ans, cands, cfg)
        rec.update(answer=ans, problems=probs)
        if task is not None and cfg["KEYWORD_CHECK"]:
            c = _contradicts(task, parse, cfg)
            if c:
                task, rec["problems"] = None, c
        rec["task"] = task
        return rec, raw

    valid, decided = [], None
    pool = concurrent.futures.ThreadPoolExecutor(max_workers=max(1, len(routes)))
    futs = {pool.submit(one, r): r for r in routes}
    pending = set(futs)
    try:
        while pending and decided is None:
            left = deadline - time.time()
            if left <= 0:
                break
            done, pending = concurrent.futures.wait(pending, timeout=left,
                                                    return_when=concurrent.futures.FIRST_COMPLETED)
            for f in done:
                rec, raw = f.result()
                meta["calls"].append({k: v for k, v in rec.items()})
                try:
                    with open(os.path.join(ctx["run_dir"], f"response_{rec['route']}.json"), "w") as fh:
                        json.dump(raw, fh, indent=2)
                except Exception:
                    pass
                tag = f"{rec['route']}: " + (rec.get("error") or "; ".join(rec.get("problems") or []) or
                                             f"{name_of(cfg, rec['task']['target_prim'])} "
                                             f"{RELATION_TEXT[rec['task']['relation']]} "
                                             f"{name_of(cfg, rec['task']['reference_prim'])}")
                _log(f"route answer after {rec.get('seconds')} s - {tag}")
                if rec.get("task") is None:
                    continue
                valid.append(rec)
                if wording_clear:
                    decided = (rec["task"], f"VLM + wording agree ({rec['route']})", [rec])
                    break
                groups = {}
                for r in valid:
                    t = r["task"]
                    groups.setdefault((t["target_prim"], t["reference_prim"], t["relation"]), []).append(r)
                best = max(groups.values(), key=len)
                if len(best) >= max(1, min(int(cfg["VOTES"]), len(routes))):
                    how = f"VLM consensus {len(best)}/{len(valid)}" if len(routes) > 1 else f"VLM answer ({best[0]['route']})"
                    decided = (best[0]["task"], how, best)
                    break
    finally:
        for p in procs:
            if p.poll() is None:
                try:
                    os.killpg(p.pid, 9)
                except Exception:
                    try:
                        p.kill()
                    except Exception:
                        pass
        pool.shutdown(wait=False, cancel_futures=True)
    meta["seconds"] = round(time.time() - t0, 2)
    meta["unanswered_routes"] = sorted(futs[f]["id"] for f in pending)

    if decided is None and valid and not wording_clear:
        best = max(valid, key=lambda r: r["task"]["confidence"])
        if best["task"]["confidence"] >= float(cfg["ACCEPT_SINGLE_AT_DEADLINE"]):
            decided = (best["task"], f"single VLM answer ({best['route']})", [best])
    if decided is not None:
        task, how, recs = decided
        task = dict(task)
        task["avoid_prims"] = sorted({p for r in recs for p in r["task"]["avoid_prims"]} | set(parse["avoid"]) -
                                     {task["target_prim"], task["reference_prim"]})
        by_prim = {p: m for m, _, p, _ in cands}
        task["avoid_marks"] = sorted(by_prim[p] for p in task["avoid_prims"])
        if parse["relation"] and task["relation"] == "beside" and parse["relation"] != "beside":
            task["relation"] = parse["relation"]
        meta.update(decided_by=how, served_by=sorted({r.get("served_by") or r["route"] for r in recs}))
        return task, [], meta
    if cfg["KEYWORD_FALLBACK"]:
        t = _task_from_parse(parse, cands, cfg)
        if t is not None:
            meta.update(decided_by="task wording (no VLM answer in time)" if not valid else "task wording")
            return t, [], meta
    problems = []
    for c in meta["calls"]:
        if c.get("error"):
            problems.append(f"{c['route']}: {c['error']}")
        elif c.get("problems"):
            problems.append(f"{c['route']}: {'; '.join(c['problems'])}")
    if meta["unanswered_routes"]:
        problems.append(f"no answer within {cfg['DEADLINE_S']:.0f} s from {', '.join(meta['unanswered_routes'])}")
    if valid:
        problems.append("routes disagreed")
    problems += parse_notes
    return None, problems or ["no usable VLM answer"], meta



def show_task_window(cfg=VLM):
    import builtins

    import omni.ui as ui
    old = getattr(builtins, "_DOBOT_TASK_WINDOW", None)
    if old is not None:
        try:
            old["win"].visible = False
            old["win"].destroy()
        except Exception:
            pass
    st = {"busy": False}
    st["model"] = ui.SimpleStringModel(load_last_task(cfg))
    st["win"] = ui.Window("Dobot task", width=620, height=260)
    with st["win"].frame:
        with ui.VStack(spacing=8, height=0):
            ui.Label("Task for the robot:", height=20)
            try:
                st["field"] = ui.StringField(st["model"], multiline=True, height=70)
            except TypeError:
                st["field"] = ui.StringField(st["model"], height=30)
            ui.Label(engine_label(cfg), height=18, style={"color": 0xFF909090, "font_size": 13})
            with ui.HStack(height=30, spacing=8):
                st["button"] = ui.Button("Ground task", width=140)
                ui.Button("Close", width=90, clicked_fn=lambda: setattr(st["win"], "visible", False))
            st["status"] = ui.Label("Uses the latest capture.", word_wrap=True, height=60)

    async def go(text):
        try:
            _, msg = await run_async(cfg, text)
            st["status"].text = msg
        finally:
            st["busy"] = False
            st["button"].enabled = True

    def on_click():
        if st["busy"]:
            return
        try:
            text = clean_task(st["model"].get_value_as_string(), cfg)
        except ValueError as e:
            st["status"].text = str(e)
            return
        st["busy"] = True
        st["button"].enabled = False
        st["status"].text = "VLM engine: reading the scene ..."
        asyncio.ensure_future(go(text))

    st["button"].set_clicked_fn(on_click)
    builtins._DOBOT_TASK_WINDOW = st
    return st


def _main(argv):
    import argparse
    ap = argparse.ArgumentParser(description="Ground a typed task into keypoints_2d_vlm.json")
    ap.add_argument("--task", default=None)
    ap.add_argument("--capture", default=None, help="capture folder (default: latest)")
    ap.add_argument("--routes", default=None, help="comma-separated route ids to enable (others disabled)")
    ap.add_argument("--check", action="store_true", help="only check the routes and exit")
    ap.add_argument("--dry-run", action="store_true", help="build tagged image + request only")
    a = ap.parse_args(argv)
    cfg = dict(VLM)
    if a.capture:
        cfg["CAPTURE_DIR"] = a.capture
    if a.routes:
        want = {r.strip() for r in a.routes.split(",")}
        cfg["ENGINES"] = [dict(e, enabled=e["id"] in want) for e in cfg["ENGINES"]]
    if a.check:
        if not any(e.get("enabled", True) for e in cfg["ENGINES"]):
            _log("no VLM route configured (VLM_PROVIDER=none): tasks are decided from their wording only")
            return 0
        routes, lines = check_engines(cfg)
        return 0 if routes else 1
    task = a.task
    if task is None:
        if not sys.stdin.isatty():
            _log("FAILED: no --task given and no terminal to ask in")
            return 2
        last = load_last_task(cfg)
        typed = input(f"Task [{last}]: ").strip()
        task = typed or last
    try:
        doc = run_blocking(cfg, task, a.dry_run)
    except Exception as e:
        _log(f"FAILED: {e}")
        return 2
    return 0 if (doc is not None or a.dry_run) else 1


if __name__ == "__main__" and "omni.kit.app" not in sys.modules:
    sys.exit(_main(sys.argv[1:]))
elif "omni.kit.app" in sys.modules and not os.environ.get("VLM_NO_AUTORUN"):
    show_task_window()

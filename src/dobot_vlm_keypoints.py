def build_keypoints(cap, task, cfg, all_prims):
    off = cfg["PIXEL_CENTER_OFFSET"]
    W, H = cap["image"]["width"], cap["image"]["height"]

    def inside(uv):
        return uv is not None and 2 <= uv[0] < W - 2 and 2 <= uv[1] < H - 2

    def px(uv):
        return [round(uv[0], 2), round(uv[1], 2)]

    tg, rf = obj_geom(cap, task["target_prim"]), obj_geom(cap, task["reference_prim"])
    top = tg["max"][2] - max(0.0005, min(0.002, (tg["max"][2] - tg["min"][2]) * 0.02))
    grasps = []
    for dx, dy in ((0, 0), (0.3, 0), (-0.3, 0), (0, 0.3), (0, -0.3)):
        uv = project(cap, [tg["center"][0] + dx * tg["r"], tg["center"][1] + dy * tg["r"], top], off)
        if inside(uv):
            grasps.append({"pixel_xy": px(uv), "object": name_of(cfg, task["target_prim"]),
                           "prim": task["target_prim"]})

    ref_uv = project(cap, rf["center"], off)
    rel = task["relation"]
    want_img = {"left_of": 180.0, "right_of": 0.0, "behind": 90.0, "in_front_of": -90.0}.get(rel)
    want_world = math.degrees(math.atan2(rf["center"][1] - tg["center"][1], rf["center"][0] - tg["center"][0])) \
        if rel == "opposite_side" else None
    robot_prim = (cap.get("robot") or {}).get("prim")
    base_xy = (cap.get("robot") or {}).get("center")
    others = [obj_geom(cap, p) for p in all_prims
              if p not in (task["target_prim"], task["reference_prim"], robot_prim)]
    dist = rf["r"] + tg["r"] + cfg["PLACE_CLEARANCE_M"]
    z = tg["min"][2]
    places = []
    for a_deg in range(0, 360, 30):
        a = math.radians(a_deg)
        p = [rf["center"][0] + dist * math.cos(a), rf["center"][1] + dist * math.sin(a), z]
        if any(math.hypot(p[0] - o["center"][0], p[1] - o["center"][1]) < o["r"] + tg["r"] + cfg["AVOID_MARGIN_M"]
               for o in others):
            continue
        if math.hypot(p[0] - tg["center"][0], p[1] - tg["center"][1]) < 2 * tg["r"]:
            continue
        uv = project(cap, p, off)
        if not inside(uv) or ref_uv is None:
            continue
        if want_img is not None:
            ang = math.degrees(math.atan2(-(uv[1] - ref_uv[1]), uv[0] - ref_uv[0]))
            dev = abs((ang - want_img + 180.0) % 360.0 - 180.0)
        elif want_world is not None:
            dev = abs((a_deg - want_world + 180.0) % 360.0 - 180.0)
        else:
            dev = 0.0
        if dev > 60.0:
            continue
        r_base = math.hypot(p[0] - base_xy[0], p[1] - base_xy[1]) if base_xy is not None else None
        in_band = r_base is None or cfg["PLACE_MIN_R"] <= r_base <= cfg["PLACE_MAX_R"]
        comfort = abs(r_base - cfg["PLACE_COMFORT_R"]) if r_base is not None else 0.0
        places.append(((0 if in_band else 1, round(dev / 30.0), comfort, a_deg),
                       {"pixel_xy": px(uv), "label": f"{rel} reference ({a_deg} deg"
                                                       + (f", {r_base * 1e3:.0f} mm from base)" if r_base else ")")}))
    places = [p for _, p in sorted(places, key=lambda x: x[0])]

    obstacles = []
    obstacle_prims = [task["reference_prim"]] + task["avoid_prims"]
    obstacle_prims += [p for p in all_prims if p not in obstacle_prims and p != task["target_prim"]]
    for prim in obstacle_prims:
        if prim == robot_prim:
            continue                     # the controller hides the robot's own links from depth rays
        o = obj_geom(cap, prim)
        h0, h1 = o["min"][2], o["max"][2]
        pts = [[o["center"][0], o["center"][1], h0 + 0.9 * (h1 - h0)]]
        pts += [[o["center"][0] + 0.6 * o["r"] * math.cos(math.radians(a)),
                 o["center"][1] + 0.6 * o["r"] * math.sin(math.radians(a)), h0 + 0.5 * (h1 - h0)]
                for a in range(0, 360, 60)]
        for p in pts:
            uv = project(cap, p, off)
            if inside(uv):
                obstacles.append({"pixel_xy": px(uv), "object": f"obstacle {name_of(cfg, prim)}", "prim": prim})
    return {"grasp_points": grasps, "placement_candidates": places, "obstacle_points": obstacles}



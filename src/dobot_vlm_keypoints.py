def _sha256_bytes(b):
    return hashlib.sha256(b).hexdigest()


def load_capture(cfg):
    cap_dir = cfg["CAPTURE_DIR"]
    if not cap_dir:
        latest = os.path.join(cfg["CAPTURE_ROOT"], "latest.json")
        if not os.path.isfile(latest):
            raise RuntimeError(f"no capture: {latest} missing; run dobot_capture_overhead.py first")
        with open(latest) as f:
            cap_dir = json.load(f)["capture_dir"]
    with open(os.path.join(cap_dir, "capture.json")) as f:
        cap = json.load(f)
    if not cap.get("camera_check", {}).get("passed"):
        raise RuntimeError(f"capture {cap.get('capture_id')} failed its camera check; recapture")
    with open(os.path.join(cap_dir, cap["image"]["file"]), "rb") as f:
        png = f.read()
    if _sha256_bytes(png) != cap["image"]["sha256"]:
        raise RuntimeError("rgb.png does not match its recorded SHA-256; recapture")
    return cap_dir, cap, png


def project(cap, p, off):
    T, K = cap["camera_to_world"], cap["intrinsics"]
    d = [p[i] - T[i][3] for i in range(3)]
    pc = [sum(T[i][j] * d[i] for i in range(3)) for j in range(3)]
    z = -pc[2]
    if z <= 1e-6:
        return None
    return (K["fx"] * pc[0] / z + K["cx"] - off, K["cy"] - K["fy"] * pc[1] / z - off)


def obj_geom(cap, prim):
    o = cap["objects"].get(prim)
    if o is None and (cap.get("robot") or {}).get("prim") == prim:
        o = cap["robot"]
    lo, hi = o["min"], o["max"]
    return {"min": lo, "max": hi, "center": [(lo[i] + hi[i]) / 2 for i in range(3)],
            "r": 0.5 * min(hi[0] - lo[0], hi[1] - lo[1])}



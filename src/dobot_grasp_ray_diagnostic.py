"""
Dobot grasp-ray diagnostic (READ-ONLY) for Isaac Sim 6.0.x Script Editor.

Purpose
    Explain why the controller reports "no grasp point lands on a pickable object".
    It reproduces the controller's exact camera model (_intrinsics / _pixel_ray) and
    answers, separately:
      A. Does the camera model agree with the image the keypoints came from?
         (projects the cylinder / cone / sphere into pixels and compares them with
          the recorded manual boxes and the keypoints)
      B. Are the keypoints stale or misaligned? (pixel distance from each grasp
         keypoint to the projected cylinder top)
      C. Is the cylinder geometrically visible along those rays?
         (own USD triangle ray caster that INCLUDES rigid bodies; the controller's
          USD caster skips them, so the cylinder is visible to it only via PhysX)
      D. Can PhysX see the cylinder at all? (rigid body / collider setup, whether
         /magician/color sits inside an articulation subtree, whether the
         controller's robot-link exclusion swallows it, and - only if the
         timeline is already playing or paused - live PhysX ray hits)

Safety
    * Never starts, stops or steps the timeline.
    * Never edits, saves or reloads the stage; never commands joints.
    * Writes only a text report, a JSON report and an annotated PNG into
      OUT_DIR (inside the KALM output folder by default).

How to run
    Open stage3_dobot_gripper_test.usd (or the repaired baseline) with the
    timeline STOPPED, paste this file into Window > Script Editor, run.
    Optional second pass: if you already have the scene paused after Play, run
    again to add the PhysX section. Do not press Play just for this script: the
    authored drive targets differ from the joint state by up to 88 deg.
"""


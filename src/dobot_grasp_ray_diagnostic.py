# Geometry: world-space points and triangles of Gprims
# =============================================================================
def _triangles_local(prim, t):
    if prim.IsA(UsdGeom.Mesh):
        mesh = UsdGeom.Mesh(prim)
        pts = mesh.GetPointsAttr().Get(t)
        counts = mesh.GetFaceVertexCountsAttr().Get(t)
        idx = mesh.GetFaceVertexIndicesAttr().Get(t)
        if pts is None or counts is None or idx is None or len(pts) == 0 or len(counts) == 0:
            return None
        pts = np.array(pts, dtype=float)
        counts = np.array(counts, dtype=np.int64)
        idx = np.array(idx, dtype=np.int64)
        starts = np.concatenate([[0], np.cumsum(counts)[:-1]])
        tris = []
        for k in range(1, int(counts.max()) - 1):
            s = starts[counts > k + 1]
            tris.append(np.stack([idx[s], idx[s + k], idx[s + k + 1]], axis=1))
        if not tris:
            return None
        tri = np.concatenate(tris)
        tri = tri[np.all(tri < len(pts), axis=1)]
        return pts[tri]
    ext = UsdGeom.Boundable.ComputeExtentFromPlugins(UsdGeom.Boundable(prim), t)
    if ext is None or len(ext) < 2:
        return None
    lo, hi = np.array(ext[0], dtype=float), np.array(ext[1], dtype=float)
    c = np.array([[lo[0], lo[1], lo[2]], [hi[0], lo[1], lo[2]], [hi[0], hi[1], lo[2]], [lo[0], hi[1], lo[2]],
                  [lo[0], lo[1], hi[2]], [hi[0], lo[1], hi[2]], [hi[0], hi[1], hi[2]], [lo[0], hi[1], hi[2]]])
    f = np.array([[0, 2, 1], [0, 3, 2], [4, 5, 6], [4, 6, 7], [0, 1, 5], [0, 5, 4],
                  [1, 2, 6], [1, 6, 5], [2, 3, 7], [2, 7, 6], [3, 0, 4], [3, 4, 7]])
    return c[f]


def _world_points(stage, root_path, mpu, max_pts=20000):
    """World vertices (metres) of every visible Gprim under root_path (inclusive)."""
    root = stage.GetPrimAtPath(root_path)
    if not root.IsValid():
        return None
    t = Usd.TimeCode.Default()
    xc = UsdGeom.XformCache(t)
    pts = []
    for p in Usd.PrimRange(root, Usd.TraverseInstanceProxies()):
        if not p.IsA(UsdGeom.Gprim):
            continue
        tris = _triangles_local(p, t)
        if tris is None:
            continue
        L = np.unique(tris.reshape(-1, 3), axis=0)
        if len(L) > max_pts:
            L = L[:: len(L) // max_pts + 1]
        M = _gf_to_np(xc.GetLocalToWorldTransform(p))
        pts.append((L @ M[:3, :3].T + M[:3, 3]) * mpu)
    return np.concatenate(pts) if pts else None


class TriCaster:
    """CPU ray caster over visible Gprims, INCLUDING rigid bodies (unlike the controller)."""

    def __init__(self, stage, mpu, exclude, max_tris):
        self.geoms = []
        self.skipped = []
        t = Usd.TimeCode.Default()
        xc = UsdGeom.XformCache(t)
        for prim in Usd.PrimRange.Stage(stage, Usd.TraverseInstanceProxies()):
            if not prim.IsA(UsdGeom.Gprim):
                continue
            path = str(prim.GetPath())
            if any(_under(path, e) for e in exclude):
                continue
            img = UsdGeom.Imageable(prim)
            if img.ComputeVisibility(t) == UsdGeom.Tokens.invisible:
                continue
            if img.ComputePurpose() in (UsdGeom.Tokens.guide, UsdGeom.Tokens.proxy):
                continue
            tris = _triangles_local(prim, t)
            if tris is None or len(tris) == 0:
                continue
            if len(tris) > max_tris:
                self.skipped.append(path)
                continue
            M = _gf_to_np(xc.GetLocalToWorldTransform(prim))
            P = tris.reshape(-1, 3)
            Pw = ((P @ M[:3, :3].T) + M[:3, 3]) * mpu
            T = Pw.reshape(-1, 3, 3)
            self.geoms.append({"path": path, "v0": T[:, 0], "e1": T[:, 1] - T[:, 0], "e2": T[:, 2] - T[:, 0],
                               "bmin": Pw.min(axis=0), "bmax": Pw.max(axis=0)})

    def cast_all(self, o, d, max_dist):
        """All hits along the ray, nearest first: list of (distance, path, point)."""
        hits = []
        with np.errstate(divide="ignore", invalid="ignore"):
            inv = 1.0 / d
        for g in self.geoms:
            with np.errstate(invalid="ignore"):
                t1, t2 = (g["bmin"] - 1e-6 - o) * inv, (g["bmax"] + 1e-6 - o) * inv
            t1 = np.where(np.isnan(t1), -np.inf, t1)
            t2 = np.where(np.isnan(t2), np.inf, t2)
            tn, tf = np.max(np.minimum(t1, t2)), np.min(np.maximum(t1, t2))
            if not (tf >= max(tn, 0.0) and tn <= max_dist):
                continue
            e1, e2 = g["e1"], g["e2"]
            p = np.cross(d, e2)
            det = np.einsum("ij,ij->i", e1, p)
            ok = np.abs(det) > 1e-14
            inv_det = np.where(ok, 1.0 / np.where(ok, det, 1.0), 0.0)
            s = o - g["v0"]
            u = np.einsum("ij,ij->i", s, p) * inv_det
            q = np.cross(s, e1)
            v = (q @ d) * inv_det
            tt = np.einsum("ij,ij->i", e2, q) * inv_det
            valid = ok & (u >= 0) & (v >= 0) & (u + v <= 1) & (tt > 1e-6) & (tt < max_dist)
            if np.any(valid):
                k = int(np.argmin(np.where(valid, tt, np.inf)))
                hits.append((float(tt[k]), g["path"], o + float(tt[k]) * d))
        hits.sort(key=lambda h: h[0])
        return hits



def _png_size(path):
    import struct
    with open(path, "rb") as f:
        head = f.read(24)
    if head[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    w, h = struct.unpack(">II", head[16:24])
    return int(w), int(h)


def _annotate(img_path, size, layers, out_path):
    """layers: list of (kind, data, rgb, label). kind in points/box/cross/ring."""
    try:
        from PIL import Image, ImageDraw
    except Exception:
        return "PIL unavailable; annotated PNG skipped"
    W, H = size
    if img_path is not None:
        im = Image.open(img_path).convert("RGB")
        if im.size != (W, H):
            im = im.resize((W, H))
        im = Image.blend(im, Image.new("RGB", im.size, (0, 0, 0)), 0.35)
    else:
        im = Image.new("RGB", (W, H), (25, 25, 30))
    dr = ImageDraw.Draw(im)
    for kind, data, col, label in layers:
        if kind == "points":
            for u, v in data:
                if np.isfinite(u) and np.isfinite(v):
                    dr.point((float(u), float(v)), fill=col)
        elif kind == "box":
            x0, y0, x1, y1 = data
            dr.rectangle([x0, y0, x1, y1], outline=col, width=2)
            if label:
                dr.text((x0 + 2, y0 - 12), label, fill=col)
        elif kind in ("cross", "ring"):
            u, v = data
            if not (np.isfinite(u) and np.isfinite(v)):
                continue
            r = 7
            if kind == "ring":
                dr.ellipse([u - r, v - r, u + r, v + r], outline=col, width=2)
            else:
                dr.line([u - r, v - r, u + r, v + r], fill=col, width=2)
                dr.line([u - r, v + r, u + r, v - r], fill=col, width=2)
            if label:
                dr.text((u + 9, v - 9), label, fill=col)
    im.save(out_path)
    return None



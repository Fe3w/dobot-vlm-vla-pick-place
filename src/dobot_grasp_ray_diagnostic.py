def _box_iou(a, b):
    ix = max(0.0, min(a[2], b[2]) - max(a[0], b[0]))
    iy = max(0.0, min(a[3], b[3]) - max(a[1], b[1]))
    inter = ix * iy
    ua = (a[2] - a[0]) * (a[3] - a[1]) + (b[2] - b[0]) * (b[3] - b[1]) - inter
    return inter / ua if ua > 0 else 0.0


def _fit_scale_offset(src, dst):
    """Least-squares u' = s*u + tx, v' = s*v + ty  (src, dst: (n,2)). Returns s, tx, ty, rms."""
    src, dst = np.asarray(src, float), np.asarray(dst, float)
    n = len(src)
    A = np.zeros((2 * n, 3))
    b = np.zeros(2 * n)
    A[0::2, 0], A[0::2, 1], b[0::2] = src[:, 0], 1.0, dst[:, 0]
    A[1::2, 0], A[1::2, 2], b[1::2] = src[:, 1], 1.0, dst[:, 1]
    x, *_ = np.linalg.lstsq(A, b, rcond=None)
    res = A @ x - b
    return float(x[0]), float(x[1]), float(x[2]), float(np.sqrt(np.mean(res ** 2)))



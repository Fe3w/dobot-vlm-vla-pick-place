# PhysX probe (only when the timeline is already playing / paused)
# =============================================================================
def _physx_probe(rays, red_path, mpu):
    try:
        import carb
        import omni.physx
        from pxr import PhysicsSchemaTools
    except Exception as e:
        return {"available": False, "why": f"omni.physx unavailable ({e})"}

    def pstr(p):
        if p is None:
            return ""
        if isinstance(p, int):
            try:
                return str(PhysicsSchemaTools.intToSdfPath(p))
            except Exception:
                return ""
        return str(p)

    res = {"available": True, "rays": []}
    try:
        r = omni.physx.get_physx_interface().get_rigidbody_transformation(red_path)
        res["red_rigidbody_known"] = bool(r is not None and r.get("ret_val", False))
        if res["red_rigidbody_known"]:
            res["red_physx_pos_m"] = _r(np.array(r["position"], dtype=float) * mpu, 4)
    except Exception as e:
        res["red_rigidbody_known"] = None
        res["red_rigidbody_error"] = str(e)
    sq = omni.physx.get_physx_scene_query_interface()
    for name, o, d in rays:
        try:
            h = sq.raycast_closest(carb.Float3(*(o / mpu)), carb.Float3(*d), 50.0 / mpu)
        except Exception as e:
            res["rays"].append({"name": name, "error": str(e)})
            continue
        if h is None or not h.get("hit", False):
            res["rays"].append({"name": name, "hit": False})
            continue
        res["rays"].append({"name": name, "hit": True, "collision": pstr(h.get("collision")),
                            "rigidBody": pstr(h.get("rigidBody")),
                            "distance_m": round(float(h.get("distance", float("nan"))) * mpu, 4)})
    return res


# =============================================================================
# Main
# =============================================================================
def run(cfg=DIAG, stage=None, timeline_state=None):
    t_start = time.time()
    del _lines[:]
    if stage is None:
        stage = omni.usd.get_context().get_stage()
    if stage is None:
        print("[DIAG] No stage open.")
        return None
    if timeline_state is None:
        if _HAVE_OMNI:
            tl = omni.timeline.get_timeline_interface()
            timeline_state = "playing" if tl.is_playing() else ("stopped" if tl.is_stopped() else "paused")
        else:
            timeline_state = "stopped"
    mpu = float(UsdGeom.GetStageMetersPerUnit(stage) or 1.0)
    report = {"stage": stage.GetRootLayer().identifier, "timeline": timeline_state, "findings": [],
              "time": time.strftime("%Y-%m-%d %H:%M:%S")}
    F = report["findings"]

    def finding(level, code, msg):
        F.append({"level": level, "code": code, "message": msg})
        out(f"[{level}] {msg}")

    section("DOBOT GRASP-RAY DIAGNOSTIC (read-only: no timeline, stage or joint changes)")
    out(f"stage: {report['stage']}")
    out(f"timeline: {timeline_state};  metres/unit: {mpu};  up axis: {UsdGeom.GetStageUpAxis(stage)}")

    red_path, cam_path, robot_path = cfg["RED_PRIM"], cfg["CAMERA_PRIM"], cfg["ROBOT_PRIM"]
    for p in (robot_path, red_path, cam_path, cfg["CONE_PRIM"], cfg["SPHERE_PRIM"]):
        if not stage.GetPrimAtPath(p).IsValid():
            finding("BLOCK", "missing_prim", f"required prim missing: {p}")
    if any(f["code"] == "missing_prim" for f in F):
        return _finish(cfg, report, t_start)
    red = stage.GetPrimAtPath(red_path)

    # ------------------------------------------------------------------ 1. inputs
    section("1. Keypoints and source image")
    kp = {"grasps": [], "places": [], "obstacles": []}
    size, K_json = None, None
    if os.path.isfile(cfg["JSON_PATH"]):
        with open(cfg["JSON_PATH"], "r") as f:
            data = json.load(f)
        kp["grasps"] = _points_from(_find_key(data, ("grasp_points", "grasp_point", "grasps")))
        kp["places"] = _points_from(_find_key(data, ("placement_candidates", "placement_points", "place_points")))
        kp["obstacles"] = _points_from(_find_key(data, ("obstacle_points", "obstacles")))
        size = _image_size_from(data)
        K_json = _intrinsics_from(data)
        crop = data.get("crop") if isinstance(data, dict) else None
        space = str(data.get("coordinate_space", "")).lower() if isinstance(data, dict) else ""
        out(f"JSON: {cfg['JSON_PATH']}")
        out(f"  grasps={len(kp['grasps'])}, placements={len(kp['places'])}, obstacles={len(kp['obstacles'])}")
        out(f"  image size in JSON: {size};  K in JSON: {K_json};  coordinate_space={space!r};  crop={crop}")
        top_keys = list(data.keys()) if isinstance(data, dict) else type(data).__name__
        out(f"  top-level keys: {top_keys}")
        report["json"] = {"path": cfg["JSON_PATH"], "size": size, "K": K_json, "crop": crop,
                          "coordinate_space": space, "grasps": [g["uv"] for g in kp["grasps"]]}
        if "crop" in space and isinstance(crop, dict):
            x0, y0 = float(crop.get("x0", 0.0)), float(crop.get("y0", 0.0))
            for rec in kp["grasps"] + kp["places"] + kp["obstacles"]:
                rec["uv"] = (rec["uv"][0] + x0, rec["uv"][1] + y0)
            out(f"  keypoints shifted by crop offset ({x0:.0f}, {y0:.0f}) exactly as the controller does")
    else:
        finding("WARN", "no_json", f"keypoint JSON not found at {cfg['JSON_PATH']}; "
                                   f"using only the projected cylinder top as a test pixel")
    if size is None:
        size = tuple(cfg["DEFAULT_IMAGE_SIZE"])
        out(f"  image size assumed: {size[0]}x{size[1]} (controller default)")
    img_path = _find_image(cfg)
    img_size = _png_size(img_path) if img_path else None
    out(f"source image: {img_path}  size={img_size}")
    report["image"] = {"path": img_path, "size": img_size}
    if img_size is not None and tuple(img_size) != tuple(size):
        finding("FAIL", "size_mismatch",
                f"keypoint JSON image size {size} differs from the source PNG {img_size}; the controller "
                f"maps pixels with the JSON size, so every ray is scaled wrongly")

    # ------------------------------------------------------------------ 2. camera
    section("2. Overhead camera model (the controller's maths)")
    cam_h = CameraModel(stage, cam_path, size, mpu, K_json, "horizontal")
    cam_v = CameraModel(stage, cam_path, size, mpu, None, "vertical")
    fwd = cam_h.T[:3, :3] @ np.array([0.0, 0.0, -1.0])
    out(f"projection={cam_h.projection}  focal={cam_h.f:.3f}  hAperture={cam_h.ha:.4f}  vAperture={cam_h.va}  "
        f"offsets=({cam_h.hoff}, {cam_h.voff})")
    out(f"model used: {cam_h.source}")
    out(f"  fx={cam_h.fx:.2f} fy={cam_h.fy:.2f} cx={cam_h.cx:.2f} cy={cam_h.cy:.2f}")
    out(f"camera position {_r(cam_h.T[:3, 3], 4)} m, looking along {_r(fwd, 3)} (world)")
    if cam_h.va:
        out(f"aperture aspect {cam_h.va / cam_h.ha:.4f} vs image aspect {size[1] / size[0]:.4f}")
    report["camera"] = {"projection": cam_h.projection, "fx": cam_h.fx, "fy": cam_h.fy, "cx": cam_h.cx,
                        "cy": cam_h.cy, "pos_m": _r(cam_h.T[:3, 3], 4), "forward": _r(fwd, 3),
                        "source": cam_h.source}
    if cam_h.projection.lower() != "perspective":
        finding("FAIL", "ortho_camera", f"camera projection is {cam_h.projection}; the controller assumes a "
                                        f"pinhole (perspective) camera, so its rays are wrong")
    if fwd[2] > -0.5:
        finding("WARN", "camera_not_down", f"camera forward axis {_r(fwd, 2)} is not mostly downward; check "
                                           f"that /overhead_camera is the camera that took the keypoint image")

    # ------------------------------------------------------------- 3. red physics
    section("3. Red cylinder: physics setup PhysX must see")
    t0 = Usd.TimeCode.Default()
    img = UsdGeom.Imageable(red)
    vis = img.ComputeVisibility(t0)
    out(f"{red_path}: type={red.GetTypeName()}, visibility={vis}, purpose={img.ComputePurpose()}")
    rb_on = [str(p.GetPath()) for p in Usd.PrimRange(red) if p.HasAPI(UsdPhysics.RigidBodyAPI)]
    anc, rb_anc = red.GetParent(), []
    while anc.IsValid() and not anc.IsPseudoRoot():
        if anc.HasAPI(UsdPhysics.RigidBodyAPI):
            rb_anc.append(str(anc.GetPath()))
        anc = anc.GetParent()
    coll = []
    for p in Usd.PrimRange(red):
        if p.HasAPI(UsdPhysics.CollisionAPI):
            ce = UsdPhysics.CollisionAPI(p).GetCollisionEnabledAttr().Get()
            approx = None
            if p.HasAPI(UsdPhysics.MeshCollisionAPI):
                approx = UsdPhysics.MeshCollisionAPI(p).GetApproximationAttr().Get()
            coll.append({"path": str(p.GetPath()), "enabled": ce, "approximation": approx})
    kin = None
    if red.HasAPI(UsdPhysics.RigidBodyAPI):
        rb = UsdPhysics.RigidBodyAPI(red)
        kin = rb.GetKinematicEnabledAttr().Get()
        rbe = rb.GetRigidBodyEnabledAttr().Get()
        out(f"RigidBodyAPI on the prim: rigidBodyEnabled={rbe}, kinematicEnabled={kin}")
    out(f"RigidBodyAPI within subtree: {rb_on};  on ancestors: {rb_anc or 'none'}")
    out(f"colliders: {coll or 'none'}")
    report["red_physics"] = {"rigid_subtree": rb_on, "rigid_ancestors": rb_anc, "colliders": coll,
                             "kinematic": kin, "visibility": str(vis)}
    if vis == UsdGeom.Tokens.invisible:
        finding("FAIL", "red_invisible", f"{red_path} is invisible; neither the camera nor the USD caster sees it")
    if not rb_on and not rb_anc:
        finding("FAIL", "red_no_rigid", f"{red_path} has no RigidBodyAPI; the latch and PhysX target lookup need one")
    if rb_anc:
        finding("WARN", "nested_rigid", f"{red_path} has rigid-body ancestors {rb_anc}; PhysX nests bodies badly")
    if not coll:
        finding("FAIL", "red_no_collider", f"{red_path} has no CollisionAPI: PhysX rays pass straight through it, "
                                           f"and the controller's USD caster skips rigid bodies, so it is invisible "
                                           f"to perception")
    elif all(c["enabled"] is False for c in coll):
        finding("FAIL", "red_collider_off", f"every collider on {red_path} has collisionEnabled=False")

    # Articulation membership: a rigid body inside an articulation root's subtree is parsed as part
    # of that articulation (or rejected as a disconnected link), not as a free object.
    arts = []
    for p in Usd.PrimRange.Stage(stage, Usd.TraverseInstanceProxies()):
        if p.HasAPI(UsdPhysics.ArticulationRootAPI):
            arts.append(str(p.GetPath()))
    out(f"ArticulationRootAPI prims: {arts or 'none'}")
    report["articulation_roots"] = arts
    joint_refs = []
    for p in Usd.PrimRange.Stage(stage, Usd.TraverseInstanceProxies()):
        if p.IsA(UsdPhysics.Joint):
            j = UsdPhysics.Joint(p)
            for rel in (j.GetBody0Rel(), j.GetBody1Rel()):
                if any(_under(str(t), red_path) for t in rel.GetTargets()):
                    joint_refs.append(str(p.GetPath()))
    for a in arts:
        ap = stage.GetPrimAtPath(a)
        if ap.IsA(UsdPhysics.Joint):
            # Root on a joint: the articulation is the bodies connected to it through joints,
            # so a free body elsewhere in the prim tree is not pulled in.
            out(f"  {a} is a joint: articulation membership follows joint connectivity, not the prim subtree")
        elif _under(red_path, a):
            finding("WARN", "red_in_articulation",
                    f"{red_path} sits inside the prim subtree of articulation root {a}. PhysX may treat it "
                    f"as part of that articulation instead of a free body. Suspect only: confirm with the "
                    f"PhysX probe (section 7, scene paused). Long-term, keep pickable objects outside the "
                    f"robot prim, e.g. /World/objects/...")
    if joint_refs:
        finding("FAIL", "red_jointed", f"joints reference {red_path} (it is welded/driven, not free): {joint_refs}")
    report["red_joint_refs"] = joint_refs

    # ------------------------------------------------------------- 4. exclusions
    section("4. Prims the controller hides from depth rays")
    robot_links = []
    if os.path.isfile(cfg["URDF_PATH"]):
        try:
            robot_links = _robot_link_paths(stage, robot_path, cfg["URDF_PATH"])
        except Exception as e:
            out(f"URDF parse failed: {e}")
    else:
        out(f"URDF not found at {cfg['URDF_PATH']}; robot exclusion not reproduced")
    markers = _marker_paths(stage, robot_links, cfg["DEPTH_IGNORE_NAME_PATTERNS"])
    out(f"robot links excluded: {robot_links}")
    out(f"marker prims excluded: {markers}")
    report["excluded"] = {"robot_links": robot_links, "markers": markers}
    for p in (red_path, cfg["CONE_PRIM"], cfg["SPHERE_PRIM"]):
        hits = [e for e in robot_links + markers if _under(p, e)]
        if hits:
            finding("FAIL", "excluded_target", f"{p} is hidden from every depth ray by the exclusion {hits}")

    # ------------------------------------------------------------- 5. projection
    section("5. Projection of scene objects into the keypoint image")
    off = cfg["PIXEL_CENTER_OFFSET"]
    W, H = size
    proj = {}
    for name, path in (("red", red_path), ("cone", cfg["CONE_PRIM"]), ("sphere", cfg["SPHERE_PRIM"])):
        P = _world_points(stage, path, mpu)
        if P is None:
            out(f"{name}: no geometry")
            continue
        uv_h = cam_h.project(P, off)
        uv_v = cam_v.project(P, off)
        ok = np.all(np.isfinite(uv_h), axis=1)
        if not np.any(ok):
            finding("FAIL", f"{name}_behind", f"{path} is entirely behind the camera")
            continue
        box_h = [float(uv_h[ok, 0].min()), float(uv_h[ok, 1].min()), float(uv_h[ok, 0].max()), float(uv_h[ok, 1].max())]
        okv = np.all(np.isfinite(uv_v), axis=1)
        box_v = ([float(uv_v[okv, 0].min()), float(uv_v[okv, 1].min()), float(uv_v[okv, 0].max()),
                  float(uv_v[okv, 1].max())] if np.any(okv) else [float("nan")] * 4)
        lo, hi = P.min(axis=0), P.max(axis=0)
        top_c = np.array([(lo[0] + hi[0]) / 2, (lo[1] + hi[1]) / 2, hi[2] - max(0.0005, min(0.002, (hi[2] - lo[2]) * 0.02))])
        top_uv = cam_h.project(top_c, off)[0]
        proj[name] = {"path": path, "box": box_h, "box_vfit": box_v, "uv": uv_h, "top_world": top_c,
                      "top_uv": top_uv, "world_min": lo, "world_max": hi}
        inside_img = 0 <= box_h[0] and box_h[2] < W and 0 <= box_h[1] and box_h[3] < H
        out(f"{name:6s} {path}: world bbox {_r(lo, 3)} .. {_r(hi, 3)} m")
        out(f"        pixel bbox (controller model) {_r(box_h)}  {'inside' if inside_img else 'NOT fully inside'} "
            f"the {W}x{H} image;  top-centre pixel {_r(top_uv)}")
        man = cfg["MANUAL_BOXES"].get(path)
        if man:
            iou_h, iou_v = _box_iou(box_h, man), _box_iou(box_v, man)
            out(f"        recorded manual box {man}: IoU {iou_h:.2f} (controller model), {iou_v:.2f} (vertical fit)")
            proj[name].update({"manual": man, "iou": iou_h, "iou_v": iou_v})
        if not inside_img:
            finding("WARN", f"{name}_outside", f"{path} projects partly or fully outside the image")
    report["projection"] = {k: {"box": _r(v["box"]), "box_vfit": _r(v["box_vfit"]), "top_uv": _r(v["top_uv"]),
                                "iou_manual": round(v.get("iou", float("nan")), 3) if "iou" in v else None,
                                "iou_manual_vfit": round(v.get("iou_v", float("nan")), 3) if "iou_v" in v else None}
                            for k, v in proj.items()}

    # Camera-model agreement with the recorded image regions.
    pairs_src, pairs_dst = [], []
    for v in proj.values():
        if "manual" in v:
            b, m = v["box"], v["manual"]
            pairs_src += [[b[0], b[1]], [b[2], b[3]]]
            pairs_dst += [[m[0], m[1]], [m[2], m[3]]]
    cam_agrees = None
    if len(pairs_src) >= 4:
        s, tx, ty, rms = _fit_scale_offset(pairs_src, pairs_dst)
        out(f"best fit  image = {s:.3f} * projected + ({tx:.1f}, {ty:.1f}) px,  rms {rms:.1f} px")
        report["image_fit"] = {"scale": s, "tx": tx, "ty": ty, "rms_px": rms}
        ious = [v["iou"] for v in proj.values() if "iou" in v]
        cam_agrees = min(ious) >= 0.5
        if cam_agrees:
            out("camera model agrees with the recorded image regions (IoU >= 0.5 for every recorded box)")
        elif abs(s - 1.0) > 0.05 or math.hypot(tx, ty) > 15.0:
            finding("FAIL", "camera_mismatch",
                    f"the controller's camera model does not reproduce the keypoint image: the recorded boxes sit "
                    f"at scale {s:.3f} and offset ({tx:.0f}, {ty:.0f}) px from the projection (rms {rms:.1f} px). "
                    f"Typical causes: the image was a viewport screenshot or crop rather than a render of "
                    f"{cam_path} at {W}x{H}, the camera moved, or the aperture/aspect differs")
        else:
            finding("WARN", "camera_rough", "projection and recorded boxes roughly agree but with low IoU; the "
                                            "manual boxes were hand-estimated, so treat this as indicative")

    # ------------------------------------------------------------- 6. ray tests
    section("6. Rays through every grasp keypoint and the projected cylinder top")
    caster = TriCaster(stage, mpu, robot_links + markers + [cam_path], cfg["MAX_TRIS_PER_MESH"])
    if caster.skipped:
        out(f"meshes too large for the CPU caster (skipped): {caster.skipped}")
    tests = [(f"grasp {i} '{g['label']}'", g["uv"]) for i, g in enumerate(kp["grasps"])]
    if "red" in proj:
        tests.append(("projected red top (V2 fallback)", tuple(proj["red"]["top_uv"])))
    man_c = cfg["MANUAL_GRASP_REGION"]
    tests.append(("centre of recorded grasp region", ((man_c[0] + man_c[2]) / 2, (man_c[1] + man_c[3]) / 2)))
    report["rays"] = []
    physx_rays = []
    any_kp_on_red = False
    top_hits_red = None
    for name, (u, v) in tests:
        o, d = cam_h.ray(u, v, off)
        hits = caster.cast_all(o, d, cfg["RAY_MAX_DIST_M"])
        first = hits[0] if hits else None
        red_hit = next((h for h in hits if _under(h[1], red_path)), None)
        d_top = None
        if "red" in proj:
            d_top = float(np.hypot(u - proj["red"]["top_uv"][0], v - proj["red"]["top_uv"][1]))
        on_red = first is not None and _under(first[1], red_path)
        if name.startswith("grasp") and on_red:
            any_kp_on_red = True
        if name.startswith("projected"):
            top_hits_red = on_red
        verdict = "HITS red cylinder first" if on_red else (
            f"first hit {first[1]}" + (f"; red cylinder is behind it at +{(red_hit[0] - first[0]) * 1e3:.0f} mm"
                                       if red_hit else "; ray never touches the red cylinder")
            if first else "hits nothing")
        out(f"{name:34s} px=({u:7.1f},{v:7.1f})" + (f"  {d_top:6.1f} px from red top" if d_top is not None else "")
            + f"  -> {verdict}")
        if first is not None:
            out(f"{'':34s} first-hit point {_r(first[2], 4)} m at {first[0]:.3f} m")
        report["rays"].append({"name": name, "uv": _r((u, v)), "px_from_red_top": d_top,
                               "first_hit": first[1] if first else None,
                               "first_hit_m": _r(first[2], 4) if first else None,
                               "red_on_ray": red_hit is not None, "red_first": on_red})
        physx_rays.append((name, o, d))
    if kp["grasps"] and not any_kp_on_red:
        dmin = min((r["px_from_red_top"] for r in report["rays"] if r["name"].startswith("grasp")
                    and r["px_from_red_top"] is not None), default=None)
        finding("FAIL", "stale_keypoints",
                "no stored grasp keypoint ray reaches the red cylinder first even with full USD geometry"
                + (f" (closest is {dmin:.0f} px from the projected top)" if dmin is not None else "")
                + ": the keypoints do not match this camera/scene")
    if top_hits_red is False:
        finding("FAIL", "top_occluded", "the ray through the projected cylinder top does not hit the cylinder "
                                        "first; something sits between camera and cylinder, or the model is off")
    elif top_hits_red:
        out("geometry check: the projected cylinder top IS reachable by a camera ray")

    # ------------------------------------------------------------- 7. physx probe
    section("7. PhysX probe")
    if timeline_state == "stopped":
        out("timeline is stopped, so PhysX has no scene to query; skipped (by design: this script never presses "
            "Play). Sections 3 and 4 tell you whether PhysX *should* see the cylinder.")
        report["physx"] = {"available": False, "why": "timeline stopped"}
    else:
        px = _physx_probe(physx_rays, red_path, mpu)
        report["physx"] = px
        if not px.get("available"):
            out(px.get("why"))
        else:
            out(f"PhysX knows {red_path} as a rigid body: {px.get('red_rigidbody_known')}"
                + (f" at {px['red_physx_pos_m']} m" if "red_physx_pos_m" in px else ""))
            if "red_physx_pos_m" in px and "red" in proj:
                usd_c = (proj["red"]["world_min"] + proj["red"]["world_max"]) / 2
                out(f"  USD bbox centre {_r(usd_c, 4)} m (rigid-body origin and bbox centre may differ)")
            for r in px["rays"]:
                out(f"  {r['name']:34s} -> " + (f"collision {r['collision']}, body {r['rigidBody']}, "
                                                 f"{r['distance_m']} m" if r.get("hit") else
                                                 r.get("error", "no PhysX hit")))
            if px.get("red_rigidbody_known") is False:
                finding("FAIL", "physx_no_red", f"PhysX does not report {red_path} as a rigid body while the "
                                                f"timeline runs: it is not simulated as a free object")
            top = next((r for r in px["rays"] if r["name"].startswith("projected")), None)
            if top is not None and top.get("hit") and not (_under(top.get("collision", ""), red_path)
                                                           or _under(top.get("rigidBody", ""), red_path)):
                finding("FAIL", "physx_misses_red", f"USD geometry says the projected top ray hits the cylinder, "
                                                    f"but PhysX reports {top.get('collision')}: the cylinder's "
                                                    f"collider is not in the PhysX scene")

    # ------------------------------------------------------------- 8. picture
    section("8. Annotated image")
    os.makedirs(cfg["OUT_DIR"], exist_ok=True)
    layers = []
    colours = {"red": (255, 70, 70), "cone": (190, 110, 255), "sphere": (80, 230, 110)}
    for name, v in proj.items():
        uv = v["uv"]
        if len(uv) > 4000:
            uv = uv[:: len(uv) // 4000 + 1]
        layers.append(("points", [tuple(p) for p in uv], colours[name], ""))
        layers.append(("box", v["box"], colours[name], f"{name} projected"))
        if "manual" in v:
            layers.append(("box", v["manual"], (200, 200, 200), f"{name} recorded"))
    for r in report["rays"]:
        col = (40, 255, 40) if r["red_first"] else (255, 220, 0)
        layers.append(("ring" if r["name"].startswith("grasp") else "cross", tuple(r["uv"]), col,
                       r["name"].split(" '")[0]))
    png = os.path.join(cfg["OUT_DIR"], "grasp_diag_overlay.png")
    why = _annotate(img_path, size, layers, png)
    out(why or f"saved {png}  (dots = projected object vertices, grey boxes = recorded regions, "
                f"rings = grasp keypoints: green hits red first, yellow does not)")
    report["overlay_png"] = None if why else png
    return _finish(cfg, report, t_start)


def _verdict(report):
    codes = {f["code"] for f in report["findings"]}
    lines = []
    if "missing_prim" in codes:
        return ["Required prims are missing; open the Dobot test stage and rerun."]
    if "excluded_target" in codes:
        lines.append("The cylinder is hidden by the controller's robot/marker exclusion list (section 4), so no "
                     "ray can ever hit it. Rename it or move it out of the robot hierarchy before anything else.")
    if codes & {"size_mismatch", "camera_mismatch", "ortho_camera"}:
        lines.append("Pixel-to-ray mapping is wrong (image size / camera model). Regenerate the keypoints "
                     "from a fresh render of /overhead_camera at the size written into the JSON.")
    if "stale_keypoints" in codes and "camera_mismatch" not in codes:
        lines.append("The stored grasp keypoints are stale for this scene: they do not land on the cylinder even "
                     "with perfect geometry. The V2 projected-top fallback is the right stopgap; fresh "
                     "keypoints (live capture + VLM) are the real fix.")
    if codes & {"red_jointed", "red_no_collider", "red_collider_off", "physx_no_red", "physx_misses_red",
                "red_no_rigid"}:
        lines.append("PhysX cannot see the cylinder as a free rigid body. Because the controller's USD caster "
                     "skips rigid bodies, a correct pixel still misses. Fix the physics setup (one RigidBodyAPI "
                     "+ an enabled CollisionAPI on the cylinder, no joints to it, ideally outside /magician), "
                     "then rerun this diagnostic with the scene paused.")
    elif "red_in_articulation" in codes:
        lines.append("Suspect: the cylinder sits under the articulation root prim. Rerun with the scene paused "
                     "after Play; if section 7 shows PhysX missing the cylinder, move it out of /magician.")
    if "top_occluded" in codes:
        lines.append("Something is between the camera and the cylinder top along the projected ray; see "
                     "section 6 for the blocking prim.")
    if not lines:
        lines.append("No blocking cause found in geometry/setup. If the stage is stopped, rerun once while "
                     "paused after Play to check the PhysX side (section 7).")
    return lines


def _finish(cfg, report, t_start):
    section("VERDICT")
    report["verdict"] = _verdict(report)
    for i, l in enumerate(report["verdict"], 1):
        out(f"{i}. {l}")
    out(f"\n(diagnostic took {time.time() - t_start:.1f} s; nothing in the stage was changed)")
    try:
        os.makedirs(cfg["OUT_DIR"], exist_ok=True)
        with open(os.path.join(cfg["OUT_DIR"], "grasp_diag_report.txt"), "w") as f:
            f.write("\n".join(_lines) + "\n")
        with open(os.path.join(cfg["OUT_DIR"], "grasp_diag_report.json"), "w") as f:
            json.dump(report, f, indent=2, default=lambda o: o.tolist() if hasattr(o, "tolist") else str(o))
        print(f"[DIAG] reports written to {cfg['OUT_DIR']}")
    except Exception as e:
        print(f"[DIAG] could not write reports: {e}")
    return report



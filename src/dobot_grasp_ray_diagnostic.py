# Camera model (identical maths to the controller, plus a vertical-fit variant)
# =============================================================================
class CameraModel:
    def __init__(self, stage, cam_path, size, mpu, K_json=None, fit="horizontal"):
        self.W, self.H = size
        self.mpu = mpu
        self.prim = stage.GetPrimAtPath(cam_path)
        cam = UsdGeom.Camera(self.prim)
        self.f = float(cam.GetFocalLengthAttr().Get())
        self.ha = float(cam.GetHorizontalApertureAttr().Get())
        va = cam.GetVerticalApertureAttr().Get()
        self.va = float(va) if va is not None else None
        self.hoff = float(cam.GetHorizontalApertureOffsetAttr().Get() or 0.0)
        self.voff = float(cam.GetVerticalApertureOffsetAttr().Get() or 0.0)
        self.projection = str(cam.GetProjectionAttr().Get())
        self.fit = fit
        if K_json is not None:
            self.fx, self.fy, self.cx, self.cy = K_json
            self.source = "keypoint JSON K"
        elif fit == "horizontal":
            self.fx = self.f / self.ha * self.W
            self.fy = self.fx
            self.cx = self.W * 0.5 + self.hoff / self.ha * self.W
            self.cy = self.H * 0.5 - self.voff / self.ha * self.W
            self.source = "USD camera, horizontal-aperture fit (controller default)"
        else:
            va = self.va if self.va else self.ha * self.H / self.W
            self.fy = self.f / va * self.H
            self.fx = self.fy
            self.cx = self.W * 0.5 + self.hoff / va * self.H
            self.cy = self.H * 0.5 - self.voff / va * self.H
            self.source = "USD camera, vertical-aperture fit (alternative)"
        self.T = _usd_world(self.prim, mpu)

    def ray(self, u, v, off):
        d_cam = np.array([(u + off - self.cx) / self.fx, -(v + off - self.cy) / self.fy, -1.0])
        d = self.T[:3, :3] @ d_cam
        return self.T[:3, 3].copy(), d / np.linalg.norm(d)

    def project(self, P, off):
        """World points (n,3) metres -> (n,2) pixels; NaN for points behind the camera."""
        P = np.atleast_2d(np.asarray(P, dtype=float))
        pc = (P - self.T[:3, 3]) @ self.T[:3, :3]          # R^T (p - t)
        z = -pc[:, 2]
        with np.errstate(divide="ignore", invalid="ignore"):
            u = self.fx * pc[:, 0] / z + self.cx - off
            v = self.cy - self.fy * pc[:, 1] / z - off
        bad = ~(z > 1e-6)
        u[bad], v[bad] = np.nan, np.nan
        return np.stack([u, v], axis=1)



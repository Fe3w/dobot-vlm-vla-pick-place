"""
dobot_wrist_level.py - make the simulated Dobot hold its suction cup straight down, like the real one.

Why
    On the real Magician the end-effector plate is kept level by a passive parallelogram linkage: whatever the
    rear arm and forearm do, the suction cup points straight down. The simulated robot has no linkage; the wrist
    is a separate driven joint (joint_6). The controller sets joint_6 = s * (joint_2 + joint_5) + b while it
    runs, with b guessed from the shape of the suction mesh. When the controller is not driving (scene loaded,
    timeline played, joints moved by hand) joint_6 just holds its old target, so the cup follows the forearm
    and points sideways or up.

What this file does
    Run it once in Isaac Sim (Window > Script Editor > open this file > Run), with the scene open:
      1. plays the timeline and moves the arm slowly through a few poses (joint_1 is not moved);
      2. at each pose turns joint_6 until the cup axis points straight down (measured from the live link pose);
      3. fits joint_6 = s * (joint_2 + joint_5) + b to those poses and saves s and b to dobot_wrist_calib.json;
      4. switches on the "leveler": while the timeline plays and no controller is running, joint_6 follows
         joint_2 and joint_5 every physics step, exactly like the real linkage. Drag joint_2 / joint_5 drive
         targets in the Property panel and the cup stays vertical.
    The task window loads the calibration and the leveler automatically, and the controller uses the
    calibrated s and b instead of its guess. Nothing is saved to the USD (stop the timeline when done; the
    task window reloads the scene before every run).

    If the cup ends up pointing straight UP, the wrong end of the suction mesh was taken as the nozzle:
    set WRIST["NOZZLE_FLIP"] = True and run again.
"""

def rot(axis, ang_rad):
    a = np.asarray(axis, float)
    a = a / np.linalg.norm(a)
    K = np.array([[0, -a[2], a[1]], [a[2], 0, -a[0]], [-a[1], a[0], 0]])
    return np.eye(3) + math.sin(ang_rad) * K + (1 - math.cos(ang_rad)) * K @ K


def tilt_deg(n, down=(0.0, 0.0, -1.0)):
    n = np.asarray(n, float) / np.linalg.norm(n)
    return math.degrees(math.acos(max(-1.0, min(1.0, float(n @ np.asarray(down, float))))))


def best_turn(n, axis, down=(0.0, 0.0, -1.0)):
    """Rotation (deg) about `axis` that brings direction n closest to `down`, and the tilt left after it."""
    a = np.asarray(axis, float) / np.linalg.norm(axis)
    n = np.asarray(n, float) / np.linalg.norm(n)
    d = np.asarray(down, float)
    n_p, d_p = n - (n @ a) * a, d - (d @ a) * a
    if np.linalg.norm(n_p) < 1e-9 or np.linalg.norm(d_p) < 1e-9:
        return 0.0, tilt_deg(n, d)              # axis parallel to the nozzle or to gravity: cannot help
    ang = math.atan2(float(a @ np.cross(n_p, d_p)), float(n_p @ d_p))
    return math.degrees(ang), tilt_deg(rot(a, ang) @ n, d)


def wrap180(x):
    return (x + 180.0) % 360.0 - 180.0


def fit_rule(sums_deg, j6_deg):
    """Fit joint_6 = s * (joint_2 + joint_5) + b (degrees). Returns (s, b, worst residual)."""
    x, y = np.asarray(sums_deg, float), np.asarray(j6_deg, float)
    best = None
    for s in (-1.0, 1.0):
        r = np.radians(y - s * x)
        b = math.degrees(math.atan2(np.mean(np.sin(r)), np.mean(np.cos(r))))   # circular mean
        res = float(np.max(np.abs(wrap180(y - s * x - b))))
        if best is None or res < best[2]:
            best = (s, b, res)
    return best


def level_value(q2, q5, cal, lo=-180.0, hi=180.0, ref=None):
    """joint_6 (deg) that levels the cup, wrapped by 360 into [lo, hi], closest to ref."""
    v = cal["sign"] * (q2 + q5) + cal["bias_deg"]
    opts = [v + k for k in (0.0, -360.0, 360.0, -720.0, 720.0) if lo - 1e-6 <= v + k <= hi + 1e-6]
    if not opts:
        return min(max(v, lo), hi)
    return opts[0] if ref is None else min(opts, key=lambda o: abs(o - ref))


def joint_angle(R0, R1, axis_index):
    """Revolute joint angle (rad) from the two joint frames in world (body pose @ localRot)."""
    Rr = R0.T @ R1
    if axis_index == 0:
        return math.atan2(Rr[2, 1], Rr[1, 1])
    if axis_index == 1:
        return math.atan2(Rr[0, 2], Rr[2, 2])
    return math.atan2(Rr[1, 0], Rr[0, 0])


def nozzle_axis(points_local, flip=False):
    """Nozzle direction in the link frame: the suction mesh's long axis, pointing to the end farther from the
    link origin (same rule the controller uses for the tool tip). flip=True takes the other end."""
    V = np.asarray(points_local, float)
    _, _, Vt = np.linalg.svd(V - V.mean(axis=0), full_matrices=False)
    a = Vt[0]
    proj = V @ a
    if abs(proj.min()) > abs(proj.max()):
        a = -a
    return -a if flip else a


def load_calib(path=None):
    path = path or WRIST["CALIB_FILE"]
    try:
        with open(path) as f:
            cal = json.load(f)
        if cal.get("sign") in (-1.0, 1.0, -1, 1) and isinstance(cal.get("bias_deg"), (int, float)):
            return cal
    except Exception:
        pass
    return None



def _quat_R(w, x, y, z):
    n = math.sqrt(w * w + x * x + y * y + z * z) or 1.0
    w, x, y, z = w / n, x / n, y / n, z / n
    return np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                     [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                     [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])


def _gf_quat_R(q):
    if q is None:
        return np.eye(3)
    im = q.GetImaginary()
    return _quat_R(float(q.GetReal()), float(im[0]), float(im[1]), float(im[2]))


class Arm:
    """Live joint angles from PhysX link poses, and joint drive targets through USD (degrees)."""
    _AX = {"X": 0, "Y": 1, "Z": 2}

    def __init__(self, stage, cfg=WRIST):
        from pxr import UsdGeom, UsdPhysics
        self.stage, self.cfg = stage, cfg
        self.j = {}
        for key in ("J2", "J5", "J6"):
            path = f'{cfg["ROBOT_PRIM"]}/joints/{cfg[key]}'
            prim = stage.GetPrimAtPath(path)
            if not prim.IsValid() or not prim.IsA(UsdPhysics.RevoluteJoint):
                raise RuntimeError(f"{path} is not a revolute joint")
            jt = UsdPhysics.RevoluteJoint(prim)
            if not prim.HasAPI(UsdPhysics.DriveAPI, "angular"):
                raise RuntimeError(f"{path} has no angular drive")
            drive = UsdPhysics.DriveAPI(prim, "angular")
            tgt = drive.GetTargetPositionAttr() or drive.CreateTargetPositionAttr(0.0)
            b0, b1 = jt.GetBody0Rel().GetTargets(), jt.GetBody1Rel().GetTargets()
            lo, hi = jt.GetLowerLimitAttr().Get(), jt.GetUpperLimitAttr().Get()
            self.j[key] = {
                "path": path, "target": tgt,
                "body0": str(b0[0]) if b0 else "", "body1": str(b1[0]) if b1 else "",
                "r0": _gf_quat_R(jt.GetLocalRot0Attr().Get()), "r1": _gf_quat_R(jt.GetLocalRot1Attr().Get()),
                "axis": self._AX.get(str(jt.GetAxisAttr().Get()), 0),
                "lo": float(lo) if lo is not None and math.isfinite(lo) else -180.0,
                "hi": float(hi) if hi is not None and math.isfinite(hi) else 180.0,
            }
        ee = stage.GetPrimAtPath(cfg["EE_PRIM"])
        if not ee.IsValid():
            raise RuntimeError(f'{cfg["EE_PRIM"]} not found')
        self.ee_path = cfg["EE_PRIM"]
        self.axis_local = nozzle_axis(self._ee_points(ee, UsdGeom), cfg["NOZZLE_FLIP"])
        self._rt = None

    @staticmethod
    def _ee_points(ee, UsdGeom):
        from pxr import Usd
        t = Usd.TimeCode.Default()
        xc = UsdGeom.XformCache(t)
        M_inv = np.linalg.inv(np.array(xc.GetLocalToWorldTransform(ee), float).T)
        pts = []
        for p in Usd.PrimRange(ee, Usd.TraverseInstanceProxies()):
            if p.IsA(UsdGeom.Mesh):
                P = UsdGeom.Mesh(p).GetPointsAttr().Get(t)
                if P is None or len(P) == 0:
                    continue
                M = M_inv @ np.array(xc.GetLocalToWorldTransform(p), float).T
                P = np.asarray(P, float)
                pts.append(P @ M[:3, :3].T + M[:3, 3])
        if not pts:
            raise RuntimeError(f"no mesh under {ee.GetPath()} to find the nozzle axis from")
        return np.concatenate(pts)

    def _R(self, path):
        """World rotation of a rigid body / link: PhysX, then Fabric."""
        if not path:
            return np.eye(3)
        try:
            import omni.physx
            r = omni.physx.get_physx_interface().get_rigidbody_transformation(path)
            if r and r.get("ret_val", False):
                q = r["rotation"]                     # x, y, z, w
                return _quat_R(q[3], q[0], q[1], q[2])
        except Exception:
            pass
        try:
            import omni.usd
            from usdrt import Rt
            from usdrt import Usd as RtUsd
            if self._rt is None:
                self._rt = RtUsd.Stage.Attach(omni.usd.get_context().get_stage_id())
            prim = self._rt.GetPrimAtPath(path)
            q = Rt.Xformable(prim).GetWorldOrientationAttr().Get()
            im = q.GetImaginary()
            return _quat_R(float(q.GetReal()), float(im[0]), float(im[1]), float(im[2]))
        except Exception:
            return None

    def angle(self, key):
        j = self.j[key]
        R0, R1 = self._R(j["body0"]), self._R(j["body1"])
        if R0 is None or R1 is None:
            return None
        return math.degrees(joint_angle(R0 @ j["r0"], R1 @ j["r1"], j["axis"]))

    def j6_axis_world(self):
        j = self.j["J6"]
        R0 = self._R(j["body0"])
        return None if R0 is None else (R0 @ j["r0"])[:, j["axis"]]

    def nozzle_world(self):
        R = self._R(self.ee_path)
        return None if R is None else R @ self.axis_local

    def target(self, key):
        v = self.j[key]["target"].Get()
        return float(v) if v is not None else 0.0

    def set_target(self, key, deg):
        j = self.j[key]
        j["target"].Set(float(min(max(deg, j["lo"]), j["hi"])))


async def _steps(n):
    import omni.kit.app
    app = omni.kit.app.get_app()
    for _ in range(int(n)):
        await app.next_update_async()


async def _settle(arm, max_s):
    """Wait until the cup orientation stops changing (or max_s of wall time)."""
    t0, last, calm = time.time(), None, 0
    while time.time() - t0 < max_s:
        await _steps(2)
        n = arm.nozzle_world()
        if n is None:
            continue
        if last is not None and tilt_deg(n, last) < 0.03:
            calm += 1
            if calm >= 5:
                return
        else:
            calm = 0
        last = n


async def _ramp(arm, goals, seconds):
    start = {k: arm.target(k) for k in goals}
    n = max(1, int(seconds * 30))
    for i in range(1, n + 1):
        for k, g in goals.items():
            arm.set_target(k, start[k] + (g - start[k]) * i / n)
        await _steps(1)


async def calibrate(cfg=WRIST):
    import omni.timeline
    import omni.usd
    inst = getattr(builtins, "_DOBOT_PNP_INSTANCE", None)
    if inst is not None and not getattr(inst, "_shutting_down", False):
        _say("BLOCK: the pick-and-place controller is running; stop it first")
        return None
    stage = omni.usd.get_context().get_stage()
    if stage is None:
        _say("BLOCK: no stage open")
        return None
    try:
        arm = Arm(stage, cfg)
    except Exception as e:
        _say(f"BLOCK: {e}")
        return None
    builtins._DOBOT_WRIST_CALIBRATING = True
    tl = omni.timeline.get_timeline_interface()
    try:
        _say("calibrating the wrist: the arm moves slowly through a few poses (joint_1 stays put). "
             "Keep the area around the simulated arm clear.")
        if tl.is_stopped():
            # Stale drive targets would make the arm jump on Play (the saved scene has some); hold the saved pose.
            for name in ("joint_1", cfg["J2"], cfg["J5"], cfg["J6"]):
                p = stage.GetPrimAtPath(f'{cfg["ROBOT_PRIM"]}/joints/{name}')
                ta, sa = p.GetAttribute("drive:angular:physics:targetPosition"), \
                    p.GetAttribute("state:angular:physics:position")
                if ta.IsValid() and sa.IsValid() and sa.Get() is not None:
                    v = math.degrees(float(sa.Get()))       # same convention as the controller's preparation
                    lo, hi = p.GetAttribute("physics:lowerLimit").Get(), p.GetAttribute("physics:upperLimit").Get()
                    if lo is None or hi is None or lo - 1.0 <= v <= hi + 1.0:
                        ta.Set(v)
        if not tl.is_playing():
            tl.play()
        await _steps(30)
        start = {k: arm.target(k) for k in ("J2", "J5", "J6")}
        sums, j6s, errs, offplane = [], [], [], []
        j6 = arm.j["J6"]
        _say(f"nozzle axis in the {cfg['EE_PRIM'].split('/')[-1]} frame: {np.round(arm.axis_local, 3)}"
             f"{' (flipped)' if cfg['NOZZLE_FLIP'] else ''}; joint_6 limits {j6['lo']:.0f}..{j6['hi']:.0f} deg")

        def reading():
            n, a = arm.nozzle_world(), arm.j6_axis_world()
            if n is None or a is None:
                raise RuntimeError("cannot read the live link poses from PhysX")
            return best_turn(n, a)            # (signed in-plane error about joint_6's axis, out-of-plane part)

        # Which way does a positive joint_6 target turn the cup about the measured axis? One small test move.
        e0, _ = reading()
        probe = 8.0 if arm.target("J6") + 8.0 <= j6["hi"] else -8.0
        before = arm.target("J6")
        await _ramp(arm, {"J6": before + probe}, 0.6)
        await _settle(arm, cfg["SETTLE_S"])
        e1, _ = reading()
        d = wrap180(e0 - e1)                  # how much the error shrank per `probe` degrees of joint_6
        if abs(d) < 0.3 * abs(probe):
            raise RuntimeError(f"joint_6 barely turns the cup ({d:.1f} deg for a {probe:.0f} deg move); is the "
                               "joint driven? (stiffness, limits)")
        k_dir = 1.0 if d * probe > 0 else -1.0
        await _ramp(arm, {"J6": before}, 0.6)
        _say(f"joint_6 turns the cup {'with' if k_dir > 0 else 'against'} its measured axis "
             f"({abs(d):.1f} deg per {abs(probe):.0f} deg)")

        for k, (f2, f5) in enumerate(cfg["POSES"]):
            j2, j5 = arm.j["J2"], arm.j["J5"]
            g2, g5 = j2["lo"] + f2 * (j2["hi"] - j2["lo"]), j5["lo"] + f5 * (j5["hi"] - j5["lo"])
            await _ramp(arm, {"J2": g2, "J5": g5}, cfg["RAMP_S"])
            await _settle(arm, cfg["SETTLE_S"])
            for it in range(cfg["ITERATIONS"]):
                err, _ = reading()
                if abs(err) <= cfg["TOL_DEG"]:
                    break
                want = arm.target("J6") + k_dir * err
                if not j6["lo"] <= want <= j6["hi"]:
                    _say(f"pose {k + 1}: level joint_6 ({want:.1f}) is outside its limits; pose skipped")
                    break
                await _ramp(arm, {"J6": want}, 0.4 + min(1.5, abs(err) / 40.0))
                await _settle(arm, cfg["SETTLE_S"])
            err, off = reading()
            q2, q5, q6 = arm.angle("J2"), arm.angle("J5"), arm.angle("J6")
            level6 = q6 + k_dir * err          # exact level angle from what is left, even if not fully there
            used = abs(err) <= 3.0
            _say(f"pose {k + 1}/{len(cfg['POSES'])}: joint_2 {q2:6.1f}  joint_5 {q5:6.1f}  -> level joint_6 "
                 f"{level6:7.1f} deg (left {err:+.1f} deg in the arm plane; {off:.1f} deg across it is the mesh "
                 f"shape, ignored){'' if used else '  NOT USED (cup blocked - touching the table or an object?)'}")
            if used:
                sums.append(q2 + q5)
                j6s.append(level6)
                errs.append(abs(err))
                offplane.append(off)
        if len(sums) < 3:
            _say("BLOCK: fewer than 3 poses could be levelled; not saved")
            return None
        s, b, res = fit_rule(sums, j6s)
        cal = {"sign": s, "bias_deg": b, "bias_rad": math.radians(b), "residual_deg": res,
               "max_tilt_deg": max(errs + [res]), "nozzle_offplane_deg": max(offplane),
               "nozzle_flip": bool(cfg["NOZZLE_FLIP"]),
               "nozzle_axis_local": [round(float(v), 5) for v in arm.axis_local],
               "poses": [{"j2_plus_j5": round(x, 3), "j6": round(y, 3)} for x, y in zip(sums, j6s)],
               "stage": stage.GetRootLayer().identifier, "created": time.strftime("%Y-%m-%d %H:%M:%S")}
        _say(f"result: joint_6 = {s:+.0f} * (joint_2 + joint_5) {b:+.2f} deg from {len(sums)} poses; worst misfit "
             f"{res:.2f} deg (the cup's tilt in the arm plane after levelling)")
        if max(offplane) > 2.0:
            _say(f"note: the measured nozzle direction leans {max(offplane):.1f} deg across the arm plane. That is "
                 "the lopsided suction mesh (bracket and servo on one side), not a real tilt; joint_6 cannot change it.")
        if res > cfg["MAX_RESIDUAL_DEG"]:
            _say(f"BLOCK: one rule does not fit every pose ({res:.1f} deg); joint_6 may not be the cup's pitch "
                 "joint in this model. Not saved; send me these lines.")
            return None
        os.makedirs(os.path.dirname(cfg["CALIB_FILE"]), exist_ok=True)
        with open(cfg["CALIB_FILE"], "w") as f:
            json.dump(cal, f, indent=2)
        _say(f"saved {cfg['CALIB_FILE']}")
        builtins._DOBOT_WRIST_CALIBRATING = False
        install_leveler(cal, cfg)
        await _ramp(arm, {"J2": start["J2"], "J5": start["J5"]}, cfg["RAMP_S"])
        _say("back at the start pose with the leveler on. LOOK at the robot now: the cup should hang straight "
             "DOWN like the real one. Drag joint_2 / joint_5 drive targets (Property panel) to check it stays "
             "vertical. If it points UP, set WRIST['NOZZLE_FLIP'] = True and run this file again. "
             "Stop the timeline when done (nothing was saved to the USD).")
        return cal
    except Exception as e:
        _say(f"calibration failed: {e}")
        return None
    finally:
        builtins._DOBOT_WRIST_CALIBRATING = False


# ---- leveler: joint_6 follows joint_2 + joint_5 while the timeline plays ---------------------------------
def install_leveler(cal=None, cfg=WRIST):
    """Keep the cup vertical whenever physics runs and no controller is driving the arm. Returns True if on."""
    remove_leveler()
    cal = cal or load_calib(cfg["CALIB_FILE"])
    if cal is None:
        return False
    import omni.physx
    import omni.usd
    state = {"arm": None, "stage": None, "n": 0, "err": 0}

    def on_step(_dt):
        state["n"] += 1
        if state["n"] % max(1, cfg["LEVELER_EVERY"]):
            return
        if getattr(builtins, "_DOBOT_WRIST_CALIBRATING", False):
            return
        inst = getattr(builtins, "_DOBOT_PNP_INSTANCE", None)
        if inst is not None and not getattr(inst, "_shutting_down", False):
            return                                      # the controller drives joint_6 itself
        try:
            stage = omni.usd.get_context().get_stage()
            if state["arm"] is None or state["stage"] is not stage:
                state["arm"], state["stage"] = Arm(stage, cfg), stage
            arm = state["arm"]
            q2, q5 = arm.angle("J2"), arm.angle("J5")
            if q2 is None or q5 is None:
                return
            cur = arm.target("J6")
            j6 = arm.j["J6"]
            v = level_value(q2, q5, cal, j6["lo"], j6["hi"], cur)
            if abs(v - cur) > cfg["LEVELER_DEADBAND_DEG"]:
                arm.set_target("J6", v)
        except Exception as e:
            state["arm"] = None
            state["err"] += 1
            if state["err"] <= 2:
                _say(f"leveler skipped a step: {e}")

    builtins._DOBOT_WRIST_LEVELER = omni.physx.get_physx_interface().subscribe_physics_step_events(on_step)
    _say(f"leveler on: joint_6 = {cal['sign']:+.0f} * (joint_2 + joint_5) {cal['bias_deg']:+.2f} deg "
         "while the timeline plays and no controller is running")
    return True


def remove_leveler():
    sub = getattr(builtins, "_DOBOT_WRIST_LEVELER", None)
    builtins._DOBOT_WRIST_LEVELER = None
    if sub is not None:
        try:
            sub.unsubscribe()
        except Exception:
            pass


def controller_overrides(cfg=WRIST):
    """CFG overrides for the V2/V3 controller: the calibrated rule instead of the mesh-shape guess."""
    cal = load_calib(cfg["CALIB_FILE"])
    if cal is None:
        return {}
    return {"PITCH_SIGN": float(cal["sign"]), "PITCH_BIAS": float(cal["bias_rad"])}



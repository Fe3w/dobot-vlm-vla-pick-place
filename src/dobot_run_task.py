        self.ccfg = dict(self.mods["capture"].CAP, **(light.get("CAPTURE") or {}), **cfg["CAPTURE_OVERRIDES"])
        self.vcfg = dict(self.mods["vlm"].VLM, **cfg["VLM_OVERRIDES"])

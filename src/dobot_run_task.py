    def v3cfg_wrist_file(self):
        v3 = getattr(self, "v3cfg", None) or self.mods["v3"].V3
        return v3.get("WRIST_CALIB_FILE") or os.path.join(_DOBOT_ASSETS, "dobot_wrist_calib.json")

    # ---- ui hooks ------------------------------------------------------------
    def status(self, text):
        _log(text)
        if self.ui:
            self.ui["status"].text = text

    def step(self, text, ok=None):
        mark = {True: "[ok]", False: "[x]", None: "[..]"}[ok]
        line = f"{mark} {text}"
        _log(line)
        if self.ui:
            self.ui["steps"].append(line)
            self.ui["log"].text = "\n".join(self.ui["steps"][-9:])

    # ---- scene ---------------------------------------------------------------
    async def _frames(self, n):
        for _ in range(int(n)):
            await self.app.next_update_async()

    async def stop_everything(self, reason="stop"):
        inst = getattr(builtins, "_DOBOT_PNP_INSTANCE", None)
        if inst is not None and not getattr(inst, "_shutting_down", False):
            try:
                inst.shutdown(reason)
            except Exception as e:
                _log(f"controller shutdown reported {e!r}")
        if not self.tl.is_stopped():
            self.tl.stop()
        for _ in range(120):
            if self.tl.is_stopped():
                break
            await self.app.next_update_async()
        return self.tl.is_stopped()

    async def reset_scene(self):
        path = self.cfg["STAGE_FILE"]
        if not os.path.isfile(path):
            raise RuntimeError(f"stage file not found: {path}")
        if not any(n in os.path.basename(path).lower() for n in self.cfg["ALLOWED_STAGE_NAMES"]):
            raise RuntimeError(f"refusing to reset to {path}: not a Dobot test copy")
        if not await self.stop_everything("scene reset"):
            raise RuntimeError("the timeline did not stop; stop it from the UI")
        reload = getattr(self.mods["v3"], "reload_stage", None)
        self.last_reset = "reopened"
        if reload is not None and not self.full_reload:
            how = await reload(self.ctx, self.app, path)
            self.last_reset = how
            _log(f"scene reloaded ({how})")
        else:
            await self.ctx.open_stage_async(path)
            for _ in range(600):
                await self.app.next_update_async()
                try:
                    if not self.ctx.is_stage_loading():
                        break
                except Exception:
                    break
        await self._frames(30)                    # let the renderer settle before any capture
        builtins._DOBOT_PNP_LAST_PLACED = None
        builtins._DOBOT_PNP_INSTANCE = None
        try:
            try:
                from isaacsim.util.debug_draw import _debug_draw
            except ImportError:
                from omni.isaac.debug_draw import _debug_draw
            dd = _debug_draw.acquire_debug_draw_interface()
            dd.clear_points()
            dd.clear_lines()
        except Exception:
            pass
        if not await self.stop_everything("after reload"):
            raise RuntimeError("the timeline did not stay stopped after reload")
        if self.wrist is not None:
            try:
                self.wrist.install_leveler()              # re-read the reloaded joints
            except Exception as e:
                _log(f"wrist leveler not re-armed: {e}")
        self.watch.attach()

    # ---- pipeline ------------------------------------------------------------
    async def run_task(self, text, batch=None):
        record = {"time": time.strftime("%Y-%m-%d %H:%M:%S"), "task": text, "steps": []}
        self.last_stage = None
        if batch:
            record["batch"] = batch
        tee = _Tee(sys.stdout)
        sys.stdout = tee
        t_start = time.time()
        saved_overrides = dict(self.v3cfg.get("CFG_OVERRIDES", {}))
        try:
            vlm, cap_mod, v3 = self.mods["vlm"], self.mods["capture"], self.mods["v3"]
            mem = memory_snapshot()
            record["memory_before"] = mem
            low = memory_problem(mem, self.cfg)
            if low:
                record["status"] = "memory_low"
                return self._fail(record, "memory", f"{low}. Restart Isaac Sim (start_dobot.sh) before the next run "
                                                    f"so it does not crash mid-motion")
            loop = asyncio.get_event_loop()

            self.status("Checking the VLM engine ...")
            routes, lines = await loop.run_in_executor(None, vlm.check_engines, self.vcfg)
            n_all = sum(1 for e in self.vcfg["ENGINES"] if e.get("enabled", True))
            record["routes"] = lines
            if not routes and not self.vcfg.get("KEYWORD_FALLBACK"):
                return self._fail(record, "VLM engine", "offline (no route answered the health check)")
            if routes:
                self.step("VLM engine online", True)
            else:
                self.step("VLM engine offline: the task wording will be used if it is unambiguous")

            self.status("Resetting the scene ...")
            await self.reset_scene()
            self.step(f"scene reset to {os.path.basename(self.cfg['STAGE_FILE'])}", True)

            real_scan = None
            if self.real_mode:
                # no depth camera in the lab: the Phone camera window shows the RGB view instead of the depth view
                self.v3cfg["CFG_OVERRIDES"] = dict(saved_overrides, DEPTH_VIZ=False, DEPTH_RENDERED=False,
                                                   VIZ_CAMERA_RAYS=False)
                self.view_steps, self.view_task, self.tip_trail = None, text, []
                self.status("Scanning the real table with the phone camera ...")
                real_scan, why = await self.real_scene_step()
                if real_scan is None:
                    return self._fail(record, "real scene", why)
                record["real_scan"] = real_scan["scan_id"]
                self.view_scan = real_scan
                self.step(f"real scene: {len(real_scan['objects'])} objects "
                          f"({', '.join(o['name'] for o in real_scan['objects'])}) mirrored into the simulation", True)

            self.status("Capturing the overhead camera ...")
            try:
                cap = await cap_mod.capture(self.ccfg)
            except RuntimeError as e:
                if "non-black" not in str(e) or self.last_reset != "in place":
                    raise
                self.step("camera gave no image after the in-place reset; reopening the scene instead")
                self.full_reload = True           # reopen the file from now on in this session
                await self.reset_scene()
                if real_scan is not None:          # the reopen removed the stand-ins: mirror the table again
                    real_scan, why = await self.real_scene_step()
                    if real_scan is None:
                        return self._fail(record, "real scene", why)
                cap = await cap_mod.capture(self.ccfg)
            if not cap or not cap.get("camera_check", {}).get("passed"):
                return self._fail(record, "capture",
                                  tee.last("BLOCK", "FAIL", "WARNING") or "capture failed (see console)")
            names = [o.get("name") for o in (cap.get("objects") or {}).values() if o.get("visible", True)]
            names = [n for n in names if n]
            record["capture_id"] = cap.get("capture_id")
            self.step(f"captured {cap['capture_id']}" + (f" ({len(names)} objects found)" if names else
                                                        " (camera check passed)"), True)

            self.status("VLM engine: reading the scene and the task ...")
            doc, msg = await vlm.run_async(self.vcfg, text, routes)
            if doc is None:
                return self._fail(record, "VLM engine", msg)
            t = doc["task"]
            record["grounding"] = {k: t.get(k) for k in ("target_prim", "reference_prim", "relation", "avoid_prims",
                                                          "decided_by", "routed_via", "confidence")}
            self.step(f"VLM engine: {msg}", True)

            self.status("Planning and moving the robot ...")
            builtins._DOBOT_PNP_INSTANCE = None
            await v3.run_v3(self.v3cfg)
            inst = getattr(builtins, "_DOBOT_PNP_INSTANCE", None)
            task = getattr(inst, "_task", None) if inst is not None else None
            if inst is None:
                return self._fail(record, "controller start",
                                  tee.last("BLOCK", "NOT STARTED", "problem:") or "controller did not start")
            self.step("controller started; robot moving (Stop halts it)")
            if task is not None and not task.done():
                try:
                    await asyncio.wait_for(asyncio.shield(task), timeout=self.cfg["ROBOT_TIMEOUT_S"])
                except asyncio.TimeoutError:
                    await self.stop_everything("timeout")
                    return self._fail(record, "robot", f"no finish within {self.cfg['ROBOT_TIMEOUT_S']} s; stopped")
            await self._frames(5)
            record["tracking_worst_mm"] = getattr(builtins, "_DOBOT_PNP_LAST_TRACKING", None)
            placed = getattr(builtins, "_DOBOT_PNP_LAST_PLACED", None)
            if not placed:
                return self._fail(record, "robot", tee.last("pipeline failed", "aborted", "WARNING", "Error")
                                  or "the controller stopped before placing the object")
            to = [round(float(x) * 1e3) for x in placed["to"]]
            record["result"] = {"placed_mm_base_frame": to}
            names = dict(self.vcfg.get("OBJECT_NAMES", {}), **(doc.get("objects") or {}))
            nm = lambda p: names.get(p) or vlm.name_of(self.vcfg, p)
            self.step(f"placed: {nm(t['target_prim'])} {vlm.RELATION_TEXT[t['relation']]} "
                      f"{nm(t['reference_prim'])} (now at {to} mm, robot base frame)", True)
            final = getattr(builtins, "_DOBOT_PNP_LAST_FINAL", None)
            check = None
            if hasattr(v3, "evaluate_result") and cap.get("objects"):
                try:
                    check = v3.evaluate_result(cap, t, final, self.v3cfg)
                except Exception as e:
                    check = {"passed": False, "checks": [], "summary": f"check could not run ({e})"}
            if check is not None:
                record["check"] = {"passed": check["passed"], "summary": check["summary"],
                                   "checks": check["checks"]}
                self.step(("check passed: " if check["passed"] else "check FAILED: ") + check["summary"],
                          check["passed"])
            ok = check is None or check["passed"]
            if real_scan is not None:
                self.write_real_plan(text, cap, real_scan, check)
            record["status"] = "success" if ok else "check_failed"
            self.status(f"{'Done' if ok else 'Placed, but the result does not match the task'} in "
                        f"{time.time() - t_start:.0f} s. Press Reset scene or type the next task.")
            return ok
        except asyncio.CancelledError:
            record["status"] = "stopped"
            self.step("stopped by user", False)
            self.status("Stopped.")
            raise
        except Exception as e:
            return self._fail(record, "runner", str(e))
        finally:
            if self.real_mode:
                self.v3cfg["CFG_OVERRIDES"] = saved_overrides
            sys.stdout = tee.orig
            record["seconds"] = round(time.time() - t_start, 1)
            try:
                import gc
                gc.collect()
            except Exception:
                pass
            record["memory_after"] = memory_snapshot()
            self._append_run(record)

    def _fail(self, record, stage, why):
        self.last_stage = stage
        record.update(status="failed", failed_stage=stage, reason=why)
        self.step(f"{stage}: {why}", False)
        self.status(f"Stopped at {stage}. Nothing else was run. Fix the cause and press Run task again.")
        return False

    def _append_run(self, record):
        try:
            root = self.ccfg["CAPTURE_ROOT"]
            os.makedirs(root, exist_ok=True)
            with open(os.path.join(root, "runs.jsonl"), "a") as f:
                f.write(json.dumps(record) + "\n")
        except Exception:
            pass


class TaskRunner:
    def __init__(self, cfg=RUN):
        import omni.kit.app
        import omni.timeline
        import omni.usd
        self.cfg = cfg
        self.app = omni.kit.app.get_app()
        self.tl = omni.timeline.get_timeline_interface()
        self.ctx = omni.usd.get_context()
        self.mods, self.paths = load_modules(cfg)

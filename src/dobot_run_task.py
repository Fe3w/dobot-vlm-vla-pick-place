"""
Dobot one-click task runner (Isaac Sim 6.0.x Script Editor).

Run THIS file only. It opens a "Dobot pick-and-place" window:

    [ task text box                                   ]
    [Run task]  [Reset scene]  [Stop]
    status + step log

Run task
    1. checks the VLM engine's routes (health, keys, model availability);
    2. resets the scene: stops the timeline, reloads the saved stage file;
    3. captures /overhead_camera (dobot_capture_overhead.py);
    4. grounds the typed task with the VLM engine (dobot_vlm_keypoints.py:
       tagged image, routes raced in parallel, wording cross-check, deadline);
    5. runs the guarded controller (dobot_pnp_run_simulation_v3.py, which loads
       the reviewed V2 controller) and waits for the robot to finish;
    6. reports success (where the object ended up) or the reason it stopped.
    The scene is left as the robot left it so you can look; press Reset scene
    (or simply Run task again, which resets first).
Reset scene
    Stops any controller and the timeline, reloads the saved stage file.
Stop
    Stops the controller and the timeline at once (cancels a running task).

The three scripts are loaded from SCRIPT_DIR (or found under SEARCH_ROOTS) with
their own auto-run disabled; their settings (VLM provider, model, V2 path, ...)
can be overridden in RUN below. Nothing is ever saved to the USD file.
Every run is appended to <CAPTURE_ROOT>/runs.jsonl.
"""


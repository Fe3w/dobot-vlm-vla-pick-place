    def start(self, coro_fn, *args):
        if self.busy:
            return False
        self.busy = True
        self.watch.paused = True
        if self.ui:
            for b in ("run", "reset", "tests"):
                if b in self.ui:
                    self.ui[b].enabled = False

        async def wrapped():
            try:
                await coro_fn(*args)
            except asyncio.CancelledError:
                pass
            except Exception as e:
                self.status(f"Error: {e}")
            finally:
                self.busy = False
                self.job = None
                self.watch.paused = False
                if self.ui:
                    for b in ("run", "reset", "tests"):
                        if b in self.ui:
                            self.ui[b].enabled = True
        self.job = asyncio.ensure_future(wrapped())
        return True

    async def real_scene_step(self):
        """Run `dobot_real.py scan` (its own Python), mirror the result into the stage. (scan|None, reason)."""
        if self.real is None:
            return None, f"dobot_real.py not found next to the scripts ({self.real_path})"
        rc = self.cfg.get("REAL", {})
        py = rc.get("PYTHON")
        if not py or not os.path.isfile(py):
            return None, f"the real-robot Python environment is missing ({py}); see the setup guide"
        import subprocess
        loop = asyncio.get_event_loop()

        def run():
            return subprocess.run([py, self.real_path, "scan", "--json"], capture_output=True, text=True,
                                  timeout=rc.get("SCAN_TIMEOUT_S", 90))
        try:
            r = await loop.run_in_executor(None, run)
        except Exception as e:
            return None, f"scan did not finish ({e})"
        path = next((l.split(" ", 1)[1].strip() for l in r.stdout.splitlines() if l.startswith("REAL_SCENE_JSON ")),
                    None)
        if r.returncode not in (0, 2) or not path:
            last = [l for l in (r.stdout + r.stderr).splitlines() if l.strip()]
            return None, (last[-1][-200:] if last else f"scan failed (exit {r.returncode})")
        with open(path) as f:
            scan = json.load(f)
        scan["path"] = path
        if not scan["objects"]:
            return None, "the camera sees no objects on the table (background photo up to date?)"
        stage = self.ctx.get_stage()
        W, H = int(self.ccfg["WIDTH"]), int(self.ccfg["HEIGHT"])
        snap = self.mods["capture"].scene_snapshot(stage, self.ccfg, W, H)
        sim_objs = snap[5]
        import numpy as _np
        from pxr import UsdGeom
        mpu = float(UsdGeom.GetStageMetersPerUnit(stage) or 1.0)
        base = stage.GetPrimAtPath(self.ccfg["BASE_PRIM"])
        Tb = self.mods["capture"]._usd_world(base, mpu)
        if rc.get("SIM_TABLE_Z_WORLD_M") is not None:
            zw = float(rc["SIM_TABLE_Z_WORLD_M"])
        elif sim_objs:
            zw = float(_np.median([o["min"][2] for o in sim_objs.values()]))
        else:
            return None, "no object on the simulated table to measure its height from; set REAL SIM_TABLE_Z_WORLD_M"
        table_base = float((_np.linalg.inv(Tb) @ _np.array([Tb[0, 3], Tb[1, 3], zw, 1.0]))[2])
        frame = {"yaw_deg": float(self.real.REAL["YAW_DEG"]), "table_z_dobot_mm": float(scan["table_z_dobot_mm"]),
                 "table_z_sim_base_m": table_base}
        specs = self.real.proxy_specs(scan, frame, Tb)
        apply_real_scene(stage, specs, list(sim_objs))
        for _ in range(20):
            await self.app.next_update_async()
        scan["frame"] = frame
        self.last_frame = frame
        return scan, ""

    def write_real_plan(self, text, cap, scan, check):
        """Hand the checked simulated run to `dobot_real.py execute`."""

def find_scripts(cfg):
    names = list(cfg["SCRIPTS"].values())
    dirs = []
    if cfg["SCRIPT_DIR"]:
        dirs.append(cfg["SCRIPT_DIR"])
    here = globals().get("__file__")
    if here and os.path.isfile(here):
        dirs.append(os.path.dirname(os.path.abspath(here)))
    for d in dirs:
        if all(os.path.isfile(os.path.join(d, n)) for n in names):
            return {k: os.path.join(d, n) for k, n in cfg["SCRIPTS"].items()}
    skip = {".git", "node_modules", "__pycache__", ".cache", ".local", "site-packages", "env_isaacsim",
            ".nvidia-omniverse", "snap", "vlm_runs", "isaac_capture"}
    found = {}
    for root in cfg["SEARCH_ROOTS"]:
        if not os.path.isdir(root):
            continue
        base = root.rstrip("/").count("/")
        for r, ds, fs in os.walk(root):
            ds[:] = [d for d in ds if d not in skip]
            if r.count("/") - base >= 7:
                ds[:] = []
            if all(n in fs for n in names):                       # prefer a folder holding all three
                return {k: os.path.join(r, n) for k, n in cfg["SCRIPTS"].items()}
            for k, n in cfg["SCRIPTS"].items():
                if n in fs and k not in found:
                    found[k] = os.path.join(r, n)
    missing = [cfg["SCRIPTS"][k] for k in cfg["SCRIPTS"] if k not in found]
    if missing:
        raise RuntimeError(f"cannot find {missing}; put the scripts in one folder and set RUN['SCRIPT_DIR']")
    return found


def load_modules(cfg):
    paths = find_scripts(cfg)
    saved = {f: os.environ.get(f) for f in _AUTORUN_FLAGS}
    mods = {}
    try:
        for f in _AUTORUN_FLAGS:
            os.environ[f] = "1"                  # load as libraries: no windows, no auto-start
        for key, path in paths.items():
            spec = importlib.util.spec_from_file_location(f"dobot_run_{key}", path)
            m = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(m)
            mods[key] = m
            _log(f"loaded {os.path.basename(path)} from {os.path.dirname(path)}")
    finally:
        for f, v in saved.items():
            if v is None:
                os.environ.pop(f, None)
            else:
                os.environ[f] = v
    for key, attr in (("capture", "capture"), ("vlm", "run_async"), ("vlm", "check_engines"), ("v3", "run_v3")):
        if not hasattr(mods[key], attr):
            raise RuntimeError(f"{paths[key]} has no {attr}(); use the matching versions of the scripts")
    return mods, paths


class _Tee:
    """Copies console output into a list while a run is active (to show the reason a stage stopped)."""

    def __init__(self, orig):
        self.orig, self.lines, self._part = orig, [], ""

    def write(self, s):
        self.orig.write(s)
        self._part += s
        while "\n" in self._part:
            line, self._part = self._part.split("\n", 1)
            self.lines.append(line)
            del self.lines[:-400]
        return len(s)

    def flush(self):
        self.orig.flush()

    def last(self, *needles):
        for line in reversed(self.lines):
            if any(n in line for n in needles):
                return line.strip()
        return None


class EditWatch:
    """Notices scene edits the user makes between runs (objects added, deleted, moved).

    Run task reloads the SAVED stage file, so unsaved edits would be silently thrown away. Edits made while a
    run is in progress (the controller's own in-memory preparation, physics) are not the user's and are
    ignored; so is everything under the controller's debug-draw root."""
    IGNORE = ("/World/VisualDebug",)

    def __init__(self, ctx):
        self.ctx = ctx
        self.stage = None
        self.listener = None
        self.paused = False
        self.edited = False

    def attach(self):
        """(Re)attach to the open stage; call after every reload."""
        try:
            from pxr import Tf, Usd
            stage = self.ctx.get_stage()
            if stage is None:
                return
            if self.listener is not None:
                self.listener.Revoke()
            self.stage = stage
            self.edited = False
            self.listener = Tf.Notice.Register(Usd.Notice.ObjectsChanged, self._changed, stage)
        except Exception as e:
            self.listener = None
            _log(f"scene edit watch unavailable ({e})")

    def _changed(self, notice, sender):
        if self.paused:
            return
        try:
            paths = [str(p) for p in list(notice.GetResyncedPaths()) + list(notice.GetChangedInfoOnlyPaths())]
        except Exception:
            paths = ["?"]
        if any(not any(p.startswith(i) for i in self.IGNORE) for p in paths):
            self.edited = True

    def unsaved_edits(self):
        """True when the user changed the open stage and has not saved it."""
        try:
            stage = self.ctx.get_stage()
            if stage is None:
                return False
            dirty = bool(stage.GetRootLayer().dirty)
            if self.listener is None or stage is not self.stage:
                return dirty                     # cannot tell who edited it: be safe
            return dirty and self.edited
        except Exception:
            return False


def memory_snapshot():
    """{"rss_mb", "ram_free_mb", "gpu_used_mb", "gpu_free_mb"} for this Isaac Sim process (None where unknown)."""
    out = {"rss_mb": None, "ram_free_mb": None, "gpu_used_mb": None, "gpu_free_mb": None}
    try:
        with open("/proc/self/status") as f:
            for l in f:
                if l.startswith("VmRSS:"):
                    out["rss_mb"] = int(l.split()[1]) // 1024
        with open("/proc/meminfo") as f:
            for l in f:
                if l.startswith("MemAvailable:"):
                    out["ram_free_mb"] = int(l.split()[1]) // 1024
    except Exception:
        pass
    try:
        import subprocess
        r = subprocess.run(["nvidia-smi", "--query-gpu=memory.used,memory.free", "--format=csv,noheader,nounits"],
                           capture_output=True, text=True, timeout=3)
        used, free = [int(x) for x in r.stdout.strip().splitlines()[0].split(",")]
        out.update(gpu_used_mb=used, gpu_free_mb=free)
    except Exception:
        pass
    return out


def memory_problem(mem, cfg):
    if mem.get("ram_free_mb") is not None and mem["ram_free_mb"] < cfg.get("MIN_FREE_RAM_MB", 0):
        return f"only {mem['ram_free_mb']} MB of system memory free"
    if mem.get("gpu_free_mb") is not None and mem["gpu_free_mb"] < cfg.get("MIN_FREE_GPU_MB", 0):
        return f"only {mem['gpu_free_mb']} MB of GPU memory free"
    return None


def apply_real_scene(stage, specs, hide_paths):
    """Hide the simulated objects and add stand-ins for the scanned real ones (in memory; never saved)."""
    import math as _m
    from pxr import Gf, UsdGeom, UsdPhysics, Vt
    for p in hide_paths:
        prim = stage.GetPrimAtPath(p)
        if prim.IsValid():
            prim.SetActive(False)
    for sp in specs:
        if stage.GetPrimAtPath(sp["path"]).IsValid():
            stage.RemovePrim(sp["path"])
        g = getattr(UsdGeom, sp["type"]).Define(stage, sp["path"])
        if sp["type"] == "Cube":
            g.CreateSizeAttr(1.0)
        else:
            g.CreateRadiusAttr(0.5)
            if sp["type"] != "Sphere":
                g.CreateHeightAttr(1.0)
                g.CreateAxisAttr("Z")
        g.CreateExtentAttr(Vt.Vec3fArray([Gf.Vec3f(-0.5, -0.5, -0.5), Gf.Vec3f(0.5, 0.5, 0.5)]))
        xf = UsdGeom.Xformable(g)
        xf.ClearXformOpOrder()
        xf.AddTranslateOp().Set(Gf.Vec3d(*sp["translate"]))
        y = sp["yaw_rad"]
        xf.AddOrientOp().Set(Gf.Quatf(_m.cos(y / 2), 0.0, 0.0, _m.sin(y / 2)))
        xf.AddScaleOp().Set(Gf.Vec3f(*sp["scale"]))
        g.CreateDisplayColorAttr(Vt.Vec3fArray([Gf.Vec3f(*sp["color"])]))
        prim = g.GetPrim()
        UsdPhysics.CollisionAPI.Apply(prim)
        if sp["pickable"]:
            UsdPhysics.RigidBodyAPI.Apply(prim)
            UsdPhysics.MassAPI.Apply(prim).CreateMassAttr(0.05)



def apply_frame_cap(fps):
    """Cap Kit's main loop at fps (runtime setting, not saved). Returns True if applied."""
    if not fps:
        return False
    try:
        import carb.settings
        s = carb.settings.get_settings()
        s.set("/app/runLoops/main/rateLimitEnabled", True)
        s.set("/app/runLoops/main/rateLimitFrequency", int(fps))
        return True
    except Exception as e:
        print(f"[DobotRun] frame-rate cap not applied ({e})")
        return False


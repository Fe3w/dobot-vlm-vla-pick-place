        self.real_path = self.cfg.get("REAL", {}).get("SCRIPT") or \
            os.path.join(os.path.dirname(self.paths["capture"]), "dobot_real.py")
        if os.path.isfile(self.real_path):
            try:
                spec = importlib.util.spec_from_file_location("dobot_run_real", self.real_path)
                self.real = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(self.real)
            except Exception as e:
                _log(f"dobot_real.py not usable here ({e}); real-scene mode off")
                self.real = None
        self.link = None
        lp = os.path.join(os.path.dirname(self.paths["capture"]), "dobot_link.py")
        if os.path.isfile(lp):
            try:
                spec = importlib.util.spec_from_file_location("dobot_run_link", lp)
                self.link = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(self.link)
            except Exception as e:
                _log(f"dobot_link.py not usable here ({e})")

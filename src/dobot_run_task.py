    def open_phone_view(self):
        """A window in Isaac Sim showing the phone camera (snapshot URL from dobot_real.py), ~4 frames per second."""
        import omni.ui as ui
        if self.real is None:
            self.status("Phone view needs dobot_real.py next to the other scripts.")
            return
        url = self.real.REAL.get("PHONE_URL") or ""
        if not url.lower().split("?")[0].endswith((".jpg", ".jpeg")):
            self.status("Phone view needs the camera app's snapshot URL (…/shot.jpg) in REAL['PHONE_URL'].")
            return
        old = getattr(builtins, "_DOBOT_PHONE_VIEW", None)
        if old is not None:
            old["win"].visible = True
            return
        win = ui.Window("Phone camera", width=1100, height=420)
        with win.frame:
            with ui.VStack():
                prov = ui.ByteImageProvider()
                try:
                    ui.ImageWithProvider(prov, fill_policy=ui.IwpFillPolicy.IWP_PRESERVE_ASPECT_FIT)
                except Exception:
                    ui.ImageWithProvider(prov)
                note = ui.Label(f"connecting to {url} ...", height=20)
        st = {"win": win, "prov": prov, "note": note}
        builtins._DOBOT_PHONE_VIEW = st

        def fetch():
            import io
            import urllib.request
            import numpy as _np
            from PIL import Image
            opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
            data = opener.open(url, timeout=3).read()
            im = Image.open(io.BytesIO(data)).convert("RGB")
            if self.rgbv is not None and self.real_mode and self.view_scan is not None:
                try:
                    cal = self.real.load_calib(self.real.REAL)
                    if list(cal.get("image_size") or [im.width, im.height]) == [im.width, im.height]:
                        arr = self.rgbv.render(_np.asarray(im), self.view_scan, cal, steps=self.view_steps,
                                               tip_trail=list(self.tip_trail),
                                               title=(f"plan: {self.view_task}" if self.view_steps else
                                                      f"scan {self.view_scan.get('scan_id', '')}"),
                                               note="outlines from the last scan; heights from the catalogue")
                        im = Image.fromarray(arr)
                except Exception as e:
                    _log(f"phone view overlay skipped: {e}")
            if im.width > 1600:
                im = im.resize((1600, round(im.height * 1600 / im.width)))
            im = im.convert("RGBA")
            return _np.ascontiguousarray(_np.asarray(im)), im.width, im.height

        async def loop():
            lp = asyncio.get_event_loop()
            fails = 0
            while win.visible:
                try:
                    arr, w, h = await lp.run_in_executor(None, fetch)
                    try:
                        prov.set_data_array(arr, [w, h])
                    except Exception:
                        prov.set_bytes_data(arr.flatten().tolist(), [w, h])
                    note.text = f"{url}   {w}x{h}"
                    fails = 0
                except Exception as e:
                    fails += 1
                    note.text = f"no image from {url}: {str(e)[:80]} (app running? same network?)"
                    await asyncio.sleep(min(5.0, 0.5 * fails))
                await asyncio.sleep(0.25)
            builtins._DOBOT_PHONE_VIEW = None
        asyncio.ensure_future(loop())


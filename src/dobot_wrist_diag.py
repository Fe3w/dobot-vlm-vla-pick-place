"""
dobot_wrist_diag.py - why can't the simulated wrist level the cup when the forearm is folded up?

Run in Isaac Sim (Window > Script Editor > open > Run), scene open, after dobot_wrist_level.py has saved
dobot_wrist_calib.json. Nothing is saved to the USD; stop the timeline afterwards (the task window reloads the
scene before every run).

It moves the arm to the poses where calibration got stuck, asks joint_6 for the level angle, and reports:
  * every contact the suction link / wrist touches (self-collision with the arm, the table, an object);
  * joint_6's target vs. where it actually is, and its drive stiffness / damping / max force;
  * the articulation's self-collision setting.
Then, with TRY_FIX = True, it applies the matching fix IN MEMORY and repeats the test, so you see whether it
works before anything is made permanent:
  * contacts with other robot links  -> those link pairs stop colliding with each other (filtered pairs);
  * no contacts but joint_6 lags     -> joint_6 drive made stiffer.
"""
import asyncio
import builtins
import importlib.util
import math
import os

# >>> dobot-settings (generated by tools/patch_paths.py; same block in every script)
def _dobot_settings():
    """Folders and settings: environment variables, else the repo's .env, else ~/.config/dobot-pnp/.env."""
    import os
    f = globals().get("__file__")
    src = os.path.dirname(os.path.abspath(f)) if f else ""
    vals = {}
    for c in (os.environ.get("DOBOT_ENV_FILE"), src and os.path.join(src, "..", ".env"),
              os.path.expanduser("~/.config/dobot-pnp/.env")):
        if not c or not os.path.isfile(c):
            continue
        with open(c) as fh:
            for line in fh:
                line = line.strip()
                if line.startswith("export "):
                    line = line[7:].strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                v = v.strip()
                if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
                    v = v[1:-1]
                else:
                    v = v.split(" #")[0].strip()
                vals[k.strip()] = v
        vals.setdefault("DOBOT_HOME", os.path.dirname(os.path.abspath(c)))
        break
    vals.update({k: v for k, v in os.environ.items() if k.startswith(("DOBOT_", "VLM_"))})
    home = os.path.expanduser(vals.get("DOBOT_HOME") or (os.path.dirname(src) if src else "~/dobot-vlm-pick-place"))

    def path(key, default):
        p = os.path.expanduser(vals.get(key) or default)
        return os.path.normpath(p if os.path.isabs(p) else os.path.join(home, p))
    vals["DOBOT_HOME"] = home
    vals["DOBOT_SRC"] = path("DOBOT_SRC", src or "src")
    vals["DOBOT_ASSETS"] = path("DOBOT_ASSETS", "assets")
    vals["DOBOT_DATA"] = path("DOBOT_DATA", ".")
    return vals


_DOBOT_ENV = _dobot_settings()
_DOBOT_SRC, _DOBOT_ASSETS, _DOBOT_DATA = _DOBOT_ENV["DOBOT_SRC"], _DOBOT_ENV["DOBOT_ASSETS"], _DOBOT_ENV["DOBOT_DATA"]
# <<< dobot-settings

DIAG = {
    "WRIST_FILE": os.path.join(_DOBOT_ASSETS, "dobot_wrist_level.py"),
    "POSES": [(35.2, 68.3), (37.7, 63.5)],    # joint_2, joint_5 (deg) where calibration got stuck
    "TRY_FIX": True,
    "STIFFNESS_GAIN": 10.0,
}


def _say(m):
    print(f"[WristDiag] {m}", flush=True)


def _load_wrist():
    path = DIAG["WRIST_FILE"]
    if not os.path.isfile(path):
        path = os.path.join(os.path.dirname(os.path.abspath(globals().get("__file__", path))), "dobot_wrist_level.py")
    spec = importlib.util.spec_from_file_location("dobot_run_wrist", path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


async def run():
    import omni.physx
    import omni.timeline
    import omni.usd
    from pxr import PhysicsSchemaTools, PhysxSchema, Sdf, Usd, UsdPhysics
    W = _load_wrist()
    cal = W.load_calib()
    if cal is None:
        _say("BLOCK: no dobot_wrist_calib.json; run dobot_wrist_level.py first")
        return
    stage = omni.usd.get_context().get_stage()
    cfg = W.WRIST
    arm = W.Arm(stage, cfg)
    robot = cfg["ROBOT_PRIM"]
    j6p = stage.GetPrimAtPath(arm.j["J6"]["path"])
    drive = UsdPhysics.DriveAPI(j6p, "angular")
    st0 = {k: (getattr(drive, f"Get{k}Attr")().Get()) for k in ("Stiffness", "Damping", "MaxForce")}
    _say(f"joint_6 drive: stiffness {st0['Stiffness']}, damping {st0['Damping']}, max force {st0['MaxForce']}")
    selfcol = []
    for p in Usd.PrimRange(stage.GetPrimAtPath(robot)):
        if p.HasAPI(PhysxSchema.PhysxArticulationAPI):
            a = PhysxSchema.PhysxArticulationAPI(p).GetEnabledSelfCollisionsAttr()
            selfcol.append((str(p.GetPath()), a.Get() if a else None))
    _say(f"articulation self-collisions: {selfcol or 'no PhysxArticulationAPI found (default: on)'}")

    # Report contacts of every robot link (in memory only).
    links = [str(p.GetPath()) for p in Usd.PrimRange(stage.GetPrimAtPath(robot))
             if p.HasAPI(UsdPhysics.RigidBodyAPI)]
    for l in links:
        api = PhysxSchema.PhysxContactReportAPI.Apply(stage.GetPrimAtPath(l))
        api.CreateThresholdAttr().Set(0.0)
    wrist_side = {cfg["EE_PRIM"], arm.j["J6"]["body1"], arm.j["J6"]["body0"]}
    seen = {}

    def on_contact(headers, *_):
        for h in headers:
            a0 = str(PhysicsSchemaTools.intToSdfPath(h.actor0))
            a1 = str(PhysicsSchemaTools.intToSdfPath(h.actor1))
            for x, y in ((a0, a1), (a1, a0)):
                if any(x == w or x.startswith(w + "/") for w in wrist_side if w):
                    seen[(x, y)] = seen.get((x, y), 0) + 1
    sub = omni.physx.get_physx_simulation_interface().subscribe_contact_report_events(on_contact)

    tl = omni.timeline.get_timeline_interface()
    builtins._DOBOT_WRIST_CALIBRATING = True        # keep the leveler out of the way while testing
    if not tl.is_playing():
        tl.play()
    await W._steps(30)

    async def test(label):
        out = []
        for q2, q5 in DIAG["POSES"]:
            seen.clear()
            await W._ramp(arm, {"J2": q2, "J5": q5}, 2.0)
            await W._settle(arm, 2.5)
            level = W.level_value(arm.angle("J2"), arm.angle("J5"), cal, arm.j["J6"]["lo"], arm.j["J6"]["hi"])
            seen.clear()
            await W._ramp(arm, {"J6": level}, 1.5)
            await W._settle(arm, 3.0)
            got = arm.angle("J6")
            err, _ = W.best_turn(arm.nozzle_world(), arm.j6_axis_world())
            pairs = sorted(seen.items(), key=lambda kv: -kv[1])
            _say(f"{label} joint_2 {q2:.1f} joint_5 {q5:.1f}: joint_6 target {level:.1f}, actual {got:.1f} "
                 f"(short by {level - got:+.1f}); cup {abs(err):.1f} deg off level in the arm plane")
            for (x, y), n in pairs[:6]:
                _say(f"    contact: {x}  <->  {y}  ({n} reports)")
            if not pairs:
                _say("    no contacts on the wrist / suction link")
            out.append((abs(err), pairs))
        return out

    before = await test("BEFORE")
    stuck = [r for r in before if r[0] > 1.0]
    if not stuck:
        _say("result: the wrist levels at these poses now; nothing to fix")
    elif DIAG["TRY_FIX"]:
        robot_pairs = {(x, y) for _, pairs in stuck for (x, y), _n in pairs
                       if any(y == l or y.startswith(l + "/") for l in links)}     # wrist touching the arm itself
        other = sorted({y for _, pairs in stuck for (x, y), _n in pairs} - {y for _, y in robot_pairs})
        if other and not robot_pairs:
            _say(f"result: the cup is pressing on {other} - the pose is too low, the cup is jammed against the "
                 "table / an object. Not a wrist problem; nothing to fix (calibration skips such poses).")
            builtins._DOBOT_WRIST_CALIBRATING = False
            _say("done. Stop the timeline (nothing was saved to the USD).")
            return
        if robot_pairs:
            for x, y in robot_pairs:
                bx = next(l for l in links if x == l or x.startswith(l + "/"))
                by = next(l for l in links if y == l or y.startswith(l + "/"))
                rel = UsdPhysics.FilteredPairsAPI.Apply(stage.GetPrimAtPath(bx)).CreateFilteredPairsRel()
                rel.AddTarget(Sdf.Path(by))
                _say(f"FIX (in memory): {bx} no longer collides with {by}")
        else:
            g = DIAG["STIFFNESS_GAIN"]
            drive.GetStiffnessAttr().Set(float(st0["Stiffness"] or 0) * g)
            drive.GetDampingAttr().Set(float(st0["Damping"] or 0) * g)
            if st0["MaxForce"] is not None and math.isfinite(float(st0["MaxForce"])):
                drive.GetMaxForceAttr().Set(float(st0["MaxForce"]) * g)
            _say(f"FIX (in memory): joint_6 drive x{g:g} stiffer (no contacts, so the drive was too weak)")
        await W._steps(10)
        after = await test("AFTER ")
        ok = all(r[0] <= 1.0 for r in after)
        _say("result: " + ("the fix works - send me these lines and I'll make it permanent in the run preparation"
                           if ok else "still not level after the fix - send me these lines"))
    builtins._DOBOT_WRIST_CALIBRATING = False
    sub = None
    _say("done. Stop the timeline (nothing was saved to the USD).")


builtins._DOBOT_WRIST_DIAG = asyncio.ensure_future(run())

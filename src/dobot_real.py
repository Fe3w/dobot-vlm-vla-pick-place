def colour_name(rgb):
    import colorsys
    r, g, b = [float(x) / 255.0 for x in rgb[:3]]
    hh, s, v = colorsys.rgb_to_hsv(r, g, b)
    if v < 0.16:
        return "black"
    if s < 0.22:
        return "white" if v > 0.78 else "grey"
    hue = hh * 360.0
    if hue < 15 or hue >= 345:
        return "red" if v > 0.35 else "dark red"
    for limit, name in ((40, "orange"), (70, "yellow"), (165, "green"), (200, "cyan"), (255, "blue"),
                        (290, "purple"), (345, "pink")):
        if hue < limit:
            return name
    return "red"


def _components(mask):
    """Connected components (4-neighbour) of a boolean grid -> label grid, count. OpenCV if present."""
    try:
        import cv2
        n, lab = cv2.connectedComponents(mask.astype(np.uint8), connectivity=4)
        return lab, n - 1
    except Exception:
        lab = np.zeros(mask.shape, int)
        n = 0
        for i, j in zip(*np.nonzero(mask)):
            if lab[i, j]:
                continue
            n += 1
            stack = [(i, j)]
            lab[i, j] = n
            while stack:
                a, b = stack.pop()
                for da, db in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    x, y = a + da, b + db
                    if 0 <= x < mask.shape[0] and 0 <= y < mask.shape[1] and mask[x, y] and not lab[x, y]:
                        lab[x, y] = n
                        stack.append((x, y))
        return lab, n


def _hull(P):
    P = np.unique(np.round(P, 3), axis=0)
    if len(P) < 3:
        return P
    P = P[np.lexsort((P[:, 1], P[:, 0]))]

    def half(pts):
        h = []
        for p in pts:
            while len(h) >= 2 and ((h[-1][0] - h[-2][0]) * (p[1] - h[-2][1])
                                   - (h[-1][1] - h[-2][1]) * (p[0] - h[-2][0])) <= 0:
                h.pop()
            h.append(p)
        return h[:-1]
    return np.array(half(P) + half(P[::-1]))


def _area(H):
    x, y = H[:, 0], H[:, 1]
    return 0.5 * abs(float(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1))))


def _min_rect(H):
    """Minimum-area rectangle of a convex hull: (center xy, (w, l) w <= l, yaw deg of the long side)."""
    best = None
    for i in range(len(H)):
        e = H[(i + 1) % len(H)] - H[i]
        a = math.atan2(e[1], e[0])
        R = np.array([[math.cos(a), math.sin(a)], [-math.sin(a), math.cos(a)]])
        Q = H @ R.T
        lo, hi = Q.min(0), Q.max(0)
        area = float(np.prod(hi - lo))
        if best is None or area < best[0]:
            c = R.T @ ((lo + hi) / 2)
            best = (area, c, hi - lo, a)
    _, c, ext, a = best
    w, l = sorted(ext)
    yaw = math.degrees(a) + (90.0 if ext[0] < ext[1] else 0.0)
    return c, (float(w), float(l)), (yaw + 90.0) % 180.0 - 90.0


def segment_scene(P_dobot, rgb, vs, us, table_z, cfg=REAL):
    """Objects on the table from a point grid in dobot mm (h, w, 3) with matching colour pixels.

    Returns (objects, info). Every object: name, colour, colour_rgb, shape, center_mm [x, y], size_mm [w, l, h],
    yaw_deg, pickable, bbox_px [u0, v0, u1, v1], points."""
    P = np.asarray(P_dobot, float)
    valid = np.isfinite(P).all(-1) & (np.abs(P).sum(-1) > 0)
    # table plane z = a x + b y + c from points near the calibrated table height (two trimmed passes)
    near = valid & (np.abs(P[..., 2] - table_z) < cfg["TABLE_BAND"])
    T = P[near]
    plane = np.array([0.0, 0.0, table_z])
    for _ in range(2):
        if len(T) < 50:
            break
        A = np.c_[T[:, 0], T[:, 1], np.ones(len(T))]
        plane = np.linalg.lstsq(A, T[:, 2], rcond=None)[0]
        r = T[:, 2] - A @ plane
        T = T[np.abs(r) < max(2.0, 2.5 * np.std(r))]
    h = P[..., 2] - (plane[0] * P[..., 0] + plane[1] * P[..., 1] + plane[2])
    rr = np.hypot(P[..., 0], P[..., 1])
    roi = valid & (rr >= cfg["ROI_R_MIN"]) & (rr <= cfg["ROI_R_MAX"])
    mask = roi & (h > cfg["MIN_HEIGHT"]) & (h < cfg["MAX_HEIGHT"] * 1.5)
    lab, n = _components(mask)
    objs, skipped = [], []
    for k in range(1, n + 1):
        m = lab == k
        if m.sum() < cfg["MIN_POINTS"]:
            continue
        pts, hk = P[m], h[m]
        top = float(np.percentile(hk, 99))
        if top > cfg["MAX_HEIGHT"]:
            skipped.append("too tall (arm or hand?)")
            continue
        if rr[m].min() < cfg["ROI_R_MIN"] + 4.0:
            skipped.append("touches the robot base")
            continue
        H = _hull(pts[:, :2])
        if len(H) < 3:
            continue
        c, (w, l), yaw = _min_rect(H)
        fill = _area(H) / max(w * l, 1e-9)
        round_ = fill < 0.90 and w / max(l, 1e-9) > 0.8
        # Seen from above, a flat-topped object is mostly top face; a sphere shows a smaller cap near its top
        # height and a cone almost none.
        flat = float(np.mean(hk > 0.85 * top))
        if round_ and flat < 0.2:
            shape = "cone"
        elif round_ and flat < 0.72:
            shape = "sphere"
        elif round_:
            shape = "cylinder"
        else:
            shape = "box"
        # round objects: the far side is partly hidden and the lowest MIN_HEIGHT is cut off -> use the larger
        # extent, and for a cone extend the measured width down to the table
        dr = l / max(1e-6, 1.0 - cfg["MIN_HEIGHT"] / top) if shape == "cone" else l
        topm = m & (h > 0.6 * top)
        col = np.median(rgb[vs[topm], us[topm]].reshape(-1, 3), axis=0) if topm.any() else np.array([128, 128, 128])
        cname = colour_name(col)
        uu, vv = us[m], vs[m]
        objs.append({"colour": cname, "colour_rgb": [int(x) for x in col], "shape": shape,
                     "center_mm": [round(float(c[0]), 1), round(float(c[1]), 1)],
                     "size_mm": [round(w, 1), round(l, 1), round(top, 1)] if not round_ else
                     [round(dr, 1), round(dr, 1), round(top, 1)],
                     "yaw_deg": round(0.0 if round_ else yaw, 1), "pickable": shape in ("box", "cylinder"),
                     "bbox_px": [int(uu.min()), int(vv.min()), int(uu.max()), int(vv.max())],
                     "points": int(m.sum())})
    objs.sort(key=lambda o: (o["bbox_px"][0] + o["bbox_px"][2]))
    count = {}
    for o in objs:
        count[(o["colour"], o["shape"])] = count.get((o["colour"], o["shape"]), 0) + 1
    seen = {}
    for o in objs:
        key = (o["colour"], o["shape"])
        seen[key] = seen.get(key, 0) + 1
        o["name"] = f"{o['colour']} {o['shape']}" + (f" {seen[key]}" if count[key] > 1 else "")
    return objs, {"table_plane": [float(x) for x in plane], "skipped": skipped}


_ROUND = {"cylinder", "sphere", "cone"}


def catalogue_entry(colour, round_, cfg=REAL):
    same = [e for e in cfg["OBJECTS"] if e.get("colour") == colour]
    if len(same) == 1:
        return same[0]            # one object of this colour: the catalogue says what it is (the shape guess from an
                                  # oblique photo is unreliable)
    fam = (lambda s: s in _ROUND) if round_ else (lambda s: s == "box")
    for e in cfg["OBJECTS"]:
        if e.get("colour") == colour and fam(e.get("shape", "box")):
            return e
    for e in cfg["OBJECTS"]:
        if "colour" not in e and fam(e.get("shape", "box")):
            return e
    return {"shape": "cylinder" if round_ else "box", "height_mm": cfg["DEFAULT_HEIGHT_MM"], "pickable": True}


_NEIGHBOURS = {"dark red": ["red"], "red": ["dark red"], "yellow": ["orange"], "orange": ["yellow"],
               "pink": ["red", "purple"], "cyan": ["blue", "green"], "purple": ["blue", "pink"]}
# Clear, saturated colours for the simulation stand-ins (the photo's measured colour is washed out by the light,
# and the VLM reads colours from the simulated picture).
_CANON_RGB = {"red": (0.85, 0.10, 0.08), "dark red": (0.55, 0.05, 0.05), "orange": (0.95, 0.50, 0.05),
              "yellow": (0.95, 0.85, 0.10), "green": (0.10, 0.70, 0.20), "cyan": (0.10, 0.75, 0.80),
              "blue": (0.10, 0.30, 0.90), "purple": (0.55, 0.20, 0.80), "pink": (0.95, 0.45, 0.70),
              "white": (0.92, 0.92, 0.92), "grey": (0.5, 0.5, 0.5), "black": (0.08, 0.08, 0.08)}


def catalogue_colour(cname, cfg=REAL):
    """The colour name to use for a detected blob, or None to drop it (not a listed object / grey shadow)."""
    listed = {e["colour"] for e in cfg["OBJECTS"] if e.get("colour")}
    if cname in listed:
        return cname
    for n in _NEIGHBOURS.get(cname, []):
        if n in listed:
            return n
    any_colour = any(not e.get("colour") for e in cfg["OBJECTS"])      # a line without colour = any colour
    if listed and cfg.get("CATALOGUE_ONLY", True) and not any_colour:
        return None
    return None if cname in cfg.get("IGNORE_COLOURS", ()) else cname


def segment_rgb(rgb, bg, calib, cfg=REAL):
    """Objects on the table from an RGB frame and a photo of the empty table, via the calibrated camera model.

    Same output as segment_scene; heights come from the OBJECTS catalogue."""
    import cv2
    if rgb.shape != bg.shape:
        raise ValueError(f"frame {rgb.shape[1]}x{rgb.shape[0]} differs from the background photo "
                         f"{bg.shape[1]}x{bg.shape[0]}: same camera resolution needed (retake `background`)")
    a = cv2.cvtColor(cv2.GaussianBlur(rgb, (5, 5), 0), cv2.COLOR_RGB2LAB).astype(np.float32)
    b = cv2.cvtColor(cv2.GaussianBlur(bg, (5, 5), 0), cv2.COLOR_RGB2LAB).astype(np.float32)
    dL = a[..., 0] - b[..., 0]
    dab = np.hypot(a[..., 1] - b[..., 1], a[..., 2] - b[..., 2])
    mask = (dab > cfg["RGB_AB_DIFF"]) | (dL > cfg["RGB_L_BRIGHTER"]) | (dL < -cfg["RGB_L_DARKER"])
    m8 = mask.astype(np.uint8) * 255
    m8 = cv2.morphologyEx(m8, cv2.MORPH_OPEN, np.ones((5, 5), np.uint8))
    m8 = cv2.morphologyEx(m8, cv2.MORPH_CLOSE, np.ones((7, 7), np.uint8))
    n, lab, stats, _ = cv2.connectedComponentsWithStats(m8, connectivity=8)
    table_z = float(calib["table_z_mm"])
    objs, skipped = [], []
    for k in range(1, n):
        if stats[k, cv2.CC_STAT_AREA] < cfg["RGB_MIN_AREA_PX"]:
            continue
        mk = (lab == k).astype(np.uint8)
        cs, _ = cv2.findContours(mk, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
        c = max(cs, key=cv2.contourArea)
        (_, (rw, rh), _) = cv2.minAreaRect(c)
        fill = cv2.contourArea(c) / max(rw * rh, 1.0)
        round_ = fill < 0.86
        inner = cv2.erode(mk, np.ones((5, 5), np.uint8))
        sel = inner.astype(bool) if inner.any() else mk.astype(bool)
        col = np.median(rgb[sel].reshape(-1, 3), axis=0)
        seen = colour_name(col)
        cname = catalogue_colour(seen, cfg)
        if cname is None:
            skipped.append(f"{seen} blob (not a listed object: shadow, arm, cable?)")
            continue
        entry = catalogue_entry(cname, round_, cfg)
        h = float(entry.get("height_mm", cfg["DEFAULT_HEIGHT_MM"]))
        pts = pixel_to_xy(calib, c[:, 0, :].astype(float), table_z + h)     # outline seen at the top face
        H = _hull(pts)
        if len(H) < 3:
            continue
        ctr, (w, l), yaw = _min_rect(H)
        r = float(np.hypot(*ctr))
        if not cfg["ROI_R_MIN"] <= r <= cfg["ROI_R_MAX"]:
            skipped.append(f"{cname} blob {r:.0f} mm from the base (outside the work area)")
            continue
        if not cfg["OBJECT_MIN_MM"] <= l <= cfg["OBJECT_MAX_MM"]:
            skipped.append(f"{cname} blob {l:.0f} mm long (not an object; the arm or a shadow?)")
            continue
        shape = entry.get("shape", "cylinder" if round_ else "box")
        x0, y0, bw, bh = cv2.boundingRect(c)
        poly = cv2.approxPolyDP(c, 2.0, True)[:, 0, :]
        objs.append({"outline_px": [[int(a), int(b)] for a, b in poly],
                     "colour": cname, "colour_rgb": [int(x) for x in col], "shape": shape,
                     "center_mm": [round(float(ctr[0]), 1), round(float(ctr[1]), 1)],
                     "size_mm": [round(l, 1), round(l, 1), round(h, 1)] if round_ else
                     [round(w, 1), round(l, 1), round(h, 1)],
                     "yaw_deg": 0.0 if round_ else round(yaw, 1),
                     "pickable": bool(entry.get("pickable", shape in ("box", "cylinder"))),
                     "bbox_px": [int(x0), int(y0), int(x0 + bw), int(y0 + bh)], "points": int(mk.sum()),
                     "height_from": "catalogue" if "height_mm" in entry else "default"})
    objs.sort(key=lambda o: o["bbox_px"][0] + o["bbox_px"][2])
    count, seen = {}, {}
    for o in objs:
        count[(o["colour"], o["shape"])] = count.get((o["colour"], o["shape"]), 0) + 1
    for o in objs:
        key = (o["colour"], o["shape"])
        seen[key] = seen.get(key, 0) + 1
        o["name"] = f"{o['colour']} {o['shape']}" + (f" {seen[key]}" if count[key] > 1 else "")
    return objs, {"skipped": skipped, "mask_px": int((m8 > 0).sum())}



def detect_all_markers_px(rgb, cfg=REAL):
    """Centres (u, v) of every calibration-dictionary marker in view (any id), left to right."""
    cv2, d = _aruco(cfg)
    gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY)
    try:
        corners, ids, _ = cv2.aruco.ArucoDetector(d, cv2.aruco.DetectorParameters()).detectMarkers(gray)
    except AttributeError:
        corners, ids, _ = cv2.aruco.detectMarkers(gray, d)
    if ids is None:
        return []
    return sorted([tuple(float(x) for x in c[0].mean(axis=0)) for c in corners], key=lambda p: (p[0], p[1]))



def cmd_view(cfg):
    """Live camera window. With calib + background: the demo view (estimated height map | photo with objects,
    reach ring and the latest checked plan), objects refreshed about once a second. q quits."""
    import cv2
    cam = open_camera(cfg)
    try:
        calib = load_calib(cfg)
    except Exception:
        calib = None
    bg = None
    if calib is not None and depth_free(cfg):
        try:
            bg = load_background(cfg)
        except Exception:
            bg = None
    V = _rgb_view() if bg is not None else None
    steps, task = None, ""
    if V is not None:
        try:
            _, plan, steps, _ = prepare_plan(cfg, force=True)
            task = plan.get("task") or ""
        except Exception:
            steps = None
    objs, last = [], 0.0
    _say("live view: press q in the window to quit" + ("" if V is not None else
         " (calibrate + background + `pip install pillow` for the full demo view)"))
    try:
        while True:
            rgb, _ = cam.grab(1)
            if bg is not None and time.time() - last > 1.0:
                try:
                    objs, _ = segment_rgb(rgb, bg, calib, cfg)
                except Exception as e:
                    objs = []
                    _say(f"detection: {e}")
                last = time.time()
            if V is not None:
                scan = {"objects": objs, "table_z_dobot_mm": calib["table_z_mm"]}
                img = cv2.cvtColor(V.render(rgb, scan, calib, steps=steps, title=f"plan: {task}" if steps else "live"),
                                   cv2.COLOR_RGB2BGR)
                if img.shape[1] > 1800:
                    img = cv2.resize(img, (1800, round(img.shape[0] * 1800 / img.shape[1])))
            else:
                img = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
                for o in objs:
                    u0, v0, u1, v1 = o["bbox_px"]
                    cv2.rectangle(img, (u0, v0), (u1, v1), (255, 255, 255), 2)
                    cv2.putText(img, f"{o['name']} {o['center_mm']}", (u0, max(15, v0 - 6)),
                                cv2.FONT_HERSHEY_SIMPLEX, 0.55, (255, 255, 255), 2)
            cv2.imshow("Dobot camera (q quits)", img)
            if cv2.waitKey(1) & 0xFF == ord("q"):
                break
    finally:
        cam.close()
        cv2.destroyAllWindows()
    return 0


def latest_plan(cfg):
    p = os.path.join(cfg["ROOT"], "latest_plan.json")
    if not os.path.isfile(p):
        raise RuntimeError("no simulated run to replay yet: run a task in Isaac Sim with 'Use real scene' ticked")
    with open(p) as f:
        return json.load(f)


def prepare_plan(cfg, force=False):
    calib = load_calib(cfg)
    plan = latest_plan(cfg)
    probs = []
    if not plan.get("check_passed"):
        probs.append("the simulated run did not pass its result check")
    age = time.time() - float(plan.get("created_epoch", 0))
    if age > cfg["MAX_PLAN_AGE_S"] and not force:
        probs.append(f"the plan is {age / 60:.0f} minutes old (use --force if the table is unchanged)")
    rows = load_motion_log(plan["motion_log"])
    steps = build_real_plan(rows, plan["frame"], calib, cfg)
    probs += check_plan(steps, calib, cfg)
    return calib, plan, steps, probs


def print_plan(plan, steps):
    _say(f"task: \"{plan.get('task')}\" (simulated {plan.get('created')}, scan {plan.get('scan_id')})")
    _say(f"result check in simulation: {plan.get('check_summary')}")
    moves = [s for s in steps if s[0] == "move"]
    _say(f"{len(moves)} moves:")
    for s in steps:
        if s[0] == "move":
            print(f"    {s[3]:18s} {s[2]:4s}  x {s[1][0]:7.1f}  y {s[1][1]:7.1f}  z {s[1][2]:7.1f}")
        else:
            print(f"    {s[2]}")


def cmd_plan(cfg, force=False):
    calib, plan, steps, probs = prepare_plan(cfg, force)
    print_plan(plan, steps)
    try:
        import cv2
        with open(plan["scan_path"]) as f:
            scan = json.load(f)
        rgb = cv2.cvtColor(cv2.imread(os.path.join(os.path.dirname(plan["scan_path"]), "rgb.png")), cv2.COLOR_BGR2RGB)
        out = os.path.join(os.path.dirname(plan["scan_path"]), "plan_view.png")
        if _save_view(out, rgb, scan, calib, steps, title=f"plan: {plan.get('task')}"):
            _say(f"picture of the plan: {out}")
    except Exception as e:
        _say(f"(no plan picture: {e})")
    for p in probs:
        _say(f"PROBLEM: {p}")
    _say("dry run only; nothing was moved" if not probs else "this plan would be refused by `execute`")
    return 0 if not probs else 1


def cmd_execute(cfg, force=False, yes=False):
    calib, plan, steps, probs = prepare_plan(cfg, force)
    print_plan(plan, steps)
    if probs:
        for p in probs:
            _say(f"REFUSED: {p}")
        return 1
    # the real table must still look like the scan the simulation planned on
    with open(plan["scan_path"]) as f:
        planned = json.load(f)
    now = do_scan(cfg, calib, save=False)
    diff = match_scenes(planned["objects"], now["objects"], cfg["MAX_OBJECT_SHIFT_MM"])
    if diff:
        for p in diff:
            _say(f"REFUSED: the table changed since the scan: {p}")
        return 1
    _say("table unchanged since the scan")
    if not yes and input("Move the REAL robot now? Keep a hand near its power switch. Type yes: ").strip().lower() != "yes":
        _say("cancelled")
        return 1
    rob = Robot(cfg)
    try:
        n = 0
        mode = None
        for s in steps:
            if s[0] == "move":
                want = s[2]
                if want != mode:
                    if n:
                        rob.move(last, True)          # finish queued moves before changing speed
                    rob.speed(*((cfg["SPEED"], cfg["ACCEL"]) if want == "fast" else (cfg["SLOW_SPEED"], cfg["SLOW_ACCEL"])))
                    mode = want
                n += 1
                last = s[1]
                rob.move(s[1], wait=(n % cfg["WAIT_EVERY"] == 0))
            elif s[0] == "suck":
                if n:
                    rob.move(last, True)
                rob.suck(s[1])
                _say(s[2])
            elif s[0] == "pause":
                time.sleep(float(s[1]))
        if n:
            rob.move(last, True)
        rob.speed(cfg["SPEED"], cfg["ACCEL"])
        rob.move(park_target(cfg, calib), True)          # back to the park pose: the next scan sees the table
        _say("done; check the object on the real table (arm parked)")
        return 0
    except KeyboardInterrupt:
        _say("STOP: clearing the robot's queue (suction is left as it was so nothing drops)")
        rob.stop()
        return 130
    finally:
        rob.close()


def cmd_export(cfg, force=False):
    """The latest checked plan as plain moves (JSON) for dobot_replay_windows.py (the Windows DobotDllType code)."""
    calib, plan, steps, probs = prepare_plan(cfg, force)
    print_plan(plan, steps)
    if probs:
        for p in probs:
            _say(f"REFUSED: {p}")
        return 1
    out = {"schema": "dobot.real_moves/1", "task": plan.get("task"), "created": time.strftime("%Y-%m-%d %H:%M:%S"),
           "scan_id": plan.get("scan_id"), "speed": [cfg["SPEED"], cfg["ACCEL"]],
           "slow_speed": [cfg["SLOW_SPEED"], cfg["SLOW_ACCEL"]], "park": park_target(cfg, calib), "steps": []}
    for st in steps:
        if st[0] == "move":
            out["steps"].append({"type": "move", "xyz": [round(float(v), 2) for v in st[1]], "speed": st[2],
                                 "label": st[3]})
        elif st[0] == "suck":
            out["steps"].append({"type": "suck", "on": bool(st[1]), "label": st[2]})
        elif st[0] == "pause":
            out["steps"].append({"type": "pause", "seconds": float(st[1]), "label": st[2]})
    path = os.path.join(cfg["ROOT"], "real_plan_moves.json")
    with open(path, "w") as f:
        json.dump(out, f, indent=2)
    _say(f"saved {path} ({sum(1 for x in out['steps'] if x['type'] == 'move')} moves). Copy it next to "
         f"dobot_replay_windows.py on the Windows laptop. Do not move the objects before it runs.")
    return 0


def cmd_park(cfg):
    calib = load_calib(cfg)
    p = park_target(cfg, calib)
    rob = Robot(cfg)
    try:
        rob.speed(cfg["SPEED"], cfg["ACCEL"])
        rob.move(p, True)
        _say(f"parked at {np.round(p, 1).tolist()}")
    finally:
        rob.close()
    return 0



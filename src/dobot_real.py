def check_parked(cfg, calib):
    """Refuse to scan with the arm away from the park pose: the background photo was taken with it parked, so
    the arm anywhere else shows up as objects. Uses the bridge if it runs (never opens the port itself)."""
    if not cfg.get("SCAN_REQUIRE_PARK", True):
        return
    try:
        L = _link_module()
        pose = L.BridgeClient(timeout=1.5).get_pose()
    except Exception:
        return                                             # no bridge: cannot tell; the user parks by hand
    d = float(np.linalg.norm(np.array(pose[:3]) - np.array(park_target(cfg, calib))))
    if d > cfg["PARK_TOL_MM"] and cfg.get("AUTO_PARK", True):
        _say(f"arm is {d:.0f} mm from its park pose; parking it before the scan")
        rob = Robot(cfg)
        try:
            rob.speed(cfg["SPEED"], cfg["ACCEL"])
            rob.move(park_target(cfg, calib), True)
            time.sleep(0.5)
            pose = rob.pose()
        finally:
            rob.close()
        d = float(np.linalg.norm(np.array(pose[:3]) - np.array(park_target(cfg, calib))))
    if d > cfg["PARK_TOL_MM"]:
        raise RuntimeError(f"the arm is {d:.0f} mm from its park pose; it would be seen as objects. Park it first: "
                           f"~/dobot_real/venv/bin/python src/dobot_real.py park")


def do_scan(cfg, calib, cam=None, save=True):
    if depth_free(cfg):
        check_parked(cfg, calib)
    own = cam is None
    cam = cam or open_camera(cfg)
    depth = None
    try:
        rgb, depth = cam.grab()
        if depth_free(cfg):
            if calib.get("model") not in ("projection", "homography"):
                raise RuntimeError("calib.json is from the depth camera; recalibrate with the phone")
            if list(calib.get("image_size") or []) != [rgb.shape[1], rgb.shape[0]]:
                raise RuntimeError(f"the phone sends {rgb.shape[1]}x{rgb.shape[0]} but was calibrated at "
                                   f"{calib.get('image_size')}: set the same resolution in the app")
            objs, info = segment_rgb(rgb, load_background(cfg), calib, cfg)
        else:
            K = calib.get("intrinsics") or cam.K
            Pc, vs, us = deproject(depth, K, cfg["STRIDE"])
            Pd = cam_to_dobot(Pc.reshape(-1, 3), calib).reshape(Pc.shape)
            Pd[depth[::cfg["STRIDE"], ::cfg["STRIDE"]] <= 0] = 0.0
            objs, info = segment_scene(Pd, rgb, vs, us, float(calib["table_z_mm"]), cfg)
    finally:
        if own:
            cam.close()
    scan = {"schema": "dobot.real_scene/1", "scan_id": time.strftime("%Y%m%dT%H%M%S"),
            "created": time.strftime("%Y-%m-%d %H:%M:%S"), "table_z_dobot_mm": float(calib["table_z_mm"]),
            "objects": objs, "info": info}
    if save:
        d = os.path.join(_root(cfg), "scans", scan["scan_id"])
        os.makedirs(d, exist_ok=True)
        if depth is not None:
            np.save(os.path.join(d, "depth_m.npy"), depth.astype(np.float32))
        try:
            import cv2
            img = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
            cv2.imwrite(os.path.join(d, "rgb.png"), img)
            for o in objs:
                u0, v0, u1, v1 = o["bbox_px"]
                cv2.rectangle(img, (u0, v0), (u1, v1), (255, 255, 255), 2)
                cv2.putText(img, o["name"], (u0, max(15, v0 - 6)), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 255, 255), 2)
            cv2.imwrite(os.path.join(d, "overlay.png"), img)
            if depth is None:
                _save_view(os.path.join(d, "view.png"), rgb, scan, calib, title=f"scan {scan['scan_id']}")
        except Exception:
            pass
        scan["dir"] = d
        with open(os.path.join(d, "real_scene.json"), "w") as f:
            json.dump(scan, f, indent=2)
        with open(os.path.join(cfg["ROOT"], "latest_scan.json"), "w") as f:
            json.dump({"scan_id": scan["scan_id"], "path": os.path.join(d, "real_scene.json")}, f)
    return scan



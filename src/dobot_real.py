def dobot_to_sim(p_mm, frame):
    """Dobot tip mm -> sim base frame m."""
    a = math.radians(frame.get("yaw_deg", 0.0))
    x, y, z = p_mm
    return [(math.cos(a) * x - math.sin(a) * y) / 1000.0, (math.sin(a) * x + math.cos(a) * y) / 1000.0,
            (z - frame["table_z_dobot_mm"]) / 1000.0 + frame["table_z_sim_base_m"]]


def sim_to_dobot(p_m, frame):
    a = math.radians(frame.get("yaw_deg", 0.0))
    x, y, z = [float(v) * 1000.0 for v in p_m[:3]]
    return [math.cos(a) * x + math.sin(a) * y, -math.sin(a) * x + math.cos(a) * y,
            z - frame["table_z_sim_base_m"] * 1000.0 + frame["table_z_dobot_mm"]]


_PRIM_TYPE = {"box": "Cube", "cylinder": "Cylinder", "cone": "Cone", "sphere": "Sphere"}


def proxy_specs(scene, frame, T_world_base):
    """Simulation stand-ins for the scanned objects: one prim spec per object (world frame, metres).

    Each prim sits directly under /World (the controller treats /World as the top of an object), shape with unit
    size scaled to the measured size, coloured like the real object, standing on the simulated table."""
    Tb = np.asarray(T_world_base, float)
    yaw_b = math.atan2(Tb[1, 0], Tb[0, 0])
    out, used = [], set()
    for o in scene["objects"]:
        w, l, h = [v / 1000.0 for v in o["size_mm"]]
        cx, cy = o["center_mm"]
        pb = np.array(dobot_to_sim([cx, cy, frame["table_z_dobot_mm"]], frame))
        pb[2] += h / 2.0 + 0.0005
        pw = Tb[:3, :3] @ pb + Tb[:3, 3]
        d = 0.5 * (w + l)
        scale = {"box": [l, w, h], "cylinder": [d, d, h], "cone": [d, d, h], "sphere": [d, d, d]}[o["shape"]]
        base = "real_" + "".join(ch if ch.isalnum() else "_" for ch in o["name"])
        name, k = base, 1
        while name in used:
            k += 1
            name = f"{base}_{k}"
        used.add(name)
        out.append({"path": f"/World/{name}", "type": _PRIM_TYPE[o["shape"]], "name": o["name"],
                    "translate": pw.tolist(), "yaw_rad": math.radians(o["yaw_deg"] + frame.get("yaw_deg", 0.0)) + yaw_b,
                    "scale": scale, "color": list(_CANON_RGB.get(o.get("colour"), [c / 255.0 for c in o["colour_rgb"]])),
                    "pickable": bool(o["pickable"])})
    return out


def rdp(P, tol):
    P = np.asarray(P, float)
    if len(P) < 3:
        return P
    a, b = P[0], P[-1]
    ab = b - a
    n = np.linalg.norm(ab)
    d = np.linalg.norm(np.cross(P - a, ab), axis=1) / n if n > 1e-9 else np.linalg.norm(P - a, axis=1)
    i = int(np.argmax(d))
    if d[i] <= tol:
        return np.array([a, b])
    return np.vstack([rdp(P[:i + 1], tol)[:-1], rdp(P[i:], tol)])


def load_motion_log(path):
    rows = []
    with open(path) as f:
        for r in csv.DictReader(f):
            rows.append({"t": float(r["sim_t"]), "move": r["move"], "latched": r["latched"] in ("1", "True"),
                         "cmd": [float(r["cmd_x"]), float(r["cmd_y"]), float(r["cmd_z"])],
                         "meas": [float(r["meas_x"]), float(r["meas_y"]), float(r["meas_z"])]})
    return rows


def build_real_plan(rows, frame, calib, cfg=REAL):
    """Steps for the real arm from a simulated run's motion log (sim base frame, mm).

    [("move", [x, y, z] reported-dobot mm, "fast"|"slow", label) | ("suck", bool, label) | ("pause", s, label)]"""
    on = next((i for i, r in enumerate(rows) if r["latched"]), None)
    if on is None:
        raise ValueError("the simulated run never picked the object up")
    off = next((i for i in range(on, len(rows)) if not rows[i]["latched"]), None)
    if off is None:
        raise ValueError("the simulated run never released the object")
    home = next((i for i in range(off, len(rows)) if "HOME" in rows[i]["move"].upper()), len(rows))
    b = float(calib["tool_radial_mm"])

    def D(p_mm_sim):                                     # sim base mm -> reported dobot mm
        return reported_from_tip(np.array(sim_to_dobot(np.asarray(p_mm_sim) / 1000.0, frame)), b).tolist()
    pick = np.array(rows[on]["meas"])                     # where the simulated cup actually touched the top
    carry = rdp([r["cmd"] for r in rows[on:off]], cfg["SIMPLIFY_MM"])
    retract = rdp([r["cmd"] for r in rows[off:home]], cfg["SIMPLIFY_MM"]) if home > off else np.zeros((0, 3))
    z_safe = max([p[2] for p in carry] + [p[2] for p in retract] + [pick[2] + cfg["HOVER_MM"]])
    steps = [("move", D([pick[0], pick[1], z_safe]), "fast", "above the object"),
             ("move", D(pick + [0, 0, cfg["HOVER_MM"]]), "fast", "hover"),
             ("move", D(pick - [0, 0, cfg["PRESS_MM"]]), "slow", "touch the object"),
             ("suck", True, "suction on"), ("pause", cfg["SUCK_SETTLE_S"], "grip")]
    for i, p in enumerate(carry[1:]):
        steps.append(("move", D(p), "slow" if i >= len(carry) - 3 else "fast", "carry"))
    steps += [("suck", False, "suction off"), ("pause", cfg["SUCK_SETTLE_S"], "let go")]
    for p in retract[1:]:
        steps.append(("move", D(p), "fast", "retract"))
    last = steps[-1][1] if steps[-1][0] == "move" else D(carry[-1])
    steps.append(("move", [last[0], last[1], max(last[2], D([0, 0, z_safe])[2])], "fast", "up"))
    return steps


def check_plan(steps, calib, cfg=REAL):
    """Problems that must stop the plan (positions outside the allowed workspace)."""
    out = []
    tz = float(calib["table_z_mm"])
    for k, s in enumerate(steps):
        if s[0] != "move":
            continue
        tip = tip_from_reported(np.array(s[1]), float(calib["tool_radial_mm"]))
        r = float(np.hypot(tip[0], tip[1]))
        if not cfg["LIMIT_R_MIN"] <= r <= cfg["LIMIT_R_MAX"]:
            out.append(f"step {k} ({s[3]}): radius {r:.0f} mm outside {cfg['LIMIT_R_MIN']:.0f}-{cfg['LIMIT_R_MAX']:.0f}")
        if tip[2] < tz - cfg["PRESS_MM"] - 3.0:
            out.append(f"step {k} ({s[3]}): {tz - tip[2]:.0f} mm below the table")
        if tip[2] > tz + cfg["LIMIT_Z_ABOVE_TABLE"]:
            out.append(f"step {k} ({s[3]}): {tip[2] - tz:.0f} mm above the table")
    return out


def match_scenes(a, b, max_shift):
    """Problems if objects in scan b are not where they were in scan a (nearest same-colour match; the shape
    guess can flip between photos, the colour does not)."""
    probs = []
    used = set()
    for o in a:
        cands = [(math.dist(o["center_mm"], q["center_mm"]), j) for j, q in enumerate(b) if j not in used
                 and q.get("colour", q["shape"]) == o.get("colour", o["shape"])]
        if not cands:
            probs.append(f"{o['name']} is gone")
            continue
        d, j = min(cands)
        used.add(j)
        if d > max_shift:
            probs.append(f"{o['name']} moved {d:.0f} mm")
    for j, q in enumerate(b):
        if j not in used:
            probs.append(f"new object: {q['name']}")
    return probs



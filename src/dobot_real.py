def kabsch(A, B):
    """R, t minimising |R a + t - b| over rows of A, B (n x 3)."""
    A, B = np.asarray(A, float), np.asarray(B, float)
    ca, cb = A.mean(0), B.mean(0)
    H = (A - ca).T @ (B - cb)
    U, _, Vt = np.linalg.svd(H)
    D = np.diag([1.0, 1.0, np.sign(np.linalg.det(Vt.T @ U.T))])
    R = Vt.T @ D @ U.T
    return R, cb - R @ ca


def radial(xy):
    xy = np.asarray(xy, float)
    n = np.linalg.norm(xy[..., :2], axis=-1, keepdims=True)
    return xy[..., :2] / np.maximum(n, 1e-9)


def tip_from_reported(p, b):
    """Real suction tip from the Dobot's reported position (tool offset b mm along the arm direction)."""
    p = np.array(p, float)
    p[..., :2] += b * radial(p)
    return p


def reported_from_tip(p, b):
    p = np.array(p, float)
    r = np.linalg.norm(p[..., :2], axis=-1, keepdims=True)
    p[..., :2] *= np.maximum(r - b, 1e-6) / np.maximum(r, 1e-9)
    return p


def fit_calibration(cam_pts, reported, cfg=REAL):
    """Camera -> dobot (tip) transform and tool offset from marker centres (camera, mm) touched by the tip
    (reported dobot positions, mm). Returns dict with R, t, tool_radial_mm, table_z_mm, rms_mm, residuals_mm."""
    cam_pts, reported = np.asarray(cam_pts, float), np.asarray(reported, float)
    if len(cam_pts) < 4:
        raise ValueError("need at least 4 calibration points")
    best = None
    lo, hi = cfg["TOOL_RADIAL_RANGE_MM"]
    for b in np.arange(lo, hi + 1e-9, 0.5):
        tips = tip_from_reported(reported, b)
        R, t = kabsch(cam_pts, tips)
        res = np.linalg.norm(cam_pts @ R.T + t - tips, axis=1)
        rms = float(np.sqrt(np.mean(res ** 2)))
        if best is None or rms < best[0]:
            best = (rms, b, R, t, res)
    rms, b, R, t, res = best
    tips = tip_from_reported(reported, b)
    return {"R": R.tolist(), "t": t.tolist(), "tool_radial_mm": float(b), "table_z_mm": float(np.median(tips[:, 2])),
            "rms_mm": rms, "residuals_mm": [round(float(x), 2) for x in res],
            "points": {"camera_mm": cam_pts.tolist(), "reported_mm": reported.tolist()}}


def _norm2(p):
    c = p.mean(0)
    s = math.sqrt(2) / max(float(np.mean(np.linalg.norm(p - c, axis=1))), 1e-9)
    return np.array([[s, 0, -s * c[0]], [0, s, -s * c[1]], [0, 0, 1.0]])


def _norm3(p):
    c = p.mean(0)
    s = math.sqrt(3) / max(float(np.mean(np.linalg.norm(p - c, axis=1))), 1e-9)
    T = np.eye(4)
    T[:3, :3] *= s
    T[:3, 3] = -s * c
    return T


def dlt_projection(world, pix):
    """3x4 camera matrix P (pixel ~ P [x y z 1]) from >= 6 points on at least two heights (normalised DLT)."""
    W, X = np.asarray(world, float), np.asarray(pix, float)
    Tx, Tw = _norm2(X), _norm3(W)
    Xn = np.c_[X, np.ones(len(X))] @ Tx.T
    Wn = np.c_[W, np.ones(len(W))] @ Tw.T
    A = []
    for (x, y, _), w in zip(Xn, Wn):
        A.append(np.r_[w, np.zeros(4), -x * w])
        A.append(np.r_[np.zeros(4), w, -y * w])
    P = np.linalg.inv(Tx) @ np.linalg.svd(np.array(A))[2][-1].reshape(3, 4) @ Tw
    return P / np.linalg.norm(P[2, :3])


def dlt_homography(pix, xy):
    """3x3 H mapping pixels to table x, y (>= 4 points on one plane; normalised DLT)."""
    X, Y = np.asarray(pix, float), np.asarray(xy, float)[:, :2]
    Tx, Ty = _norm2(X), _norm2(Y)
    Xn = np.c_[X, np.ones(len(X))] @ Tx.T
    Yn = np.c_[Y, np.ones(len(Y))] @ Ty.T
    A = []
    for x, y in zip(Xn, Yn):
        A.append(np.r_[x, np.zeros(3), -y[0] * x])
        A.append(np.r_[np.zeros(3), x, -y[1] * x])
    H = np.linalg.inv(Ty) @ np.linalg.svd(np.array(A))[2][-1].reshape(3, 3) @ Tx
    return H / H[2, 2]


def undistort_px(calib, uv):
    """Simple radial lens model (one coefficient k1, centre = image centre): camera pixels -> ideal pixels."""
    uv = np.atleast_2d(np.asarray(uv, float))
    k1 = float(calib.get("k1") or 0.0)
    if k1 == 0.0:
        return uv
    c, sc = np.asarray(calib["dist_center"], float), float(calib["dist_scale"])
    d = uv - c
    return c + d * (1.0 + k1 * np.sum((d / sc) ** 2, axis=1, keepdims=True))


def distort_px(calib, uv):
    """Inverse of undistort_px (fixed-point iteration)."""
    uv = np.atleast_2d(np.asarray(uv, float))
    k1 = float(calib.get("k1") or 0.0)
    if k1 == 0.0:
        return uv
    c, sc = np.asarray(calib["dist_center"], float), float(calib["dist_scale"])
    u = (uv - c) / sc
    ru = np.linalg.norm(u, axis=1)
    rmax = math.sqrt(-1.0 / (3.0 * k1)) if k1 < 0 else np.inf     # the model folds back beyond this radius
    rd = np.minimum(ru, 0.999 * rmax)
    for _ in range(25):                                            # Newton on rd * (1 + k1 rd^2) = ru
        f = rd * (1.0 + k1 * rd ** 2) - ru
        rd = np.clip(rd - f / (1.0 + 3.0 * k1 * rd ** 2), 0.0, 0.999 * rmax)
    scale = np.where(ru > 1e-12, rd / np.maximum(ru, 1e-12), 1.0)[:, None]
    return c + u * scale * sc


def pixel_to_xy(calib, uv, z):
    """Robot x, y (mm) of pixels uv (n, 2) on the horizontal plane at height z (mm)."""
    uv = undistort_px(calib, uv)
    if calib["model"] == "homography":
        h = np.c_[uv, np.ones(len(uv))] @ np.asarray(calib["H"], float).T
        return h[:, :2] / h[:, 2:3]
    P = np.asarray(calib["P"], float)
    u, v = uv[:, 0], uv[:, 1]
    a11, a12 = P[0, 0] - u * P[2, 0], P[0, 1] - u * P[2, 1]
    a21, a22 = P[1, 0] - v * P[2, 0], P[1, 1] - v * P[2, 1]
    b1 = u * (P[2, 2] * z + P[2, 3]) - (P[0, 2] * z + P[0, 3])
    b2 = v * (P[2, 2] * z + P[2, 3]) - (P[1, 2] * z + P[1, 3])
    det = a11 * a22 - a12 * a21
    return np.c_[(b1 * a22 - a12 * b2) / det, (a11 * b2 - a21 * b1) / det]


def xyz_to_pixel(calib, P_mm):
    P_mm = np.atleast_2d(np.asarray(P_mm, float))
    if calib["model"] == "homography":
        h = np.c_[P_mm[:, :2], np.ones(len(P_mm))] @ np.linalg.inv(np.asarray(calib["H"], float)).T
        return distort_px(calib, h[:, :2] / h[:, 2:3])
    else:
        h = np.c_[P_mm, np.ones(len(P_mm))] @ np.asarray(calib["P"], float).T
    return distort_px(calib, h[:, :2] / h[:, 2:3])


def fit_rgb_calibration(pix, reported, cfg=REAL, image_size=None):
    """Pixels of marker centres touched by the tip (reported dobot positions, mm) -> camera model + tool offset.

    Points on two heights (>= 6, height spread >= 15 mm): a full projection matrix, which also corrects the
    parallax of object tops. All on the table: a homography (table plane only)."""
    pix, reported = np.asarray(pix, float), np.asarray(reported, float)
    if len(pix) < 4:
        raise ValueError("need at least 4 calibration points")
    spread = float(np.ptp(reported[:, 2]))
    model = "projection" if (len(pix) >= 6 and spread >= 15.0) else "homography"
    fixed = cfg.get("TOOL_RADIAL_MM")
    lo, hi = cfg["TOOL_RADIAL_RANGE_MM"]
    grid = [float(fixed)] if fixed is not None else np.arange(lo, hi + 1e-9, 0.5)
    if image_size is None:
        image_size = (float(np.max(pix[:, 0])) * 1.1, float(np.max(pix[:, 1])) * 1.1)
    centre, scale = [image_size[0] / 2.0, image_size[1] / 2.0], image_size[0] / 2.0
    lens = cfg.get("LENS_K1", 0.0)
    k1s = [0.0]
    if lens == "auto" and len(pix) >= 8:
        k1s = [0.0] + [float(k) for k in np.arange(-0.40, 0.401, 0.02) if abs(k) > 1e-9]
    elif lens not in ("auto", None):
        k1s = [float(lens)]

    def fit(k1, b_grid):
        best = None
        for b in b_grid:
            tips = tip_from_reported(reported, b)
            cal = {"model": model, "k1": k1, "dist_center": centre, "dist_scale": scale}
            und = undistort_px(cal, pix)
            try:
                if model == "projection":
                    cal["P"] = dlt_projection(tips, und)
                else:
                    cal["H"] = dlt_homography(und, tips)
            except np.linalg.LinAlgError:
                continue
            xy = np.vstack([pixel_to_xy(cal, pix[i:i + 1], tips[i, 2]) for i in range(len(pix))])
            res = np.linalg.norm(xy - tips[:, :2], axis=1)
            rms = float(np.sqrt(np.mean(res ** 2)))
            if best is None or rms < best[0]:
                best = (rms, b, cal, res, tips)
        return best

    def loo(k1, b):
        """Leave-one-out error (mm): each point predicted by a model fitted without it. The camera matrix can
        absorb lens bending at the points it was fitted to, so only predicting held-out points shows it."""
        tips = tip_from_reported(reported, b)
        cal = {"model": model, "k1": k1, "dist_center": centre, "dist_scale": scale}
        und = undistort_px(cal, pix)
        errs = []
        for i in range(len(pix)):
            keep = np.arange(len(pix)) != i
            try:
                c2 = dict(cal, P=dlt_projection(tips[keep], und[keep]))
            except np.linalg.LinAlgError:
                return np.inf
            errs.append(np.linalg.norm(pixel_to_xy(c2, pix[i:i + 1], tips[i, 2])[0] - tips[i, :2]))
        return float(np.sqrt(np.mean(np.square(errs))))

    best0 = fit(0.0, grid)
    best = best0
    if len(k1s) > 1 and model == "projection" and best0 is not None:
        b0 = best0[1]
        scores = {k: loo(k, b0) for k in k1s}
        k_best = min(scores, key=scores.get)
        if k_best != 0.0 and scores[k_best] < 0.85 * scores[0.0]:   # the lens term must clearly help
            best = fit(k_best, grid) or best0
    rms, b, cal, res, tips = best
    z = tips[:, 2]
    table = float(np.median(z[z <= z.min() + 5.0]))
    px_err = np.linalg.norm(xyz_to_pixel(cal, tips) - pix, axis=1) if model == "projection" else None
    if model == "projection":
        cal["P"] = np.asarray(cal["P"], float)
    out = {"model": model, "tool_radial_mm": float(b), "table_z_mm": table, "rms_mm": rms,
           "k1": float(cal.get("k1") or 0.0), "dist_center": cal["dist_center"], "dist_scale": cal["dist_scale"],
           "residuals_mm": [round(float(x), 2) for x in res],
           "points": {"pixel": pix.tolist(), "reported_mm": reported.tolist()}}
    if model == "projection":
        out["P"] = cal["P"].tolist()
        out["rms_px"] = float(np.sqrt(np.mean(px_err ** 2)))
        M = cal["P"][:, :3]
        out["camera_position_mm"] = (-np.linalg.solve(M, cal["P"][:, 3])).round(1).tolist()
    else:
        out["H"] = cal["H"].tolist()
    return out


def cam_to_dobot(P, calib):
    R, t = np.asarray(calib["R"], float), np.asarray(calib["t"], float)
    return np.asarray(P, float) @ R.T + t


def deproject(depth_m, K, stride=1):
    """Pinhole back-projection of a depth image (metres) -> (h, w, 3) camera points in mm, (v, u) grids."""
    d = depth_m[::stride, ::stride].astype(float) * 1000.0
    vs, us = np.mgrid[0:depth_m.shape[0]:stride, 0:depth_m.shape[1]:stride]
    x = (us - K["cx"]) / K["fx"] * d
    y = (vs - K["cy"]) / K["fy"] * d
    return np.stack([x, y, d], axis=-1), vs, us



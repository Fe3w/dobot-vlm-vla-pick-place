def cmd_hovertest(cfg):
    """Accuracy test without Isaac Sim: scan, then hover the cup HOVERTEST_MM above each object's top centre."""
    calib = load_calib(cfg)
    scan = do_scan(cfg, calib)
    objs = scan["objects"]
    if not objs:
        _say("no objects found (background photo up to date? objects inside the reach area?)")
        return 2
    b, tz = float(calib["tool_radial_mm"]), float(calib["table_z_mm"])
    z_safe = tz + cfg["HOVERTEST_SAFE_MM"]
    rob = Robot(cfg)
    try:
        rob.speed(cfg["SLOW_SPEED"] * 2, cfg["SLOW_ACCEL"] * 2)
        _say(f"{len(objs)} objects: " + ", ".join(f"{o['name']} at {o['center_mm']} mm" for o in objs)
             + f". Picture: {scan['dir']}/view.png. The arm moves at {cfg['SLOW_SPEED'] * 2:.0f} mm/s; hand on the "
               "power switch.")
        for o in objs:
            cx, cy = o["center_mm"]
            top = tz + float(o["size_mm"][2])
            above = reported_from_tip(np.array([cx, cy, z_safe]), b).tolist()
            hover = reported_from_tip(np.array([cx, cy, top + cfg["HOVERTEST_MM"]]), b).tolist()
            probs = check_plan([("move", above, "slow", "above"), ("move", hover, "slow", "hover")], calib, cfg)
            if probs:
                _say(f"{o['name']}: skipped ({probs[0]})")
                continue
            a = input(f"\nHover over {o['name']} (top at {top - tz:.0f} mm above the table, from the "
                      f"{o.get('height_from', 'catalogue')})? Enter = go, s = skip, q = quit: ").strip().lower()
            if a.startswith("q"):
                break
            if a.startswith("s"):
                continue
            p = rob.pose()
            rob.move([p[0], p[1], max(p[2], above[2])], True)     # straight up first
            rob.move(above, True)
            rob.move(hover, True)
            input(f"The cup should be {cfg['HOVERTEST_MM']:.0f} mm above the CENTRE of the {o['name']}'s top. Note how "
                  "far off it is (mm, which direction), then press Enter to go back up ...")
            rob.move(above, True)
        _say("hover test done. Off by more than ~5 mm: redo calibration with more markers where the objects are.")
        return 0
    except KeyboardInterrupt:
        _say("STOP")
        rob.stop()
        return 130
    finally:
        rob.close()



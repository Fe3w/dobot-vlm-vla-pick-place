class Camera:
    def __init__(self, cfg=REAL):
        import pyrealsense2 as rs
        self.rs, self.cfg = rs, cfg
        self.pipe = rs.pipeline()
        c = rs.config()
        c.enable_stream(rs.stream.depth, cfg["WIDTH"], cfg["HEIGHT"], rs.format.z16, cfg["FPS"])
        c.enable_stream(rs.stream.color, cfg["WIDTH"], cfg["HEIGHT"], rs.format.rgb8, cfg["FPS"])
        prof = self.pipe.start(c)
        self.depth_scale = prof.get_device().first_depth_sensor().get_depth_scale()
        self.align = rs.align(rs.stream.color)
        intr = prof.get_stream(rs.stream.color).as_video_stream_profile().get_intrinsics()
        self.K = {"fx": intr.fx, "fy": intr.fy, "cx": intr.ppx, "cy": intr.ppy, "width": intr.width,
                  "height": intr.height, "model": str(intr.model), "coeffs": list(intr.coeffs)}
        self.name = prof.get_device().get_info(rs.camera_info.name)
        for _ in range(30):                              # auto-exposure settles
            self.pipe.wait_for_frames()

    def grab(self, n=None):
        """(rgb uint8 HxWx3, depth metres HxW median of n aligned frames)."""
        n = n or self.cfg["SCAN_FRAMES"]
        ds, rgb = [], None
        for _ in range(n):
            f = self.align.process(self.pipe.wait_for_frames())
            d, c = f.get_depth_frame(), f.get_color_frame()
            if not d or not c:
                continue
            ds.append(np.asanyarray(d.get_data()).astype(np.float32) * self.depth_scale)
            rgb = np.asanyarray(c.get_data()).copy()
        D = np.stack(ds)
        D[D <= 0] = np.nan
        with np.errstate(all="ignore"):
            depth = np.nanmedian(D, axis=0)
        return rgb, np.nan_to_num(depth, nan=0.0)

    def close(self):
        try:
            self.pipe.stop()
        except Exception:
            pass


class PhoneCamera:
    """A phone running an IP-camera app. Snapshot URLs (.jpg) are fetched; stream URLs are read with OpenCV."""

    def __init__(self, cfg=REAL):
        self.cfg, self.url = cfg, cfg["PHONE_URL"]
        if not self.url:
            raise RuntimeError("set REAL['PHONE_URL'] to the address the phone app shows")
        self.name = f"phone camera at {self.url}"
        self.K = None
        self._cap = None

    def _one(self):
        last = None
        for attempt in range(4):                     # the phone sometimes misses a request: try again
            try:
                return self._one_try()
            except Exception as e:
                last = e
                time.sleep(0.4 * (attempt + 1))
        raise last

    def _one_try(self):
        import cv2
        if self.url.lower().split("?")[0].endswith((".jpg", ".jpeg")):
            import urllib.request
            opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))      # local network: no proxy
            data = opener.open(self.url, timeout=self.cfg["PHONE_TIMEOUT_S"]).read()
            img = cv2.imdecode(np.frombuffer(data, np.uint8), cv2.IMREAD_COLOR)
        else:
            if self._cap is None:
                self._cap = cv2.VideoCapture(self.url)
            for _ in range(4):                       # drop buffered (old) frames
                self._cap.grab()
            ok, img = self._cap.read()
            if not ok:
                img = None
        if img is None:
            raise RuntimeError(f"no image from {self.url} (is the camera app running, same Wi-Fi/hotspot?)")
        return cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

    def grab(self, n=None):
        frames = [self._one() for _ in range(n or self.cfg["PHONE_FRAMES"])]
        if len({f.shape for f in frames}) != 1:
            raise RuntimeError("the phone changed resolution between frames")
        return np.median(np.stack(frames), axis=0).astype(np.uint8), None

    def close(self):
        if self._cap is not None:
            self._cap.release()
            self._cap = None



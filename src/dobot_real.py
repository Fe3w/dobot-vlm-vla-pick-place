def _aruco(cfg):
    import cv2
    d = cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, cfg["ARUCO_DICT"]))
    return cv2, d


def detect_marker_px(rgb, cfg=REAL):
    """Pixel (u, v) of the calibration marker's centre, or None."""
    cv2, d = _aruco(cfg)
    gray = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY)
    try:
        corners, ids, _ = cv2.aruco.ArucoDetector(d, cv2.aruco.DetectorParameters()).detectMarkers(gray)
    except AttributeError:
        corners, ids, _ = cv2.aruco.detectMarkers(gray, d)
    if ids is None:
        return None
    for c, i in zip(corners, ids.flatten()):
        if int(i) == cfg["MARKER_ID"]:
            u, v = c[0].mean(axis=0)
            return float(u), float(v)
    return None


def detect_marker(rgb, depth, K, cfg=REAL):
    """Marker centre in camera mm (RealSense), or None."""
    uv = detect_marker_px(rgb, cfg)
    if uv is not None:
        u, v = uv
        ui, vi = int(round(u)), int(round(v))
        win = depth[max(0, vi - 3):vi + 4, max(0, ui - 3):ui + 4]
        z = float(np.median(win[win > 0])) * 1000.0 if (win > 0).any() else 0.0
        if z <= 0:
            return None
        return np.array([(u - K["cx"]) / K["fx"] * z, (v - K["cy"]) / K["fy"] * z, z]), (float(u), float(v))
    return None



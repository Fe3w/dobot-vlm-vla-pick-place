class Robot:
    """The Dobot through dobot_link: its bridge if running (it owns the serial port), else USB serial directly."""

    def __init__(self, cfg=REAL):
        dl = _link_module()
        lcfg = dict(dl.LINK)
        if cfg.get("PORT"):
            lcfg["PORT"] = cfg["PORT"]
        self.dev = dl.bridge_or_direct(lcfg)
        self.port = self.dev.port
        self.cfg = cfg
        self._r = None

    def pose(self):
        return list(self.dev.get_pose())

    def speed(self, v, a):
        self.dev.speed(v, a)

    def move(self, p, wait):
        if self._r is None:
            self._r = float(self.pose()[3])             # keep the end rotation as it is
        x, y, z = (float(v) for v in p)
        self.dev.ptp(x, y, z, self._r, mode=self.cfg.get("PTP_MODE", "MOVL_XYZ"), wait=wait)

    def suck(self, on):
        self.dev.suction(bool(on), wait=True)

    def stop(self):
        self.dev.stop_now()

    def close(self):
        self.dev.close()


